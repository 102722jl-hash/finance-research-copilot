# 关系判据.py —— v5 第 21 讲（补）：外源数据题的「无标准答案」判据
#
# 【为什么需要这个文件（要解决的真问题）】
#   现有 `溯源` 检查的是**存在性**：答案里的数字在工具原文里能不能字面找到。
#   但 2026-10-16 的真实事故证明这层不够：
#     题目「苏州有多少家上市公司」→ 官方（苏州市政府，截至 2026-08-21）**297 家 / A股 236 家**；
#     系统答 **295 家 / A股 235 家**（来自 2026 年 6 月末口径的另一篇报道），却挂了官方发布日期。
#     原文里 284/295/297/235/236 **全都在**（不同时点、不同来源），
#     所以存在性校验 100% 放行，`无支撑断言率 = 0` —— 报告一片绿，答案是错的。
#
#   ⇒ 错误发生在「**选哪一个**」这一层，而检查停在「**有没有**」这一层。层次错配。
#
# 【方法：蜕变关系（metamorphic relation）】
#   外源数据没有「标准答案」（互联网无穷大，不可能穷举），但**系统两次输出之间必须满足某些关系**。
#   违反关系 ⇒ 至少有一次是错的 —— **不需要知道哪次错，就能发现出错**。
#   这在测试理论里叫「无 oracle 测试」，是评测"有依据但不准确"这类错的唯一可行手段。
#
# 【三条纪律】
#   ① **纯函数**：不联网、不调 LLM、不读库 → 可以用合成夹具做确定性单测（免费、必跑）。
#      端到端真跑是另一回事，不能拿它当证据（见 `agent-eval-no-ground-truth` 第六节）。
#   ② **宁可不判，不可误判**：拿不到判据（没时点、原文没分块、单位对不上）就返回「跳过」，
#      绝不猜。假阳性会让人去"修一个不存在的问题"，比漏报更贵。
#   ③ **只判关系，不判事实**：本文件永远不出现「297 才是对的」这种期望值。
#      它只知道"数字和它的时点必须出自同一块"——换任何一个城市、任何一年都成立。
#
# 【口径陷阱（实测踩过，写死在这里）】
#   「境内外 = A股 + 境外」**不成立**：A+H 两地上市的公司会被两边各算一次
#   （苏州官方原文：境内外 297、A股 236，差 61；但"境外上市公司 63 家" —— 63 > 61）。
#   所以**不要**做 X − Y = Z 的算术校验，那会产生大量假阳性。
#   只做两条**零假阳性**的弱校验：同标签不得两个值、分项不得大于合计。

import re

# ── 数字与单位 ──────────────────────────────────────────────
# ⚠️ 只认「数字 + 计量单位」，**不认裸数字** —— 否则年份（2026）、序号（1.）、
#    页码都会被当成指标，制造一堆假阳性。实测：把裸数字放进来，一条答案能抽出 20+ 个"数"。
_量 = re.compile(r"(\d[\d,]*(?:\.\d+)?)\s*(家|只|个|亿元|亿|万元|万|%|倍)")

# ── 时点 ──────────────────────────────────────────────────
# 三种写法都要认：`2026-08-25` / `2026年8月21日` / `截至8月21日`（无年份）
_时点带年 = re.compile(r"(\d{4})\s*[-/年]\s*(\d{1,2})\s*[-/月]\s*(\d{1,2})\s*日?")
_时点无年 = re.compile(r"截至\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日")
# ⚠️ 只有年月、没有日：「2026年6月末」——这种**必须认**，否则引用性旧值会被错配时点。
#    实测：答案里写「此前2026年6月末为295家」时，若认不出 6 月这个时点，
#    295 就会被配到最近的前一个时点（官方的 8-25）上 → **正确答法被判跨块混搭**（假阳性）。
_时点年月 = re.compile(r"(\d{4})\s*年\s*(\d{1,2})\s*月(?!\s*[\d日])")
# ⚠️ 第四种：**紧凑 8 位数字** `20260630`。
#    AKShare 的 `报告日` 列就是这个格式（`stock_financial_report_sina`），
#    于是 `macro_mcp_server._概览()` 返回的是 `（利润表｜20260630）`。
#    必须认，否则会出这个**反向事故**（2026-10-19 实测）：
#      工具给 `20260630` → 模型规规矩矩转述成「截至 2026年6月30日」
#      → 溯源在来源块里找不到这个时点 → 判「时点无出处」→ **把正确答案整条拦掉**。
#      即：**模型越诚实标时点，越会被拦**（「中国银行最新财报情况」就是这么被误杀的）。
#    防误判：月 1~12、日 1~31 才认；前后不能紧邻数字
#      （`1032905000000` 这种金额是连续 13 位，切不出前后都无数字的 8 位段）。
_时点紧凑 = re.compile(r"(?<!\d)(\d{4})(\d{2})(\d{2})(?!\d)")

# ── 分块 ──────────────────────────────────────────────────
# 优先认显式块标记 `【#3 ｜ 2026-08-25 ｜ 来源】`；退化为 web_search 现有的 `1. 标题` 编号行。
_块显式 = re.compile(r"【#\d+[^】]*】")
_块编号 = re.compile(r"(?m)^\s*\d+\.\s+")

# 口径归类用的噪声词：这些不该进标签
_噪声 = ("其中", "共", "达", "为", "约", "近", "已", "有", "是", "大约", "合计为", "，", "、", "：", ":", "（", "(")


def _数值(串: str) -> float:
    return float(串.replace(",", ""))


def 抽数(文本: str) -> list[tuple[float, str]]:
    """抽「数字+单位」，返回 (数值, 原串)。原串留着给人看证据。"""
    return [(_数值(m.group(1)), m.group(0).replace(" ", "")) for m in _量.finditer(文本 or "")]


def 抽时点(文本: str) -> list[tuple[int, int, int, str]]:
    """抽时点，返回 [(年, 月, 日, 原串)]，按出现顺序。只有年月的记 日=0。

    ⚠️ 无年份的「截至8月21日」记 年=0 —— 排序时会被当"最旧"，
       所以比较**时点先后**前必须先确认两边年都 > 0，否则返回"不可比"。
       （这是刻意保守：拿不准就不判，别误杀。）
    """
    候选 = []
    for m in _时点带年.finditer(文本 or ""):
        候选.append((m.start(), (int(m.group(1)), int(m.group(2)), int(m.group(3)), m.group(0))))
    for m in _时点年月.finditer(文本 or ""):
        候选.append((m.start(), (int(m.group(1)), int(m.group(2)), 0, m.group(0))))
    for m in _时点无年.finditer(文本 or ""):
        候选.append((m.start(), (0, int(m.group(1)), int(m.group(2)), m.group(0))))
    # 紧凑 8 位（`20260630`）—— 带月日合法性校验，避免把 8 位金额当日期
    for m in _时点紧凑.finditer(文本 or ""):
        月, 日 = int(m.group(2)), int(m.group(3))
        if 1 <= 月 <= 12 and 1 <= 日 <= 31:
            候选.append((m.start(), (int(m.group(1)), 月, 日, m.group(0))))
    # 按在原文里出现的位置排序（三种正则分开跑，得重新按位置排）
    候选.sort(key=lambda x: x[0])
    return [v for _, v in 候选]


def _时点键(t) -> tuple[int, int, int]:
    return (t[0], t[1], t[2])


def _时点可比(a, b) -> bool:
    """两边都有年份才可比。无年份的那次「截至8月21日」不知道是哪一年，拒绝比较。"""
    return a[0] > 0 and b[0] > 0


def _是检索列表(文本: str) -> bool:
    """行首 `N. ` 到底是不是 web_search 的检索结果列表？

    判据：至少 2 个块带 `来源：http…`（`search_mcp_server` 每条结果的固定行）。

    ⚠️ 2026-10-20 实测事故（「宝钢股份的十大流通股东有哪些？」）：
       `查股东` 返回的是一张**表**，每行形如 `1. 中国宝武钢铁集团…｜持股 96.28 亿股`。
       `_块编号` 把 11 行切成 11 个"来源块" → 报告期「2026中报」只落在块1，
       而所有数字都在块2~11 → 判「96.28亿 配 2026-06-30 找不到同一块来源」
       → **一条完全正确的股东表被整条硬拦成【无法回答】**。
       ⇒ 行首编号 + 表格分隔符（｜/|）≠ 多篇检索结果，必须区分开。
    """
    return len(re.findall(r"(?m)^\s*来源[:：]\s*https?://", 文本 or "")) >= 2


def 分块(原文: str) -> list[str]:
    """把 web_search 的输出切成"来源块"。每块 = 一条检索结果。"""
    文本 = 原文 or ""
    if _块显式.search(文本):
        片 = _块显式.split(文本)
    elif _块编号.search(文本) and _是检索列表(文本):
        片 = _块编号.split(文本)
    else:
        return []
    # 第一片通常是表头（「共 N 条」），丢掉；其余非空的才算块。
    # ⚠️ 但**不能无条件丢**：真实原文常常是「工具A的输出 + web_search 的编号列表」拼起来的，
    #    工具 A 那一段（例如 `query_public_financials` 的关键科目概览，**报告期就写在这里**）
    #    正好落在片[0] 里。无条件丢掉 = 让工具 A 的时点彻底消失在判据视野里。
    #    实测事故（2026-10-19，「中国银行最新财报情况」）：
    #      答案规规矩矩写「截至 2026年6月30日」，而 `2026-06-30` / `20260630` 只出现在片[0]（概览）里
    #      → 判「主时点在所有来源块里都找不到（时点无出处）」→ **正确答案被整条硬拦**。
    #    ⇒ 片[0] 只要"像正文"（够长、且不是「共 N 条」这种纯表头）就保留成一块。
    #      这一步只会让判据**更宽松**（多一块可命中），不会制造新的误拦。
    头 = 片[0].strip() if 片 else ""
    结果 = [p.strip() for p in 片[1:] if p.strip()]
    if (len(头) > 40
            and not re.fullmatch(r"(共|找到|检索到|返回)?\s*[约]?\s*\d+\s*(条|个|篇).*", 头)
            and not re.fullmatch(r"[^\n]{0,20}结果[^\n]{0,20}", 头)):
        结果.insert(0, 头)
    return 结果


def _口径(窗口: str) -> str:
    """把一个「数字前面的文字窗口」归成口径类别。归类失败就返回最后 4 个字。"""
    s = 窗口
    for w in _噪声:
        s = s.replace(w, "")
    s = s.strip(" \t-—>·")
    if any(k in s for k in ("境内外", "总数", "合计", "总计", "全市共")):
        return "合计口径"
    if "A股" in s or "A 股" in s:
        return "A股口径"
    if "境外" in s or "海外" in s:
        return "境外口径"
    if "境内" in s:
        return "境内口径"
    return s[-4:] or "未标注口径"


def 抽家数(文本: str) -> list[tuple[str, float, str]]:
    """抽「带口径标签的家数」，返回 (口径, 数值, 原串)。

    窗口取数字前 12 个字 —— 太短抓不到"境内外"，太长会把上一句的口径串进来。
    实测：取 12 字时「境内外上市公司总数达297家」归到"合计口径"正确。
    """
    出 = []
    for m in re.finditer(r"(\d[\d,]*(?:\.\d+)?)\s*家", 文本 or ""):
        起 = max(0, m.start() - 12)
        窗口 = (文本 or "")[起:m.start()]
        # ⚠️ 必须在**最后一个标点处截断**：否则窗口会跨到上一句去。
        #    实测：「境内外297家，其中A股236家」→ 取 12 字窗口时，
        #    236 的窗口是「境内外297家，其中A股」→ 被误归成"合计口径"，
        #    于是「分项不超合计」永远认不出分项（自演示第 5 条被跳过就是它）。
        # ⚠️ 冒号**不能**当切点：它是「标签：数值」的分隔符，切掉就把标签丢了
        #    （实测：「境内外上市公司总数：297家」被切成空窗口 → 归为"未标注口径"，
        #      于是「口径唯一」把 297/236 误判成同口径多值）。
        切点 = [窗口.rfind(p) for p in "，。；、,;\n…"]
        切 = max(切点)
        if 切 >= 0:
            窗口 = 窗口[切 + 1:]
        窗口 = 窗口.rstrip("：: ")   # 「境内外上市公司总数：」→ 去掉尾冒号，标签才留下
        出.append((_口径(窗口), _数值(m.group(1)), m.group(0).replace(" ", "")))
    return 出


