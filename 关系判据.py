# 四条判据（对外只暴露 `判`）
# ══════════════════════════════════════════════════════════════
def _归一(文本: str) -> str:
    """归一化：去空格 / 去 markdown 星号 / 去千分位逗号 / 去中文逗号。

    ⚠️ 这个是踩出来的必需品：答案里写「297 家」（中间有空格）、
       而 `抽数` 抽出的原串已经被 `.replace(" ", "")` 成「297家」，
       于是 `答案.find("297家")` 返回 **-1** → 配对时点取错 → **正确答法被判跨块**。
       所有"在文本里定位"的动作，一律先归一化再做。
    """
    s = 文本 or ""
    for c in (" ", "\u3000", "\t", "*", ",", "，", "\n", "\r"):
        s = s.replace(c, "")
    return s


def _句们(答案: str) -> list[str]:
    """按行和句末标点切成"句"，丢掉空片。"""
    import re as _re
    return [p.strip() for p in _re.split(r"(?<=[。；!?！？])|\n", 答案 or "") if p and p.strip()]


def 分段(答案: str) -> list[tuple[tuple | None, str]]:
    """把答案切成 [(段时点, 句子)] —— **每句配自己的时点**，没有就继承上一句。

    【为什么必须分段（这是本轮最大的一个假阳性来源）】
      好答案会**合法引用旧值做对比**：「截至8月21日…297家 / A股236家（此前 2026年6月末
      为 295 家 / 235 家）」。若按全文取"最近的前一个时点"，
      295 会被配到 8-25 上 → 判成跨块混搭 → **把正确答法判红**（实测踩到过）。
      分段之后：297 属于「8-21 段」、295 属于「6 月段」，各判各的，互不干扰。
    """
    出 = []
    当前 = None
    for 句 in _句们(答案):
        时 = 抽时点(句)
        if 时:
            当前 = 时[-1]
        出.append((当前, 句))
    return 出


def 主段(答案: str) -> tuple[tuple | None, str]:
    """答案里**时点最新**的那一段（= 主结论所在段）。没有时点则返回 (None, 全文)。"""
    段们 = [(t, s) for t, s in 分段(答案) if t]
    if not 段们:
        return None, (答案 or "")
    return max(段们, key=lambda x: _时点键(x[0]))


def 同源同组(答案: str, 原文: str, 只判主口径: bool = False) -> str:
    """判据 1：答案里的数字，必须和**它所在那一段**的时点出自同一块来源。

    这是抓 2026-10-16 那次事故的核心判据：
      「境内外295家、A股235家」+「官方 2026-08-25」——295 根本不在官方那一块里，
        它是从另一篇（6 月末口径）搬过来的。跨块配对 = 混搭 = 错。

    规则（按句分段后逐个数字判）：
      · 段时点在**原文里根本找不到**（如引用了原文没给日期的"6 月末"）→ **跳过**，不判；
        （不判是因为无从核对；判了就是假阳性）
      · 段时点在原文某几块里出现 → 该数字必须出现在**其中一块**，否则 ❌ 跨块配对。

    `只判主口径=True`（**硬拦截专用**）：只对「合计口径 / A股口径 的家数」判违例，
      其余（创业板/科创板/北交所等结构分项、以及亿元/%等其它量）一律跳过。

    ⚠️ 为什么要这个开关（实测假阳性）：
      答案主结论「境内外 297 家 / A股 236 家（截至 8-21）」完全正确，但同一段后面
      还列了「创业板 69 家 / 科创板 59 家 / 北交所 21 家」——这些来自**另一篇报道**，
      不在官方块里 → 整条答案被拦。用户问的是"有多少家上市公司"，
      主答案对了却因为一个分项被拦，**误拦的代价大于漏拦**。
      ⇒ 硬拦截只管主结论；结构分项留给评测期（`外源探测.py`）暴露，不在产品面上连坐。

    ⚠️ 跳过条件（宁可不判）：原文没分块 / 答案没时点 / 答案没带单位的数字。
    """
    块们 = [_归一(b) for b in 分块(原文)]
    if not 块们:
        return "✅ 跳过：原文没有可识别的来源分块（无法判同源，不误判）"
    if not 抽数(答案):
        return "✅ 跳过：答案里没有带计量单位的数字"
    if not 抽时点(答案):
        return "✅ 跳过：答案未标任何时点（这本身是另一个问题：该标而未标）"

    违例, 判了, 跳过 = [], 0, 0
    段们 = 分段(答案)
    全部时点 = [t for t, _ in 段们 if t]
    主时点 = max(全部时点, key=_时点键) if 全部时点 else None
    重要口径 = {"合计口径", "A股口径"}

    for 段时点, 句 in 段们:
        数们 = 抽数(句)
        if not 数们:
            continue
        # 「原串 → 口径」，用于判断这个数是不是主结论（合计/A股家数）
        口径表 = {_归一(原串): 口径 for 口径, _值, 原串 in 抽家数(句)}
        if 段时点 is None:
            跳过 += len(数们)
            continue
        形态 = [_归一(x) for x in _时点形态(段时点)]
        命中块 = [b for b in 块们 if any(形 in b for 形 in 形态)]
        if not 命中块:                      # 原文没给这个时点
            if 主时点 and _时点键(段时点) == _时点键(主时点):
                # ⭐ 主结论的时点在**所有来源里都找不到** → 这个日期是"自己造的/串了别的文章的"
                #   实测事故：答案是「295/235 + 官方 2026-08-25」，而 8-25 这版检索里根本没出现
                #   （只有 8-21）。引用旧值（如"6 月末"）不适用本条 —— 旧值不是主结论。
                违例.append(f"主时点 {段时点[3]} 在所有来源块里都找不到（时点无出处）")
            else:
                跳过 += len(数们)           # 引用性旧值：原文没给日期，无从核对
            continue
        for _值, 原串 in 数们:
            原串归一 = _归一(原串)
            口径 = 口径表.get(原串归一)
            if 只判主口径 and not (口径 in 重要口径):
                跳过 += 1                   # 结构分项等次要数字：硬拦截不管，避免连坐
                continue
            判了 += 1
            if not any(原串归一 in b for b in 命中块):
                违例.append(f"{原串} 配 {段时点[3]} 找不到同一块来源")

    if 违例:
        return "❌ 跨块配对：" + "；".join(违例[:3])
    if 判了 == 0:
        return f"✅ 跳过：没有可核对的「数字+时点」组合（跳过 {跳过} 个数字）"
    return f"✅ 同源同组通过（判 {判了} 个数字、{len(块们)} 块来源，跳过 {跳过}）"


def _时点形态(t) -> list[str]:
    """一个时点的**所有常见写法**，用于"块里有没有出现过这个时点"的匹配。

    ⚠️ 这里踩过：只比原串 → 答案写「2026年8月21日」、原文写「截至8月21日」，
       匹配失败 → **正确答法被误判成跨块配对**（自演示第 1 条就是这么红的）。
       时点归一化必须把「带年/不带年、- 与 年月日、有无"截至"」全部覆盖。
    """
    年, 月, 日 = t[0], t[1], t[2]
    if 日 == 0:
        # 只有年月（如「2026年6月末」）：只认到月，别硬凑日
        形态 = [f"{年}年{月}月", f"{年}-{月}", f"{月}月"]
        return 形态
    形态 = [f"{月}月{日}日", f"截至{月}月{日}日", f"{月}-{日}", f"{月}/{日}"]
    # ⭐ 2026-10-20：「会计报告期名称」也是时点的合法写法，必须一起认。
    #   实测事故：「十大流通股东」工具返回只写「报告期 2026中报」（不写日期），
    #   模型正确地补成「截至 2026-06-30」→ 块里找不到这个字面日期 → 判「时点无出处」
    #   → **整条正确答案被硬拦**（用户看到的是一条完全正常的股东表被【无法回答】）。
    #   ⇒ 时点归一化必须覆盖「中报/年报/一季报/三季报」这套会计口径叫法。
    #   `2026年中报` 里的「年」用 `年?` 兼容，避免「2026中报」「2026年中报」两种写法漏一个。
    报告期词 = {(6, 30): ("中报", "半年报", "半年度报告"),
             (12, 31): ("年报", "年度报告", "年度"),
             (3, 31): ("一季报", "一季", "第一季度报告"),
             (9, 30): ("三季报", "三季", "第三季度报告")}.get((月, 日), ())
    if 年 and 报告期词:
        形态 += [f"{年}{词}" for 词 in 报告期词]      # 2026中报
        形态 += [f"{年}年{词}" for 词 in 报告期词]    # 2026年中报
    if 年:
        形态 += [f"{年}-{月:02d}-{日:02d}", f"{年}年{月}月{日}日",
                 f"{年}-{月}-{日}", f"{年}/{月}/{日}", f"{年}.{月}.{日}",
                 # 紧凑 8 位：`20260630`（AKShare 报告日格式，见 `_时点紧凑` 的注释）
                 f"{年}{月:02d}{日:02d}"]
    return 形态


def 口径唯一(答案: str) -> str:
    """判据 2：**同一个口径、同一个时点**，不得出现两个不同的值。

    抓的是"同一句话里先给 297、后面又冒出 295"这种自相矛盾。

    ⚠️ 必须按时点分段比，不能全文比：答案合法地写「8 月口径 297、6 月末口径 295」
       是完全正确的（两个时点本来就该有两个数）。实测全文比 → 好答案被判红。
    """
    冲突 = []
    段数 = 0
    for 段时点, 句 in 分段(答案):
        组: dict[str, set[float]] = {}
        for 口径, 值, _原 in 抽家数(句):
            组.setdefault(口径, set()).add(值)
        for k, v in 组.items():
            if len(v) > 1:
                冲突.append(f"[{段时点[3] if 段时点 else '无时点'}] {k}={sorted(v)}")
        段数 += len(组)

    if 冲突:
        return "❌ 同口径多值：" + "；".join(冲突[:3])
    if 段数 == 0:
        return "✅ 跳过：答案里没有带口径标签的家数"
    return f"✅ 口径按时点唯一（{段数} 个「段×口径」组合）"


def 分项不超合计(答案: str) -> str:
    """判据 3：**分项 ≤ 合计**。

    ⚠️ 只做这一个不等式，**不做**「合计 = 分项之和」——因为 A+H 两地上市会被重复计数
       （苏州：境内外 297、A股 236，差 61，但境外 63 家；63 ≠ 61 是正常口径，不是错）。
       做等式校验会制造一堆假阳性，这条踩过，别加回去。
    """
    各家 = 抽家数(答案)
    合计 = [v for k, v, _ in 各家 if k == "合计口径"]
    分项 = [(k, v) for k, v, _ in 各家 if k in ("A股口径", "境外口径", "境内口径")]
    if not 合计 or not 分项:
        return "✅ 跳过：没同时出现合计口径与分项口径"

    最大合计 = max(合计)
    超 = [f"{k}={v:g} > 合计{最大合计:g}" for k, v in 分项 if v > 最大合计]
    if 超:
        return "❌ 分项大于合计：" + "；".join(超[:3])
    return f"✅ 分项不超合计（合计 {最大合计:g}，最大分项 {max(v for _, v in 分项):g}）"


def 时点不倒退(前答: str, 后答: str) -> str:
    """判据 4：追问「最新的呢」之后，答案的时点**不许倒退**。

    抓的是"第一次给 2026-08、追问最新反而退回 2025 年末"——
    检索结果一变，模型就可能捡到更旧的那篇。
    """
    前 = 抽时点(前答)
    后 = 抽时点(后答)
    if not 前 or not 后:
        return "✅ 跳过：任一侧没标时点，无法比较先后"

    a = max(前, key=_时点键)          # 前答里最晚的时点
    b = max(后, key=_时点键)          # 后答里最晚的时点
    if not _时点可比(a, b):
        return "✅ 跳过：时点缺年份，不可比"
    if _时点键(b) < _时点键(a):
        return f"❌ 时点倒退：追问最新后从 {a[3]} 退回 {b[3]}"
    return f"✅ 时点未倒退（{a[3]} → {b[3]}）"


def 同义一致(答A: str, 答B: str) -> str:
    """判据 5：**同一问题的不同问法**，数字必须一致（或时点不同，能解释差异）。

    三种结论：
      · 数字一致 → ✅
      · 数字不同 + 时点不同 → ✅ 放行（记"时点漂移"：差异有解释，不算错）
      · 数字不同 + 时点相同（或都没标时点）→ ❌ 无法解释的差异

    ⚠️ 「都没标时点」判 ❌ 是**刻意严格**的：同问法两次给出不同数字、又都说不出时点，
       对用户就是"系统自己都说不准"，属于必须拦的形态。

    ⚠️ 只比**主段**（时点最新那一段）的数字，不比全文：
       好答案会在括号里引用旧值做对比（「此前 6 月末为 295 家」），
       全文比集合 → 一份引用了旧值的答案会被判成"与另一份不一致"（假阳性，实测踩到）。
    """
    时A0, 段A = 主段(答A)
    时B0, 段B = 主段(答B)
    A = {v for v, _ in 抽数(段A)}
    B = {v for v, _ in 抽数(段B)}
    if not A or not B:
        return "✅ 跳过：任一侧主段里没有带单位的数字"
    if A == B:
        return f"✅ 主段数字一致（{sorted(A)}）"

    差A, 差B = A - B, B - A
    能解释 = (时A0 and 时B0 and _时点可比(时A0, 时B0)
              and _时点键(时A0) != _时点键(时B0))

    if 能解释:
        return (f"✅ 放行：主段数字不同但时点不同（{时A0[3]} vs {时B0[3]}），"
                f"属时点漂移而非矛盾")
    return (f"❌ 同问法不一致且无法用时点解释：A 独有 {sorted(差A)}、B 独有 {sorted(差B)}"
            f"（主段时点 {时A0[3] if 时A0 else '无'} / {时B0[3] if 时B0 else '无'}）")


判据表 = {
    "同源同组": 同源同组,
    "口径唯一": 口径唯一,
    "分项不超合计": 分项不超合计,
    "时点不倒退": 时点不倒退,
    "同义一致": 同义一致,
}


def 判(判据: str, **参数) -> str:
    """统一入口：`判("同源同组", 答案=..., 原文=...)` → 以 ✅/❌ 开头的说明串。"""
    fn = 判据表.get(判据)
    if fn is None:
        raise RuntimeError(f"未知判据 `{判据}`（可用：{sorted(判据表)}）")
    try:
        return fn(**参数)
    except TypeError as e:
        raise RuntimeError(f"判据 `{判据}` 参数不对：{e}") from e


