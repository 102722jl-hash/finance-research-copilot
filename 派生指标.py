def _钱(v) -> str:
    return f"{v:,.2f}" if isinstance(v, (int, float)) else str(v)


def _取财(公司: str, 指标: str, 年份: int) -> tuple[float | None, str]:
    """取一个财务因子。返回 (值, 一行溯源文本)；失败时 值=None、文本=原因。"""
    r = 查财务数值(公司, 指标, 年份)
    if not r["ok"]:
        return None, r["错误"]
    if r["值"] is None:
        return None, f"「{指标}」在报告期 {r['报告期']} 的数值为空"
    return r["值"], f"{指标} = {_钱(r['值'])}（来源表 {r['源表']}，报告期 {r['报告期']}）"


def _取股价(公司: str) -> tuple[float | None, str]:
    """取最新股价（走实时行情，带数据源与时点）。"""
    解析 = realtime_tool._解析标的(公司)
    if 解析 is None:
        return None, f"认不出标的「{公司}」"
    代码, 显示名 = 解析
    信息 = realtime_tool._取行情(代码)
    if not 信息:
        return None, f"取不到「{公司}」的实时行情"
    价 = 信息.get("最新价")
    if not 价:
        return None, f"「{公司}」的实时行情里没有有效最新价（{信息.get('来源')}，{信息.get('时点')}）"
    溯源 = (f"最新股价 = {价} 元（数据源 {信息.get('来源')}，"
            f"快照时点 {信息.get('时点') or '未知'}）")
    return float(价), 溯源


def _算ROE(公司: str, 年份: int) -> str:
    净利, s1 = _取财(公司, _归母净利, 年份)
    权益, s2 = _取财(公司, _归母权益, 年份)
    if 净利 is None or 权益 is None:
        return _算不出("ROE（净资产收益率）", [s1, s2])
    if 权益 == 0:
        return _算不出("ROE（净资产收益率）", ["分母「股东权益合计」为 0，无法计算"])
    值 = 净利 / 权益 * 100
    return _出结果(公司, 年份, "ROE（净资产收益率）", f"{值:.2f}%",
                   "归母净利润 ÷ 股东权益合计(不含少数股东权益) × 100%", [s1, s2])


def _算毛利率(公司: str, 年份: int) -> str:
    收入, s1 = _取财(公司, _营业总收入, 年份)
    成本, s2 = _取财(公司, _营业成本, 年份)
    if 收入 is None or 成本 is None:
        return _算不出("毛利率", [s1, s2])
    if 收入 == 0:
        return _算不出("毛利率", ["分母「营业总收入」为 0，无法计算"])
    值 = (收入 - 成本) / 收入 * 100
    注 = "（库内另有同名派生指标「毛利率」，按营业收入口径计算，可对照使用）"
    return _出结果(公司, 年份, "毛利率", f"{值:.2f}%",
                   "(营业总收入 − 营业成本) ÷ 营业总收入 × 100%", [s1, s2], 补充=注)


def _算PE(公司: str, 年份: int) -> str:
    价, s1 = _取股价(公司)
    eps, s2 = _取财(公司, _每股收益, 年份)
    if 价 is None or eps is None:
        return _算不出("PE（市盈率）", [s1, s2])
    if eps == 0:
        return _算不出("PE（市盈率）", ["分母「基本每股收益」为 0，无法计算"])
    值 = 价 / eps
    return _出结果(公司, 年份, "PE（市盈率）", f"{值:.2f} 倍",
                   "最新股价 ÷ 基本每股收益", [s1, s2],
                   补充="（PE 跨了两个源：股价是实时行情，EPS 来自年报）")


def _算PB(公司: str, 年份: int) -> str:
    价, s1 = _取股价(公司)
    权益, s2 = _取财(公司, _归母权益, 年份)
    股本, s3 = _取财(公司, _期末总股本, 年份)
    if 价 is None or 权益 is None or 股本 is None:
        return _算不出("PB（市净率）", [s1, s2, s3])
    if 股本 == 0:
        return _算不出("PB（市净率）", ["分母「期末总股本」为 0，无法计算"])
    每股净资产 = 权益 / 股本
    值 = 价 / 每股净资产
    s2b = (f"每股净资产 = 归母权益 ÷ 期末总股本 = {_钱(权益)} ÷ {_钱(股本)} "
           f"= {每股净资产:.4f} 元"
           f"（库内**没有**现成的「每股净资产」字段，这是按定义推导的）")
    return _出结果(公司, 年份, "PB（市净率）", f"{值:.2f} 倍",
                   "最新股价 ÷ 每股净资产；每股净资产 = 归母权益 ÷ 期末总股本",
                   [s1, s2, s3, s2b],
                   补充="（PB 跨了两个源：股价是实时行情，净资产来自年报）")


