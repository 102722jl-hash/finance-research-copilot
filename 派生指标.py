def _算不出(指标名, 原因们) -> str:
    """缺因子时的返回。⚠️ 措辞不能写成"工具不支持该指标" ——

    指标**是**支持的，只是这家公司/这个报告期缺必要科目（实测：银行/券商没有
    「营业成本」「存货」「应收账款」，所以存货周转率对他们永远算不出）。
    写成"工具不支持"会让模型对用户说"我们查不了周转率"，把局部数据缺失
    说成全局能力缺失 —— 这是另一种不准。
    """
    行 = [f"【算不出】{指标名}：缺失必要因子，无法按公式计算。"]
    行 += [f"  · {r}" for r in 原因们 if r]
    行.append("→ 这是**该公司/该报告期缺科目**，不是工具不支持该指标。"
              "请如实告诉用户「按现有数据算不出」，并说明缺的是哪个科目；"
              "**不要**用 0 或近似值顶替，也不要自己换公式。")
    return "\n".join(行)


@tool
def 算派生指标(公司: str, 指标: str, 年份: int = 0) -> str:
    """按**白名单公式**计算派生指标（这些指标库里没有现成字段）。

    白名单共 9 个：
      · ROE（净资产收益率）/ 毛利率 / PE（市盈率）/ PB（市净率）
      · ROA（总资产收益率）= 净利润 ÷ 资产总计
      · 有息负债率 = (短期借款+一年内到期的非流动负债+长期借款+应付债券) ÷ 资产总计
      · 存货周转率 = 营业成本 ÷ 平均存货
      · 应收账款周转率 = 营业总收入 ÷ 平均应收账款
      · 总资产周转率 = 营业总收入 ÷ 平均资产总计

    什么时候该用：用户问的是上面任意一个指标。
      ⚠️ 尤其是**周转率 / ROA / 有息负债率** —— 这几个词若改用 `查财务指标`，
      会掉进语义检索、返回一个**量纲都不对**的数（如把"存货金额"当成"存货周转率"）。
    什么时候不该用：增长率、占比、ROIC、PEG、EV/EBITDA 等**不在白名单**的派生指标
      —— 那些一律回答「当前工具不支持该指标」，**不许自己造公式**。

    参数：
      - 公司：中文名（如 "宝钢股份"）或代码（如 "600019.SH"）。
      - 指标：上面白名单里的名字（中英文、常见别名都认）。
      - 年份：年报年份（如 2025）；不填取最新一期年报。
        ⚠️ 周转率类**建议给年份**：给了才能做期初期末平均；不给只能用期末数（返回体会写明）。

    返回：计算结果 + 公式 + **每一个因子的取值与来源表**（可复算、可溯源），
    并标注「按公式计算」。因子缺失时会明确说"算不出"，**绝不拿近似值顶替**。
    """
    键 = (指标 or "").strip().lower().replace(" ", "")
    规范 = _规范名.get(键) or _规范名.get((指标 or "").strip())
    if 规范 is None:
        return (f"当前工具不支持该指标「{指标}」。\n"
                f"本工具只支持白名单内的 {len(算函数)} 个派生指标：{白名单说明}\n"
                f"其他指标（增长率 / 占比 / ROIC / PEG / EV-EBITDA 等）一律不支持，"
                f"**不要自己套公式推算** —— 请如实告诉用户不支持。")
    try:
        return 算函数[规范](公司, 年份)
    except Exception as e:          # 工具绝不能抛异常（v5 第 2 讲）
        return f"计算「{指标}」时出错（{type(e).__name__}: {e}）。请稍后重试。"


