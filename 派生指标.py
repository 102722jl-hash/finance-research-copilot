# 有息负债的构成项。⚠️ 口径写死在这里，也必须写进公式行 ——
#   不同数据商口径能差 20 个百分点（有的含应付票据/租赁负债，有的只算银行借款）。
_有息项 = ["短期借款", "一年内到期的非流动负债", "长期借款", "应付债券"]
_有息公式 = "短期借款 + 一年内到期的非流动负债 + 长期借款 + 应付债券"
_有息口径注 = "（⚠️ 各构成项中为空的按 0 计入；本口径**未含**应付票据、租赁负债，若你需要含它们请说明）"


def _取财可空(公司: str, 指标: str, 年份: int) -> tuple[float, str, bool]:
    """取一个"可以合法为空"的因子。返回 (值, 一行溯源, 是否真有值)。

    与 `_取财` 的区别：`_取财` 遇到 NULL 返回 None（→ 算不出）；
    这里遇到 NULL 返回 0.0 并把"空（按 0 计）"写进溯源文本 ——
    只用于**有息负债的构成项**这种"没有余额就是 0"的科目。
    """
    r = 查财务数值(公司, 指标, 年份)
    if not r["ok"]:
        return 0.0, f"{指标}：{r['错误']}（按 0 计）", False
    if r["值"] is None:
        return 0.0, f"{指标} = 空（报告期 {r['报告期']} 无该科目余额，按 0 计）", False
    return (float(r["值"]),
            f"{指标} = {_钱(r['值'])}（来源表 {r['源表']}，报告期 {r['报告期']}）",
            True)


def _平均科目(公司: str, 科目: str, 年份: int) -> tuple[float | None, list[str]]:
    """取「平均余额」= (期初 + 期末) ÷ 2。返回 (平均额, 溯源行列表)。

    ⚠️ 年份=0（"最新年报"）时**不做平均** —— 因为拿不到报告期就没法倒推上一年，
       这时只取期末数并在溯源里写明"期末口径"，让模型转述时能说清。
    """
    末, s末 = _取财(公司, 科目, 年份)
    if 末 is None:
        return None, [s末]
    期 = f"{年份}年报" if 年份 else "最新年报"
    if not 年份:
        return 末, [s末, f"⚠️ 未指定年份 → 平均{科目}取期末数（{期}），未做期初期末平均"]
    初, s初 = _取财(公司, 科目, 年份 - 1)
    if 初 is None:
        return 末, [s末, s初,
                    f"⚠️ 缺 {年份 - 1} 年报的「{科目}」，改用期末数（不做期初期末平均）"]
    均 = (初 + 末) / 2
    return 均, [s初, s末,
                f"平均{科目} = (期初 {_钱(初)} + 期末 {_钱(末)}) ÷ 2 = {_钱(均)}"]


def _算ROA(公司: str, 年份: int) -> str:
    净利, s1 = _取财(公司, _净利润, 年份)
    资产, s2 = _取财(公司, _资产总计, 年份)
    if 净利 is None or 资产 is None:
        return _算不出("ROA（总资产收益率）", [s1, s2])
    if 资产 == 0:
        return _算不出("ROA（总资产收益率）", ["分母「资产总计」为 0，无法计算"])
    值 = 净利 / 资产 * 100
    注 = ("（分母用**期末**资产总计，未做期初期末平均；本库是母公司口径，"
          "该口径下「净利润」与「归母净利润」为同一数）")
    return _出结果(公司, 年份, "ROA（总资产收益率）", f"{值:.2f}%",
                   "净利润 ÷ 资产总计 × 100%", [s1, s2], 补充=注)


def _算有息负债率(公司: str, 年份: int) -> str:
    资产, s0 = _取财(公司, _资产总计, 年份)
    if 资产 is None:
        return _算不出("有息负债率", [s0])
    if 资产 == 0:
        return _算不出("有息负债率", ["分母「资产总计」为 0，无法计算"])
    合计, 因子, 有值 = 0.0, [], False
    for 项 in _有息项:
        v, s, ok = _取财可空(公司, 项, 年份)
        合计 += v
        因子.append(s)
        有值 = 有值 or ok
    if not 有值:
        return _算不出("有息负债率", 因子 + ["四个有息负债科目全部为空"])
    因子.append(f"有息负债合计 = {_钱(合计)}")
    因子.insert(0, s0)
    值 = 合计 / 资产 * 100
    return _出结果(公司, 年份, "有息负债率", f"{值:.2f}%",
                   f"({_有息公式}) ÷ 资产总计 × 100%", 因子, 补充=_有息口径注)


def _算周转率(公司: str, 年份: int, 指标名: str, 分子科目: str, 分母科目: str) -> str:
    """周转率通用实现：分子（流量） ÷ 平均分母（存量）。单位「次」。"""
    分子, s1 = _取财(公司, 分子科目, 年份)
    分母, s2s = _平均科目(公司, 分母科目, 年份)
    if 分子 is None or 分母 is None:
        return _算不出(指标名, [s1] + s2s)
    if 分母 == 0:
        return _算不出(指标名, [s1] + s2s + [f"分母「平均{分母科目}」为 0，无法计算"])
    值 = 分子 / 分母
    return _出结果(公司, 年份, 指标名, f"{值:.2f} 次",
                   f"{分子科目} ÷ 平均{分母科目}", [s1] + s2s,
                   补充="（单位是「次」，**不是**金额，也不是百分数）")


