# 派生指标.py —— v5 第 13 讲任务 1：**白名单内的派生指标，用真公式算**
#
# 【要解决的问题】
#   原来的系统提示写死了「严禁自己推算派生指标（如比率、增长率、占比）」。
#   这条规矩本身是对的（防幻觉），但它把 ROE/PE/PB 这类**用户最常问**的指标也一起禁掉了，
#   而库里恰好**没有**这些字段 → 用户问「ROE 多少」只能答"不支持"，体验很差。
#
# 【做法：放开白名单，但**不让 LLM 做除法**】
#   系统提示改成"白名单内的可以按公式算，其他一律说不支持"；
#   同时新增本文件的 `算派生指标` 工具 —— **用 Python 取真实字段、做真实除法**。
#   为什么要这样：让模型自己在脑子里相除，等于把"数字必须来自工具"这条底线自己拆了。
#   LLM 做 8 位数除法不可靠，而工具算出来的每一步因子都可溯源、可复算。
#
# 【白名单（9 个，与系统提示里的清单必须逐字一致）】
#   ROE = 归母净利润 ÷ 股东权益合计(不含少数股东权益) × 100%
#   毛利率 = (营业总收入 − 营业成本) ÷ 营业总收入 × 100%
#   ROA = 净利润 ÷ 资产总计 × 100%
#   有息负债率 = (短期借款+一年内到期的非流动负债+长期借款+应付债券) ÷ 资产总计 × 100%
#   存货周转率 = 营业成本 ÷ 平均存货
#   应收账款周转率 = 营业总收入 ÷ 平均应收账款
#   总资产周转率 = 营业总收入 ÷ 平均资产总计
#   PE = 最新股价 ÷ 基本每股收益
#   PB = 最新股价 ÷ 每股净资产
#   ⚠️ v5-23 起「名单/公式/说明」的**唯一来源**是 `tools.派生别名` + `tools.派生白名单说明`，
#      本文件只做 import，不再各写一份。
#
# 🔴 【实测发现的三个坑（都已处理，别改回去）】
#   1. 「每股净资产」**库里没有这个字段**（三表只有基本/稀释每股收益）。
#      → PB 的分母改成 **归母权益 ÷ 期末总股本** 推导（`期末总股本` 非空率 100%）。
#      这跟"股价÷每股净资产"数学上等价，但**必须写清推导过程**，不能偷偷换公式。
#   2. 「基本每股收益」在**年报里大面积为空**（实测 38210 行仅 4715 行非空 = 12.3%，
#      宝钢 2025 年报就是空的）→ PE 经常算不出来。
#      ⚠️ 这时**绝不能拿季度 EPS 顶替**（宝钢 2026Q1 的 EPS=0.02 会算出 PE=296，荒谬）。
#      缺因子就如实说算不出。
#   3. 「股东权益合计」在字典里的真名带括号：**股东权益合计(不含少数股东权益)**，
#      直接查"股东权益合计"精确匹配不到（会走语义，可能配到"含少数股东权益"那个）。
#      → 白名单里写**全名**，绕开歧义。
#
# ⚠️ 【口径提醒】库内是**母公司（个别）报表**（见 库口径核查.md），
#    所以这里算出的 ROE / 毛利率 与公开（合并报表）口径**不可直接比较**，返回里必须写明。

