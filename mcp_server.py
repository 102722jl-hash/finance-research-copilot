# mcp_server.py —— v5 第 3 讲：把三个工具包成一个 **MCP server**（可插拔）。
#
# 【为什么要 MCP】
#   前四版加工具的方式都是"**在本进程里改代码**"：
#       写个 @tool → 塞进 graph.py 的 tools=[...] → 重启。
#   这有三个天花板：
#     ① 只有**你这个进程**能用（Claude Desktop / Cursor 想用？没门）；
#     ② 加工具要动 Agent 的代码 + 重启（工具和 Agent 焊死在一起）；
#     ③ 换语言/换进程就别想了（工具必须是 Python 函数）。
#
#   MCP（Model Context Protocol）把工具从"本进程的函数"变成"**跨进程的服务**"：
#
#        ┌────────────┐   JSON-RPC（stdio / HTTP）   ┌──────────────┐
#        │  MCP 客户端 │ ◄──────────────────────────► │  MCP 服务端   │
#        │ (Agent/IDE)│   tools/list → 动态发现工具    │ (本文件)      │
#        └────────────┘   tools/call → 调用工具        └──────────────┘
#
#   三个质变：
#     ① **可插拔**：客户端连上就问 `tools/list`，服务端说有哪些工具，**客户端代码不用改**；
#     ② **可复用**：同一个 server，Claude Desktop / Cursor / 你自己的 Agent 都能连；
#     ③ **可异构**：server 用什么语言写都行，只要说 MCP 协议。
#
# 【MCP 的三个原语（本文件全用上了）】
#   - **tools**     ：可被模型调用的函数（← 我们那三个）
#   - **resources** ：可被读取的"资料"（如公司名单表，像 GET 一个文档）
#   - **prompts**   ：预置的提示词模板（用户主动选用，不是模型自己调）
#
# ⚠️⚠️ 【stdio 传输的第一天坑】⚠️⚠️
#   stdio 模式下，**stdout 是 JSON-RPC 的协议通道**。
#   所以本文件里**绝对不能出现 `print(...)`**——任何一行 print 都会把协议冲乱，
#   客户端会报"解析失败"，而且**报错信息通常在客户端那边，极难定位**。
#   → 要打日志，一律走 **stderr**：`print(..., file=sys.stderr)`（或 logging 配到 stderr）。
#   （对比 v5-1 的教训：外部接口的"隐性约定"必须显式守——这是同一个主题第三次出现。）

import sys

from mcp.server.fastmcp import FastMCP

# 【关键设计：MCP server 只做"外壳"，业务逻辑一行不重写】
#   底下就是 v1/v3/v5 那三个 @tool，本文件只负责"换个嘴巴说话"。
#   → 同一份业务逻辑，两种暴露方式（进程内 @tool / 跨进程 MCP），**不会出现两份实现**。
import rag_tool
import realtime_tool
import tools

mcp = FastMCP("投研工具集")


# ══════════════════════════════════════════════════════════════
# 原语 1：tools —— 直接复用已有的 @tool（用 .invoke 调，参数是 dict）
#   FastMCP 会自动把 **函数签名 + docstring** 转成 MCP 的 tool schema，
#   客户端拿到后交给模型 —— 这和 langchain 的 bind_tools 是同一套逻辑，只是跨了进程。
#
# ⚠️ 【第三个坑：tool 名必须是 ASCII】MCP 规范（SEP-986）规定工具名只允许
#    A-Z a-z 0-9 _ - . 。函数名直接叫「查财务指标」不会报错，但每次连接都会刷警告
#    （Tool name contains invalid characters），而且**部分客户端可能不兼容**。
#    → 正确姿势：`@mcp.tool(name="query_financials")` 显式给一个 ASCII 名，
#       **Python 函数名照旧用中文**（它俩是两回事），中文留给 docstring 当描述给模型读。
#    （这是 v5 主题"隐性约定"的第 5 次出现。）
# ══════════════════════════════════════════════════════════════
@mcp.tool(name="query_financials")
def 查财务指标(公司: str, 指标: str, 年份: int = 0) -> str:
    """根据公司名（或 wind_code）与中文指标名，查该公司的结构化财务数据。

    什么时候该用：问"营业总收入 / 归母净利润 / 总资产 / 经营现金流 / 资产负债率"等精确数字。
    什么时候不该用：问公司公告原文、年报里的说法（该用 查公告）。

    参数：
      - 公司：中文名（如 "宝钢股份"）或代码（如 "600019.SH"）。
      - 指标：如 "营业总收入" / "归母净利润" / "总资产" / "经营现金流" / "资产负债率"。
      - 年份：年报年份（如 2025）；不填则取最新一期年报。
    """
    return tools.查财务指标.invoke({"公司": 公司, "指标": 指标, "年份": 年份})


@mcp.tool(name="query_announcements")
def 查公告(问题: str) -> str:
    """在上市公司公告 / 年报原文里做语义检索，找回最相关的段落（带出处）。

    什么时候该用：问"公告里怎么说""风险提示""分红方案""原文依据"这类需要出处的问题。
    什么时候不该用：只要一个标准财务数字（该用 查财务指标）。

    参数：
      - 问题：一句自然语言问题或关键词，如 "宝钢2023年度业绩快报归母净利润"。
    """
    return rag_tool.查公告.invoke({"问题": 问题})


@mcp.tool(name="query_realtime_quote")
def 查实时行情(标的: str) -> str:
    """查 A 股实时行情（价格、涨跌幅、成交量、总市值等），带数据源与数据时点。

    什么时候该用：问"现在多少钱""今天涨了吗""大盘怎么样"这类**时效性**问题。
    什么时候不该用：问历史某年的财务数字、公告原文。

    ⚠️ 非交易时段拿到的是**最近一次快照**（收盘价），回答时必须照搬返回里的"数据时点"。

    参数：
      - 标的：公司名（如 "宝钢股份"）、wind_code（如 "600019.SH"）或指数名（如 "上证指数"）。
    """
    return realtime_tool.查实时行情.invoke({"标的": 标的})


# ══════════════════════════════════════════════════════════════
# 原语 2：resources —— "可读的资料"，不是让模型调的函数，而是像 GET 一份文档
#
# ⚠️ 【资源 URI 的第二个坑】URI 的 scheme（`://` 前面那段）**必须是 ASCII**。
#    写 "投研://公司名单" 会被 pydantic 按 URL 校验直接拒掉：
#        ValidationError: Input should be a valid URL, relative URL without a base
#    因为 URI 规范里 scheme 只允许 `字母/数字/+/-/.`，中文不是合法 scheme 字符，
#    整个串就被当成"没有协议头的相对路径"。
#    → 正确姿势：scheme 用英文（research / file / db…），**路径部分可以中文**。
#    （这是 v5 主题"隐性约定"的第 4 次出现：外部协议/接口的格式约束必须照规矩来。）
# ══════════════════════════════════════════════════════════════
@mcp.resource("research://公司名单", name="company_list")
def 公司名单() -> str:
    """本系统支持的查询标的（公司名 → wind_code），可作为资源被客户端读取。"""
    行 = ["# 支持的标的", "", "## 公司"]
    行 += [f"- {名}：{码}" for 名, 码 in tools.公司映射.items()]
    行 += ["", "## 指数"]
    行 += [f"- {名}：{码}" for 名, 码 in realtime_tool.指数映射.items()]
    return "\n".join(行)


# ══════════════════════════════════════════════════════════════
# 原语 3：prompts —— 预置模板，由**用户主动选用**（不是模型自动调）
# ══════════════════════════════════════════════════════════════
@mcp.prompt(name="stock_brief")
def 投研速览(标的: str) -> str:
    """生成一份"标的速览"的提问模板。"""
    return (f"请给我一份「{标的}」的速览，按顺序：\n"
            f"1. 最新行情（价格、涨跌幅、成交额、总市值）—— 用 查实时行情，并说明数据时点；\n"
            f"2. 最近一期年报的关键财务数字（营业总收入、归母净利润、资产负债率）—— 用 查财务指标；\n"
            f"3. 最近公告里的风险提示 —— 用 查公告，并标出文件名与页码。\n"
            f"所有数字都要带出处；查不到的如实说明。")


if __name__ == "__main__":
    # 默认 stdio 传输：由客户端（IDE / Agent）把本进程当子进程拉起，用管道通信。
    # ⚠️ 再次提醒：这一段之后 stdout 就是协议通道了，别 print。
    print("[投研工具集] MCP server 启动（stdio）", file=sys.stderr)
    mcp.run()
