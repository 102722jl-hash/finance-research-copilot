#     「可能是该指标在这些公司里普遍为空，**或报告期不对**」
#   —— 这是**归因错误**：2012 年不是"这些公司没披露"，而是**整张表就不含这一年**。
#   用户会因此跑去翻一份根本不存在的年报。比单纯"查不到"更糟。
#   ⇒ 取数前先比区间，落在区间外就直说「超出本库覆盖范围」，
#     并把用户**引导到替代工具**（`query_public_financials` 走 AkShare 新浪接口，
#     实测覆盖宝钢 1997 年至今 105 期 → 2012 年营业总收入 = 1,915.12 亿元，真有数）。
_覆盖缓存: dict[str, tuple[int, int] | None] = {}


def 覆盖区间(cur, 真表: str) -> tuple[int, int] | None:
    """本表实际覆盖的 (最早报告期, 最晚报告期)；查不到返回 None（**绝不阻断主流程**）。"""
    if 真表 in _覆盖缓存:
        return _覆盖缓存[真表]
    try:
        cur.execute(f"SELECT MIN(report_period), MAX(report_period) FROM `{真表}`")
        r = cur.fetchone()
        区 = (int(r[0]), int(r[1])) if r and r[0] and r[1] else None
    except Exception:
        区 = None                       # 表为空/权限问题 → 不报错，退化成"不检查"
    _覆盖缓存[真表] = 区
    return 区


def _期名(期: int) -> str:
    """`20231231` → 「2023 年报」；`20260331` → 「2026 一季报」（给人/模型读的写法）。"""
    s = str(期)
    if len(s) != 8:
        return s
    季 = {"0331": "一季报", "0630": "中报", "0930": "三季报", "1231": "年报"}.get(s[4:])
    return f"{s[:4]} {季}" if 季 else s


def 越界话术(公司: str, 指标: str, 年份: int, 季度: int, 区: tuple[int, int]) -> str:
    """年份落在覆盖区间外时的话术。

    🔴 三条必须做到：① 说清是**库不覆盖**（不是公司没披露）；
       ② 给出**本库覆盖区间**，让用户知道边界在哪；③ 给**可执行的替代路径**。
    """
    季末 = {0: "1231", 1: "0331", 2: "0630", 3: "0930", 4: "1231"}.get(季度, "1231")
    求 = f"{年份}Q{季度}" if 季度 in (1, 2, 3) else f"{年份}年报"
    早, 晚 = _期名(区[0]), _期名(区[1])
    区间文 = f"{早} ~ {晚}"
    if int(f"{年份}{季末}") > 区[1]:
        return (f"【超出本库覆盖范围】你要的「{求}」**晚于本库最新一期**：本库覆盖 {区间文}。"
                f"该期可能尚未披露，或本库还没更新到它。\n"
                f"👉 若确认已披露，请改用 `query_public_financials`（公开合并报表口径，"
                f"通常更新更快）；若还未披露，请等该期报告出来再查。")
    return (f"【超出本库覆盖范围】你要的「{求}」**早于本库最早一期**："
            f"本库只有 {区间文} 的数据，更早的期**不在库内**。\n"
            f"⚠️ 这不是「{公司}没披露」—— 是**本库没有收这一年**。\n"
            f"👉 要更早年份，请改用 `query_public_financials`（公开合并报表口径，"
            f"实测可回溯到 1997 年）。该工具只支持**单家公司**；"
            f"若是**整个行业**要历史年份，改用 `query_industry_public_financials`"
            f"（行业级公开合并报表聚合，会逐家取回后汇总）—— **不要用现有数据外推**。")


