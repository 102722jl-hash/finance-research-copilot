# 小工具：动态找真表名（避免写死 ashareincome_202605261519 这种带后缀的名字）
# ══════════════════════════════════════════════════════════════
_表名缓存: dict[str, str] = {}


def _找真表名(cur, 前缀: str) -> str | None:
    """在 information_schema 里按前缀找最新的那张表。"""
    if 前缀 in _表名缓存:
        return _表名缓存[前缀]
    cur.execute(
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema=%s AND table_name LIKE %s "
        "ORDER BY table_name DESC LIMIT 1",
        (DB_NAME, 前缀 + r"\_%"),   # \_ 转义：把 _ 当普通字符来匹配
    )
    r = cur.fetchone()
    if r:
        _表名缓存[前缀] = r[0]
    return r[0] if r else None


