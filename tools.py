    if r["值"] is None:
        return f"查到 {公司} 的「{指标}」记录（报告期 {r['报告期']}），但该期数值为空"

    # ── 格式化返回（带来源，模型才知道该引用谁）──
    年 = str(r["报告期"])[:4]
    # ⚠️ 语义命中时**必须把"我把它当成了谁"写出来** —— 否则模型会以为这就是用户问的
    #    那个名字，等于把一次"猜测"包装成了"事实"（这是本讲最需要防的事）。
    # ⚠️ 展示用 `原值` 而不是 `值`：库算出来的派生指标带单位（如 '6.01%'），
    #    `值` 是剥掉百分号后的 float（6.01），用它会把单位弄丢。
    return (f"来源表 {r['源表']}：{公司} {年}年报「{指标}」{r['语义注']} "
            f"= {r['原值']}（报告期 {r['报告期']}）")


