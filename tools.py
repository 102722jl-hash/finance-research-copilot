# ①-c 【v5-16】比值类指标的「分子 / 分母」定义 —— 行业**加权口径**用
#
#   【为什么需要它】
#     「行业平均毛利率」有两种口径，不是一回事：
#       · 成员**简单平均** = Σ(每家毛利率) ÷ 家数            ← 现状给的是这个
#       · 行业**加权**     = Σ分子 ÷ Σ分母 = Σ(收入−成本) ÷ Σ收入  ← 本讲补这个
#     小公司的比率会把简单平均拉偏，加权口径才是"整个行业真实赚了多少个点"。
#
#   ⚠️ 分子/分母**必须与 `指标映射[指标]` 那条 expr 是同一套定义** ——
#      否则"简单平均"和"加权"算的不是同一个东西，并列展示反而误导。
#      本文件末尾的 `校验可加权()` 会自动对着 expr 反解核对（防止以后改一处漏一处）。
# ══════════════════════════════════════════════════════════════
