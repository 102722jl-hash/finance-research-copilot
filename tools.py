def 翻译指标(指标: str) -> dict:
    """**指标中文名 → (表前缀, 取数式, 是否表达式)**。全项目**唯一**的指标翻译入口。

    ⭐ v5 第 15 讲从 `查财务数值` 里抽出来。原因：`行业聚合.py` 要对**行业里每只成员股**
    用同一个指标批量取数 —— 如果它自己再抄一份翻译逻辑，就会出现
    "单公司查询走白名单、行业查询走字典"这种**口径分裂**，而且以后改一处必漏一处。

    顺序（v5 第 11/12 讲定下的，一步都不能少）：
      ① 白名单 `指标映射`（人工核过，42 条）→ 命中直接用；
      ② 字典**精确**查 `字典唯一候选()` → 唯一才用，≥2 条一律反问（「净利润」这类不能猜）；
      ③ 字典**公共前缀**查 `包含候选()` → ≥2 条反问（v5-15 新增，修「股东权益合计」）；
      ④ **语义**检索（阈值以上才用，且返回体必须自报"我匹配到了谁"）；
      ⑤ 都不行 → 模糊兜底给建议 / 明确"不支持"。

    返回 `{"ok": True, "表前缀", "取数式", "is_expr", "语义注"}`
    或 `{"ok": False, "错误"}`（错误已是可直接转述给用户的人话）。
    """
    语义注 = ""
    if 指标 in 指标映射:
        表前缀, 取数式, is_expr = 指标映射[指标]
        return {"ok": True, "表前缀": 表前缀, "取数式": 取数式,
                "is_expr": is_expr, "语义注": 语义注}

    # ⭐ v5 第 16 讲：**派生白名单硬拦截**（在字典/语义**之前**）。
    #    ROE / PE / PB 家族在库里没有现成列，只能走 `算派生指标`。
    #    不拦的话它们会掉进语义检索 —— 实测「净资产收益率」被配到「投资净收益」
    #    （0.36 ≥ 阈值），给一个**看着有出处的错数**。宁可明确指路，不可静默错答。
    规范 = 派生规范名(指标)
    if 规范:
        return {"ok": False,
                "错误": (f"「{指标}」是**派生指标**（库里没有现成字段），"
                       f"请改用 `算派生指标` 工具按公式计算：{派生白名单说明}")}

    c = 字典唯一候选(指标)
    if c is not None:
        表前缀 = c["table_prefix"]
        if c["is_derived"]:
            取数式, is_expr = c["expr"], True
        else:
            取数式, is_expr = c["field"], False
        return {"ok": True, "表前缀": 表前缀, "取数式": 取数式,
                "is_expr": is_expr, "语义注": 语义注}

    候选 = 查字典(指标)
    if len(候选) > 1:
        选项 = "、".join(f"{x['statement']}·{x['field'] or '派生'}" for x in 候选[:6])
        return {"ok": False,
                "错误": f"指标「{指标}」在报表里对应**多个字段**，请指明要哪一个：{选项}"}

    # ⭐ v5 第 15 讲：精确查 0 条时，先补一道"**公共前缀**"检查。
    #    「股东权益合计」精确查不到，但它是「股东权益合计(含/不含少数股东权益)」
    #    两个真名的公共前缀 —— 这类必须**反问**，不能交给语义去替你选一个。
    #    （修的就是 v5-14 那条 KNOWN 红：语义以 0.59 命中"含少数"并给了数，
    #      数值恰好对、但标注的名字是错的。）
    包含 = 字典包含候选(指标) if not 候选 else []
    if len(包含) >= 2:
        名 = list(dict.fromkeys(x["cn_name"] for x in 包含))
        return {"ok": False,
                "错误": (f"指标「{指标}」在报表里对应**多个字段**，请指明要哪一个："
                       + "、".join(名[:6]))}

    # ⭐ v5-22：**歧义词** —— 语义分再高也**不自动取数**，只给候选让人确认。
    #   【为什么要这张表】
    #     语义阈值 0.35 是"负例零误过"调出来的，但它挡不住**真·同义、不同口径**的词。
    #     实测（金标准 KNOWN 红）：`负债率` → `资产负债率` 相似度 **0.417 ≥ 0.35** → 直接给数；
    #     而"负债率"在实务里常指**有息负债率**（只算有息负债），两者能差 20 个百分点以上。
    #   【为什么不能靠调阈值】
    #     毛利润→毛利率 是 0.408，比负债率的 0.417 **还低** —— 阈值调到 0.42 会把毛利润那条打掉。
    #     两个方向都有真实需求，阈值这一维**无法两全**。
    #   ⇒ 只能按"词"拦截：这类词命中就不猜，交给用户点明。
    _歧义候选 = {
        "负债率": "资产负债率（负债合计÷资产总计）、有息负债率（有息负债÷总资产）、净负债率",
        "净负债率": "净负债率（有息负债净额÷净资产）、资产负债率",
        # ⚠️ v5-23：「有息负债率」**已从本表移除** —— 它现在是 `算派生指标` 白名单里
        #    能按公式算的指标（语义明确，不存在"要用户再点明一次"的必要）。
        #    留在本表会让它永远只反问、永远算不出来。真正歧义的是口语「负债率」（保留）。
        "利润率": "毛利率、净利率、营业利润率",
        "回报率": "ROE（净资产收益率）、ROA（总资产收益率）",
        "收益率": "ROE（净资产收益率）、ROA（总资产收益率）",
        "周转率": "存货周转率、应收账款周转率、总资产周转率",
        "费用率": "销售费用率、管理费用率、财务费用率",
        "增长率": "营业收入增长率、净利润增长率",
    }
    _词 = (指标 or "").strip().replace(" ", "")
    if _词 in _歧义候选:
        return {"ok": False,
                "错误": (f"「{指标}」有多种口径，不能替你自动选一个。"
                       f"你是不是想说：{_歧义候选[_词]}？请指明之后再查。")}

    语义 = _语义找(指标)
    if 语义 and 语义[0]["相似度"] >= 语义阈值:
        c = 语义[0]
        表前缀 = c["table_prefix"]
        取数式, is_expr = (c["expr"], True) if c["is_derived"] else (c["field"], False)
        语义注 = (f"（语义匹配「{c['statement']}·{c['主名']}」，"
                 f"相似度 {c['相似度']:.2f}）")
        return {"ok": True, "表前缀": 表前缀, "取数式": 取数式,
                "is_expr": is_expr, "语义注": 语义注}

    近 = 搜字典(指标, 上限=8)
    if 近:
        名 = "、".join(dict.fromkeys(x["cn_name"] for x in 近 if x["cn_name"]))
        return {"ok": False, "错误": f"暂不支持指标「{指标}」。你是不是想说：{名}？"}
    if 语义:
        名 = "、".join(f"{r['statement']}·{r['主名']}" for r in 语义[:3])
        return {"ok": False,
                "错误": f"暂不支持指标「{指标}」，最接近的候选是：{名}。请用其中一个名字重新提问。"}
    if not 字典可读():
        return {"ok": False,
                "错误": (f"暂时查不到指标「{指标}」：指标字典读不到（多半是本机 MySQL 没启动）。"
                       f"这**不是**不支持该指标，请确认数据库后再试。")}
    return {"ok": False,
            "错误": (f"暂不支持指标「{指标}」。本系统可查三大报表 400+ 个科目，"
                   f"可直接说 Wind 科目名（如「资产总计」「递延所得税资产」）。")}


def 查财务数值(公司: str, 指标: str, 年份: int = 0, 季度: int = 0) -> dict:
    """查一个财务指标的**原始数值**（供派生计算复用；不做字符串格式化）。

    为什么要有它：`查财务指标` 返回的是给人/给模型读的一句话，派生指标（ROE/PE/PB）
    要用它的**数字**去做除法。再解析字符串既脆弱又重复，所以把取数抽成这一层，
    `查财务指标` 只负责把它包装成一句话 —— **同一份取数逻辑，两种用法**。

    返回 dict：
      ok=True  → 值（float，可能 None=该期为空）/ 源表 / 报告期 / 期名 / 语义注
      ok=False → 错误（已是人话，可直接转述给用户）
    """
    # ── 翻译：指标 → 表前缀 + 取数式 + 是否表达式 ──
    #    ⭐ v5 第 15 讲把它抽成公共函数 `翻译指标()`：`行业聚合.py` 要对**行业里每一只成员股**
    #    用同一个指标取数，必须复用同一套翻译（白名单 → 字典 → 语义），
    #    否则"单公司口径"和"行业口径"迟早会漂移成两个说法。
    tr = 翻译指标(指标)
    if not tr["ok"]:
        return {"ok": False, "错误": tr["错误"]}
    表前缀, 取数式, is_expr = tr["表前缀"], tr["取数式"], tr["is_expr"]
    语义注 = tr["语义注"]

    代码 = 解析公司(公司) or 公司

    try:
        conn = pymysql.connect(host=DB_HOST, port=DB_PORT, user=DB_USER,
                               password=DB_PASSWORD, database=DB_NAME, charset="utf8mb4")
    except Exception as e:
        return {"ok": False,
                "错误": (f"数据库连接失败（{type(e).__name__}），暂时查不到「{指标}」。"
                       f"请稍后重试，或确认本机 MySQL 服务已启动。")}

    try:
        with conn.cursor() as cur:
            真表 = _找真表名(cur, 表前缀)
            if 真表 is None:
                return {"ok": False, "错误": f"库里找不到「{表前缀}」系列的表"}

            # ⭐ 2026-10-20：**先比覆盖区间** —— 只在"用户明确指定了年份"时检查。
            #    不指定年份（取最新一期）时永远落在区间内，不必多查一次。
            if 年份:
                区 = 覆盖区间(cur, 真表)
                if 区:
                    季末探 = {0: "1231", 1: "0331", 2: "0630", 3: "0930", 4: "1231"}.get(季度, "1231")
                    待查 = int(f"{年份}{季末探}")
                    if 待查 < 区[0] or 待查 > 区[1]:
                        return {"ok": False,
                                "错误": 越界话术(公司, 指标, 年份, 季度, 区),
                                "越界": True}

            select_col = 取数式 if is_expr else f"`{取数式}`"
            季末 = {0: "1231", 1: "0331", 2: "0630", 3: "0930", 4: "1231"}.get(季度, "1231")
            if 年份:
                报告期值 = int(f"{年份}{季末}")
                期名 = (f"{年份}Q{季度}" if 季度 in (1, 2, 3) else f"{年份}年报")
                sql = (f"SELECT report_period, {select_col} FROM `{真表}` "
                       f"WHERE wind_code=%s AND report_period=%s")
                参数 = (代码, 报告期值)
            else:
                期名 = "最新年报"
                sql = (f"SELECT report_period, {select_col} FROM `{真表}` "
                       f"WHERE wind_code=%s AND report_period LIKE %s "
                       f"ORDER BY report_period DESC LIMIT 1")
                参数 = (代码, "%1231")

            cur.execute(sql, 参数)
            row = cur.fetchone()
    except Exception as e:
        return {"ok": False,
                "错误": (f"查询「{指标}」时出错（{type(e).__name__}: {e}）。"
                       f"这多半是本机数据库的问题，不是数据本身没有 —— 请如实告知用户查询失败。")}
    finally:
        conn.close()

    if not row:
        return {"ok": False, "错误": f"没查到 {公司}（代码 {代码}）的「{指标}」{期名}"}

    报告期, 值 = row
    原值 = 值                     # 保留原始形态（如库算出来的 '6.01%'），展示时用它，别把单位丢了
    # 派生算式在库里已经拼成带 '%' 的字符串（如 '6.01%'），这里统一成 float 便于计算
    if isinstance(值, str):
        try:
            值 = float(值.rstrip("%"))
        except ValueError:
            return {"ok": False, "错误": f"「{指标}」返回值不是数字：{值}"}
    elif 值 is not None:
        值 = float(值)

    return {"ok": True, "值": 值, "原值": 原值, "源表": 真表, "报告期": int(报告期),
            "期名": 期名, "语义注": 语义注, "代码": 代码}


