# 诚实边界（v5-9 扩字典时明确，别当"什么都能查"）
# ──────────────────────────────────────────────────────────────
# 1. 本工具**只能单表派生**。跨表的指标当前做不了：
#    · 净资产收益率(ROE)、净资产 → 要 资产负债表(tot_assets/tot_liab) + 利润表(归母净利润)；
#    · 存货周转天数、应收账款周转天数 → 要 资产负债表(存货/应收) + 利润表(营业成本)；
#    · 股息率、市盈率、市净率 → 要 分红/股本/行情，还得配股价。
#    做法：要支持就把算式下沉到 SQL（JOIN 两表）或建一张宽表视图，别让模型自己算。
# 2. **报告期口径**：report_period 是"报告期末"。年报=1231；季度=0331/0630/0930。
#    接口类问题里说的"第1季度"通常指 0331。跨年比较（如"近三年营业收入"）要多次调用，
#    或用 年份=0 取最新一期再自行换年份 —— 本工具一次只返回一期。
# 3. **数值单位**：库里是**元**（原始值）。"换算成亿元"是**展示层**的事（系统提示第 5 条偏好），
#    工具不换算，模型按偏好换算。
# 4. **空值**：某公司某期该列可能为 NULL（如银行没有"存货"）→ 返回"该期数值为空"，不是报错。
