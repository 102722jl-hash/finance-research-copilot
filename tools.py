def 由算式找比值(取数式: str, is_expr: bool) -> str | None:
    """给一条算好的 expr，反查它是 `可加权比值` 里的哪个指标（认别名用）。

    为什么要这样：用户可能说"销售毛利率"（别名），归一后拿到的 expr 与"毛利率"相同
    —— 用 expr 当钥匙，任何别名都能自动享受到加权口径，不必逐个维护别名表。
    """
    if not is_expr:
        return None
    名 = _由算式到比值.get(取数式)
    return 名


def 校验可加权() -> list[str]:
    """自检：`可加权比值` 与 `指标映射` 里的 expr 是否**同一定义**。

    做法：从 expr 里把 `ROUND(<分子> / NULLIF(<分母>, 0) ...` 的分子/分母抠出来，
    换成 (字段, 符号) 列表，与 `可加权比值` 逐项比对。返回不一致的描述列表（空 = 全对）。
    """
    import re as _re
    不一致 = []
    for 名, spec in 可加权比值.items():
        if 名 not in 指标映射:
            不一致.append(f"「{名}」不在 指标映射 里，无法对照")
            continue
        expr = 指标映射[名][1]
        m = _re.search(r"ROUND\(\s*(.*?)\s*/\s*NULLIF\(\s*([A-Za-z_]+)\s*,", expr)
        if not m:
            不一致.append(f"「{名}」的 expr 形态不认识：{expr}")
            continue
        分子串, 分母字段 = m.group(1), m.group(2)
        # 分子：可能带括号 "( oper_rev - less_oper_cost )"，也可能就是单个字段
        分子串 = 分子串.strip().strip("()")
        项 = []
        for 片段 in _re.split(r"(?=[+-])", 分子串.replace(" ", "")):
            if not 片段:
                continue
            符 = -1 if 片段.startswith("-") else 1
            字段 = 片段.lstrip("+-")
            if 字段:
                项.append((字段, 符))
        期望分子 = [(f, s) for f, s in spec["分子"]]
        期望分母 = [(f, s) for f, s in spec["分母"]]
        if 项 != 期望分子:
            不一致.append(f"「{名}」分子：expr={项} vs 表={期望分子}")
        if 期望分母 != [(分母字段, 1)]:
            不一致.append(f"「{名}」分母：expr={分母字段} vs 表={期望分母}")
    return 不一致


