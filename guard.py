# ⭐ 2026-10-20 真实流量集修**结构性误拒**：名称表里带后缀的名字认不出来
#
#   实测（clean.xlsx 1410 条）：「埃夫特」「摩尔线程」这类**新股简称**被判「域外」拒答，
#   可名单里明明有 —— 存的是 `埃夫特-U` / `摩尔线程-U`（未盈利上市的标记后缀）。
#   `_有标的` 原来是「全名 in 问题」，问题里写的是简称 → 擦肩而过。
#   同一个根因还坑过「宝钢」（名单里是「宝钢股份」）。
#
#   ⇒ 除了全名，再建一份**去后缀短名表**：剥掉 `-U/-W/-UW`（ASCII 后缀）和
#      `股份/集团/控股`（中文后缀）。这样：
#        `埃夫特-U` → `埃夫特` ✅　`宝钢股份` → `宝钢` ✅　`上汽集团` → `上汽` ✅
#   ⚠️ 短名最短 2 字（宝钢/上汽/万科）—— 这会让极少数域外问题落到 B，
#      但按项目定下的"宁可多走一轮 B，也绝不误拒"原则，这是正确的一侧。
#   ⚠️ 只剥**尾部**后缀，不做模糊/编辑距离（那会引入不可控误判）。
# ══════════════════════════════════════════════════════════════
_短名表: set | None = None


def _短名集合() -> set:
    """全市场名单 + 去后缀短名（懒建一次，之后只读）。"""
    global _短名表
    if _短名表 is None:
        出 = set()
        for 名 in 名称表():
            净 = re.sub(r"-[A-Za-z]{1,3}$", "", 名)      # -U / -W / -UW
            for 后缀 in ("股份", "集团", "控股"):
                if 净.endswith(后缀) and len(净) - len(后缀) >= 2:
                    净 = 净[: -len(后缀)]
                    break
            if len(净) >= 2:
                出.add(净)
        _短名表 = 出
    return _短名表


def _有标的(问题: str) -> bool:
    if _代码形状.search(问题):
        return True
    if any(名 in 问题 for 名 in 指数映射):
        return True
    for 名 in _短名集合():              # 全市场短名（≥2 字，已剥后缀）
        if 名 in 问题:
            return True
    return False


