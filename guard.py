def 拒绝文案(类别: str, 详情: str = "", 建议: str = "") -> str:
    """生成结构化拒答文案。**确定性输出**，同参数必同文案。"""
    行 = ["【无法回答】", f"原因：{_原因文案.get(类别, 详情 or '超出能力边界')}"]
    if 详情 and 类别 in _原因文案:
        行.append(f"细节：{详情}")
    if 类别 in ("C", "越界"):
        行.append("可以问我：财务指标、公告原文、实时行情、资金流、涨停池、涨跌幅榜、"
                  "板块行情、K线与技术指标、龙虎榜、大宗交易、十大流通股东、研报与快讯。")
    elif 类别 == "域外":
        行.append("可以问我：某只股票的财务指标/行情/资金流/公告，某个行业的聚合数据或趋势，"
                  "或宏观数据（LPR、CPI 等）。")
    elif 类别 == "无出处":
        行.append("已拦截原回答以免误导。可改为：让我只回答能查到出处的部分。")
    elif 类别 == "口径混搭":
        行.append("已拦截原回答以免给出过时或拼凑的数字。可改为：只问一个明确口径"
                  "（如「境内外合计」或「A股」），并允许我说明数据的**截至时点**。")
    elif 类别 == "无数据":
        行.append("可以问我：已接入的财务指标、公告检索、实时行情、资金流、涨停池、"
                  "板块、K线/技术指标、龙虎榜、大宗交易、股东、研报与快讯。")
    elif 类别 == "超时":
        行.append("可以改为：把问题拆成更具体的一条（明确公司 + 明确指标/年份）。")
    elif 类别 == "轮数上限":
        # ⭐ v5-10：原来的建议是"拆成更具体的一条"，但落到这里的**恰恰是本来就具体、
        #    只是缺数据源**的问题（行业趋势/供应商关系/宏观销量…）。给"拆问题"的建议
        #    等于答非所问。改成**正面告诉它我能答什么**，用户才知道下一步问什么。
        行.append("可以改问：某只股票的财务指标 / 实时行情 / 资金流 / K线，"
                  "某个板块的行情，某家公司的公告、股东、研报或快讯。")
    if 建议:
        行.append(建议)
    return "\n".join(行)


