# 量纲换算因子（知识点 3 的核心）：工具给"百万元"，答案写"亿元"，比值就是 1e-2。
# 这里穷举常见量纲，避免为了一个单位写一堆特例。
# ⚠️ v5-6 修 bug：量纲因子表原来手写成 (1, 10, 100, 1000, 1e4, 1e8, 0.1, 0.01, 0.001, 1e-4, 1e-8)
#    —— **从 1e4 直接跳到 1e8，漏了 1e5 / 1e6 / 1e7**。
#    后果实测：工具返回"千元"、答案按用户偏好换算成"亿元"（÷1e5），匹配必然失败 →
#      「宝钢关联交易」里 152.94 / 139.34 亿元这类**合法换算被误判成编造**，
#      把无支撑断言率算高一截（12 个"无支撑"里有 4 个是误报）。
#    修法：别手写，直接生成 1e8 → 1e-8 全功率（元/千元/万元/百万元/亿元/十亿 一次覆盖）。
#    代价（诚实）：因子表越全，匹配越松 → 可能"碰巧"对上（如 5.95 对上 595,101）。
#      但容差仍是 max(0.01, |目标|*1e-3)，且该指标本就是**下界**，不是"无幻觉"的证明。
_因子 = tuple(10.0 ** e for e in range(8, -9, -1))


def _匹配串们(文本: str) -> list[str]:
    """抠出所有数值的**原始字符串**（去掉千分位逗号）。保留字符串是为了做"子串兜底"。"""
    出 = []
    for m in _数.finditer(文本 or ""):
        出.append(m.group(0).replace(",", ""))
    return 出


def _数值们(文本: str) -> list[float]:
    """从文本里抠出所有数值。负数、千分位、小数都吃。"""
    出 = []
    for s in _匹配串们(文本):
        try:
            出.append(float(s))
        except ValueError:
            pass
    return 出


def _末位(串: str) -> float:
    """数字字符串的"最后一位"数值 —— 也就是它**被舍入的粒度**。

    "4.02" → 0.01　"153" → 1　"3469.26" → 0.01　"0.26" → 0.01

    为什么要它：答案里的数字都是**四舍五入过**的，真正的误差上界就是"最后一位的一半"。
    容差只有建立在答案自己的粒度上，才是对的（v5-7 的教训，见 `_可支撑`）。
    """
    s = (串 or "").lstrip("+-")
    if "." in s:
        return 10.0 ** (-len(s.split(".", 1)[1]))
    return 1.0


def _可支撑(a: float, 池值: list[float], 池串: str, 容差: float | None = None) -> bool:
    """答案里的数值 a，能否在支撑池里找到对应。

    **三道闸**（顺序就是宽松度递增）：
      ① 量纲匹配：存在池中的 v 与因子 f，使 v * f ≈ a。
         这是主力——专治"工具给 346926（百万元），答案写 3469.26 亿元"。
      ② 子串兜底：str(int(a)) 是池中某个数值字符串的子串。
         这是**防误报**的——工具返回报告期 `20231231`，答案会写成 `2023-12-31`，
         于是 `12` 和 `31` 会被拆出来；子串规则能把它们认回去，否则会拦截好答案。

    ⚠️ **容差必须在"答案的单位"上比 —— 这是 v5-7 实测踩出来的第三个坑。**
       旧写法是 `目标 = a / f`，再拿 `max(0.01, |目标| * 1e-3)` 当容差。问题是 `|目标|`
       在"千元"量纲里可以放大到 1e5 倍，于是容差跟着变成 `0.1% × 402000 = 402 千元`；
       而答案把 `402,480 千元` 写成 `4.02 亿元`、舍入误差上界是 `0.005 亿元 = 500 千元` ——
       **舍入误差比容差还大，合法换算必然被判无支撑**。
       实测：宝钢关联交易 16 行销售数据里，有 11 行因此被误判成"编造"。
       新写法改成 `预测 = v * f`（把池里的数换算到答案单位再比），容差由调用方按
       **答案数字的舍入粒度**（`_末位(s) / 2`）传入 —— 量纲一致，误差口径一致。

    ⚠️ ①② 都**只比绝对值**，不比符号 —— 这是实测踩出来的：
       工具返回涨跌幅 `-0.26`，答案写「跌幅 0.26%」，符号由**中文词**（涨/跌）承担，
       数字本身是正的。若比符号，这类正确回答会被误判成"无支撑"。
       代价：答案把"跌 0.26%"写成"涨 0.26%"时，这里**抓不出来**
       （符号错了但数字对）——记在诚实清单里。
    """
    if not 池值 and not 池串:
        return False
    模 = abs(a)
    # ⚠️ 容差取**三项的最大值，全部在"答案的单位"上**：
    #    ① 0.01         —— 兜底下限（小数被截断时不至于太苛刻）
    #    ② 答案的舍入粒度/2 —— 答案写 4.02，真值可能在 [4.015, 4.025]
    #    ③ |a| × 1e-3   —— 相对容差：答案把 1234567 写成 1235000（舍到千位）时靠它
    #   为什么不只用③：v5-7 之前③是在 `模/f` 上算的，f=1e-5 时会被放大 1e5 倍，
    #     变成"答案的 10000%" ——形同虚设又方向错误。换成在 `模` 上算才等于"0.1%"。
    #   为什么不只用②：整数（如 1235000）的"末位"是 1，但它可能其实舍到了千位，
    #     只给 ±0.5 会把好答案判成无支撑（实测「风险提示」就这样被误拦）。
    允许 = max(0.01, 容差 or 0.0, 模 * 1e-3)
    for v in 池值:
        for f in _因子:
            预测 = abs(v) * f        # 把池里的数换算到**答案的单位**再比
            if abs(预测 - 模) <= 允许:
                return True
    try:
        整数串 = str(int(模))
    except (ValueError, OverflowError):
        return False
    # ⚠️ v5-22：子串兜底必须**边界独立**，否则两位小数会被长数字串"顺手认领"。
    #   实测（修百分比硬拦时暴露）：答案编造「净利率 23.8%、ROE 12.3%」，
    #   支撑里只有报告期 `20241231` —— 旧写法 `"23" in 池串` 命中（2024**23**1231 里就有 23）、
    #   `"12" in 池串` 也命中 → **两个编造的百分数被判成"有出处"**。
    #   两位数在 8 位报告期里几乎必然出现，这条兜底等于对 <100 的数形同虚设。
    #   ⇒ 要求整数串在池串里**前后都不是数字**（真正作为独立数值出现）。
    return bool(len(整数串) >= 2
                and re.search(r"(?<![\d.])" + re.escape(整数串) + r"(?![\d.])", 池串))


def _差值可支撑(a: float, 池值: list[float], 容差: float) -> bool:
    """答案里的数值 a，是不是**池中两个数之差**（换算到答案单位后）？

    【为什么必须有这条（2026-10-20 多角度评测跑出来的真 bug）】
      实测「宝钢股份2025年和2024年的营业收入对比」：工具返回 2025=100688078026.64、
      2024=118319040327.56，模型写「同比减少 176.31 亿元」——这是**正确的减法**，
      可工具里永远没有 176.31 这个值 → 判"编造" → **整条对比答案被硬拦**。
      「增减额 / 环比变动 / 差额」是投研里最常见的天然派生量，不认它等于系统性误杀对比类问题。

    【为什么敢认它，却**不**认"两数之商"】
      差值是**精确算术**且需要两个数同时存在，碰巧凑出来的概率极低；
      而比值/K线几百个价格两两组合能凑出任意百分比（会把护栏彻底废掉）。
      ⇒ 差值兜底**只对非百分比数值启用**（百分比仍走 `_比率该硬拦` 那条更严的规则）。
    ⚠️ 仍需 `池值 >= 10`（数据不足时不给这条兜底），并且容差仍按**答案自己的舍入粒度**。
    """
    import bisect
    模 = abs(a)
    排序 = sorted({abs(v) for v in 池值})
    if len(排序) < 2:
        return False
    for f in _因子:
        尺 = 模 / f if f else 0.0
        if 尺 <= 0:
            continue
        for x in 排序:
            需要 = x - 尺
            i = bisect.bisect_left(排序, 需要)
            for j in (i - 1, i, i + 1):
                if 0 <= j < len(排序) and abs((x - 排序[j]) * f - 模) <= 容差:
                    return True
    return False


# ⭐ 2026-10-20：**孤立比率不硬拦** —— 修前端实测的一条"好答案被拦"。
#
#   实测样本（用户截图）：「今日中国银行股票价格走势」→ A 通道，查了 market_clock /
#   查实时行情 / 查K线，25 个数值断言里只有 1 个（`1.7`）找不到出处 → 无支撑率 4%
#   → 但 v5-22 的"百分比一律硬拦"规则**只看单个数字**，直接把整条回答拦成【无法回答】。
#   用户看到的是"你查到了数据却不给我"，这是最伤体验的一种拒答。
#
#   【为什么 1.7 本来就找不到出处】
#     涨跌幅 / 振幅 / 换手率这类**派生比率**：工具返回的是"现价 5.40、昨收 5.31"，
#     比率是模型自己算的 `(5.40-5.31)/5.31 = 1.69%`。工具里**永远不会**有一条叫 1.7 的值。
#     把它算成"编造"，等于要求模型不许做任何算术 —— 那不现实也不合理。
#     （试过"用池里的任意两个数反推比率"来自动认领：**不能这么做**。
#        K线几百个价格两两组合能凑出任意百分比，等于把这条护栏彻底废掉。）
#
#   【和 v5-22 的编造案例怎么区分】
#     v5-22 那条真编造（净利率 23.8% + ROE 12.3%）：支撑池里**只有报告期**
#       （池值 < 10 个），而且无支撑率极高 → 两个条件都命中 → 照样硬拦。
#     本次这条：工具返回了几十上百个真实数值，只是差一个派生比率 → 放行。
#   ⚠️ 诚实记：这条会让"数据很足、只编一个比率"的情况漏拦（只计入无支撑率，不拦截）。
#      这是**有意选择的误差方向** —— 误杀整条好答案的代价，大于放过一个比率。
#
#   ⭐ 2026-10-20 收紧判据（多角度评测暴露：只看"无支撑率 ≥ 25%"会贴边横跳）：
#      · 实测「两年营收对比」有 4 个断言、1 个比率（降幅 14.9%）无支撑 → 率正好 25% → 被拦。
#        可那是**正确答案**（14.9% = 176.31/1183.19），只是模型自己算的。
#      · 而"中行负债率"那条 3 个断言、1 个错比率 → 33%。两条差 8 个百分点，
#        却一个是好答案、一个是真错 —— **单靠率阈值分不开**。
#     ⇒ 改成看**成串与否**：单发孤立比率一律不拦；比率成串（≥2 个）或率超一半、
#        或者支撑池根本没数据（<10 个值）时才拦。
#        依据：真编造不会只编一个（v5-22 是 23.8/12.3 两个、情形③ 是四个）。
_比率硬拦阈值 = 0.50      # 无支撑率过半 → 系统性编造，比率照拦


def _比率该硬拦(无支撑率: float, 池值数: int, 比率数: int = 1) -> bool:
    """答案是"系统性编造"还是"差一两个派生比率"？"""
    if 池值数 < 10:
        # 支撑池本身就没什么数据（比如只返回了报告期）→ 却在讲比率 → 这是编造
        return True
    if 比率数 >= 2:
        # 比率成串且都没出处 → 不是"顺手算了一个"，是整段在编
        return True
    return 无支撑率 >= _比率硬拦阈值


# ⭐ 2026-10-20 多角度评测：「今天大盘怎么样？」50 个断言里只有 1 个（8756.0）无出处
#   （无支撑率 2%），却因为 |8756| ≥ 100 触发硬拦 → **整条大盘行情被扔掉**。
#
#   病根和"孤立比率"完全一样：**`硬拦截阈值` 只看单个数字的大小，不看整体是不是系统性编造**。
#   一个数字大 ≠ 整条答案在编。
#
#   ⇒ 统一成一条：**整体无支撑率极低（≤5%）且断言够多（≥20）且支撑池有真实数据（≥10）时，
#      单个数不硬拦，只计入无支撑率指标**。
#      依据：真编造的答案是"成片没出处"，不会在 50 个数字里只错 1 个。
#   ⚠️ 页码例外**不受这条影响**：编造出处（第 N 页）性质最恶劣，多大都要拦。
_低错率豁免_率 = 0.05
_低错率豁免_断言数 = 20


def _算是孤立错(无支撑率: float, 断言数: int, 池值数: int) -> bool:
    """在这条答案里，这个无支撑数字是"孤立的错"还是"成片编造"？"""
    # ⚠️ 2026-10-20：这里必须容一个极小 epsilon —— **不是保险，是修 bug**。
    #   实测（「宝钢股份的十大流通股东有哪些？」）：40 个断言错 2 个，无支撑率 = 2/40。
    #   IEEE754 下 `2/40` = 0.05000000000000000277…（比 0.05 大一点点），
    #   于是 `0.1000... <= 0.05` 判 False → 判成"成片编造" → 137.96（模型自己算的
    #   "前三大合计持股"，96.28+29.82+11.86）被硬拦 → **一张正确的股东表整条被扔**。
    #   这类比值边界（1/20、2/40、3/60）在真实流量里非常常见，必须显式容错。
    return (无支撑率 <= _低错率豁免_率 + 1e-9
            and 断言数 >= _低错率豁免_断言数
            and 池值数 >= 10)


# 硬拦截阈值：只有**够大**的无支撑数字才值得把整条回答拦下来。
# 理由：>= 100 的基本是金额 / 市值 / 成交量 / 股数 —— 编造它们代价最大；
#       而 < 100 的常常是序号、条数、页码，误报率明显偏高，只计入指标不拦截。
硬拦截阈值 = 100.0

# ⚠️ 例外：**页码类数字无论多大都硬拦**。
#    这是 v5-5 实测补的一条规则：真实样本「宝钢股份的关联交易有哪些？」里，
#    模型写「来源：230521274.pdf 第79页」，但工具只返回过第 11/13/18/165 页。
#    79 < 100，按阈值不拦 —— 可这正是**编造出处**，性质最恶劣。
#    → 所以"第 N 页"里的 N 单独走一条硬拦规则，不受阈值保护。
_页码 = re.compile(r"第\s*(\d+)\s*页")


# ⭐ v5-20 概数识别 —— 「概述类回答允许合理约数」。
#   问题：模型把工具给的 5032 亿说成「约 5000 亿」是**合法的概述**，
#   旧口径却按答案自己的舍入粒度给容差（±0.5），差 32 就被判无支撑 → 整条回答被硬拦。
#   → 识别到近似标记时，把容差放宽到 **10% 相对容差**。
#   ⚠️ 只放宽到 10%：仍要求"贴近某个真实值"，编造量级（把 5000 亿说成 9000 亿）照样拦得住。
#   ⚠️ 只认**真·近似词**，不认"超过/不到/逾"这类**边界词** ——
#      边界词是"序关系"断言（可大可小），放宽它会放过"把 4800 说成超过 5000"这类夸大。
_概数前 = re.compile(r"(大约|大概|约为|将近|接近|约|近|≈|~)\s*$")
#   后标记允许中间夹一个量词（"5000 **亿**左右" 里 左右 与 5000 之间隔着"亿"）。
_概数后 = re.compile(r"^[^0-9]{0,4}(左右|上下|出头|多|余)")
概数相对容差 = 0.10


def 检查断言(回答: str, 支撑文本: str) -> dict:
    """把答案拆成"数值断言"，逐条检查是否有出处。**纯代码，无模型，同输入必同输出。**

    返回：
      - 全部:     答案里检出的数值断言（已剔除列表序号）
      - 无支撑:   找不到出处的那些（**这就是"瞎编"的量化口径**）
      - 需硬拦:   无支撑 且（|值| >= 硬拦截阈值 **或** 是「第 N 页」的页码）
      - 无支撑率: 无支撑 / 全部
    """
    清理 = _日期.sub("  ", _序号.sub("", 回答 or ""))
    # ⭐ v5-8：把这些数字里属于"标识符"（股票代码 / 年份）的**先剔掉**——
    #    它们不是数据断言，不该进 `全部`，也不该被要求"工具返回过"。
    答案串 = []          # [(数字串, 是否概数)]
    for m in _数.finditer(清理):
        if _是标识符(m, 清理):
            continue
        s = m.group(0).replace(",", "")
        # ⭐ v5-20：就地判"这个数是不是概数"（看它前后 8 字窗口里有没有近似词）。
        前文 = 清理[max(0, m.start() - 8):m.start()]
        后文 = 清理[m.end():m.end() + 8]
        概 = bool(_概数前.search(前文) or _概数后.search(后文))
        # ⭐ v5-22：**百分比单独标记** —— 它不享受 `硬拦截阈值=100` 的豁免。
        #   原因（用户是做财务打分的，这条对他最致命）：
        #     毛利率 45.6% / 资产负债率 61.2% / ROE 12.3% —— **全都 < 100**，
        #     按旧规则一律不进"需硬拦"，只有金额级别的编造才拦得住。
        #     等于"编造一个百分数能过大半护栏"。
        #   识别口径：数字紧跟 % / ％ / "个百分点"，或**前文**是"占比/比重/率="这类
        #     比率引导词（防"四十五点六"这种没带 % 的写法漏网）。
        后二 = 清理[m.end():m.end() + 3]
        是百分比 = (后二.startswith(("%", "％")) or "百分点" in 后二
                    or (bool(re.search(r"(占比|比重|比例|率)\s*[:：=为]?\s*$", 前文))
                        # 市盈率/市净率/市销率 是**倍数**不是百分比，别混进来
                        and not re.search(r"(市盈率|市净率|市销率)\s*$", 前文)))
        答案串.append((s, 概, 是百分比))
    支撑串 = _匹配串们(支撑文本 or "")
    池值 = []
    for s in 支撑串:
        try:
            池值.append(float(s))
        except ValueError:
            pass
    池串 = "|".join(支撑串)
    页码集 = {float(m.group(1)) for m in _页码.finditer(清理)}

    全部, 无支撑, 需硬拦 = [], [], []
    比率待定 = []        # 无支撑的**百分比**：是否硬拦要看整体，先攒着
    大数待定 = []        # 无支撑的**大数字**（≥硬拦截阈值）：是否是孤立错也要看整体
    差值豁免 = 0         # 被"两数之差"兜底认领的个数（观测用）
    孤立豁免 = 0         # 被"低错率豁免"放行的大数字个数（观测用）
    for s, 概, 是百分比 in 答案串:
        try:
            a = float(s)
        except ValueError:
            continue
        全部.append(a)
        # ⚠️ 容差按**这个数字串自己的舍入粒度**给：最后一位的一半（至少 0.01）。
        #    不能只用 |a|*1e-3 的相对容差 —— 量纲一换算就出事（见 _可支撑 的注释）。
        半位 = max(0.01, 0.5 * _末位(s))
        # ⭐ v5-20：概数放宽容差（10% 相对）—— 「约 5000 亿」不是编造，是概述。
        容差 = max(半位, abs(a) * 概数相对容差) if 概 else 半位
        if _可支撑(a, 池值, 池串, 容差=容差):
            continue
        # ⭐ 2026-10-20：**差值兜底** —— 「同比减少 176.31 亿」是合法减法，不是编造。
        #    只对**非百分比**启用（比值另有 `_比率该硬拦` 那条更严的规则），且要求池值 ≥ 10。
        if (not 是百分比) and len(池值) >= 10 and _差值可支撑(a, 池值, 容差):
            差值豁免 += 1
            continue
        无支撑.append(a)
        # ⭐ v5-22：百分比**一律进硬拦**（不受 100 阈值保护）。
        #   注释里原本的理由是"<100 的多是序号/条数/页码，误报率高" —— 这个理由对
        #   **序号**成立，对**比率**完全是反的：比率是财务结论本身，编造的代价和金额同级。
        #   序号在上面的 `_序号.sub` 和 `_是标识符` 里已经剔过一轮，这里的百分比不会再混入。
        # ⭐ 2026-10-20 修正：改成**先攒后判** —— 见 `_比率该硬拦`（孤立派生比率不该拦整条）。
        if a in 页码集:
            需硬拦.append(a)          # 页码=编造出处，性质最恶劣，**永不放行**
        elif abs(a) >= 硬拦截阈值:
            大数待定.append(a)        # 大小不是理由，要看整体是否成片编造（见 _算是孤立错）
        elif 是百分比:
            比率待定.append(a)
    无支撑率 = (len(无支撑) / len(全部)) if 全部 else 0.0
    孤立错 = _算是孤立错(无支撑率, len(全部), len(池值))
    if 大数待定:
        if 孤立错:
            孤立豁免 = len(大数待定)
        else:
            需硬拦.extend(大数待定)
    比率豁免 = 0
    if 比率待定:
        if _比率该硬拦(无支撑率, len(池值), len(比率待定)):
            需硬拦.extend(比率待定)
        else:
            比率豁免 = len(比率待定)
    return {
        "全部": 全部,
        "无支撑": 无支撑,
        "需硬拦": 需硬拦,
        "无支撑率": 无支撑率,
        # ⭐ 观测用：被"孤立比率"规则放行的个数（前端/回归都能看出护栏有没有在乱拦）
        "比率豁免": 比率豁免,
        # ⭐ 观测用：被"两数之差"兜底认领的个数（增减额/差额类派生数）
        "差值豁免": 差值豁免,
        # ⭐ 观测用：被"低错率豁免"放行的大数字（50 个断言里错 1 个 ≠ 整条在编）
        "孤立豁免": 孤立豁免,
    }


