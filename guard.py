# ⭐ 补丁（本地修复）：**会话自指**（问"我前面问了什么""我们刚才聊到哪"）
#
#   【为什么】这是「域外判定」的**又一例误伤**（前端实测）：
#     「我前面问了什么问题」→ 域内词表里没有"前面/刚才/问题" → `_域内()` False
#     → 判「域外」直接拒答。可它问的是**这段对话自己**，系统有完整记忆
#     （thread 里的 messages 就在 state 里），完全答得了。
#     这跟当初「你有哪些能力」被误拒是**同一类**：把"本系统/本会话自己"当成了外部话题。
#
#   【和「域外」的分界】
#     域外   = 与投研无关的**外部话题**（天气/电影/菜谱）。
#     会话自指 = 话题**就是这段对话**——它有确定答案（前文记录），必须答。
#
#   【判据】"回顾词"(前面/刚才/之前/上面/刚刚…) 与 "回顾诉求"(问/说/聊+什么/啥/问题/内容)
#     两边至少命中一边，且**必须带回顾词**（否则「我买了什么股票」会被误收）。
#     纯「我们聊到哪了」没有回顾词 → 单独给一条分支。
# ══════════════════════════════════════════════════════════════
_回顾词 = r"(?:前面|刚才|之前|上面|刚刚|先前|上一(?:条|句|轮|个)|一开始|最开始)"
_会话自指 = re.compile(
    # 我们聊到哪（了）
    r"(?:我|我们).{0,6}(?:聊|说|问)到(?:哪|哪里)"
    r"|"
    # 我问了什么 / 我说了啥
    r"(?:我|我们).{0,6}(?:问|说|聊)(?:了|过|的)?(?:什么|啥|哪些)"
    r"|"
    # 前面问的是什么 / 刚才说了啥 / 上一轮提了什么
    r"(?:" + _回顾词 + r").{0,10}(?:问|说|聊|提)(?:了|过|的)?(?:什么|啥|哪些|问题|内容|话)"
    r"|"
    # 我前面的问题 / 刚才那个话题
    r"(?:我|我们)?.{0,4}(?:" + _回顾词 + r").{0,8}(?:问题|话题|内容|话|提问)"
    r"|"
    # 问的什么来着（诉求在前、回顾词在后）
    r"(?:问|说|聊)(?:了|过|的)?(?:什么|啥).{0,8}(?:" + _回顾词 + r")"
)

