# ⭐ v5 第 17 讲补丁：**系统自述**（问本系统自己有什么能力/工具/怎么用）
#
#   【为什么必须单独有一类】
#     这是 v5-16「域外判定」上线后**立刻暴露的误伤**（前端实测）：
#       「你有哪些能力」/「你有什么工具」→ 没有**任何投研信号** → 被判「域外」→ **拒答**。
#     但这类问题**完全合理**：用户第一次打开系统，就想知道"你能干什么"。
#     把它当域外拒掉，等于"你问我能力，我回答你没资格问"——体验最差的一种。
#
#   【和「域外」的分界】
#     域外 = 与投研无关的**外部话题**（天气/电影/菜谱）。
#     自述 = 话题**就是本系统自己** —— 它有确定答案（能力清单），必须答。
#
#   【判据】要**同时**有「自指」和「自述诉求」，两边缺一不可 ——
#     只认"你"会把「你能查宝钢的营收吗」误判成自述（那是**询问能力**不是**介绍能力**），
#     好在那种句子带标的，会先被 A 通道接走（本规则放在 A/D 之后）。
# ══════════════════════════════════════════════════════════════
_自指 = r"(?:你|您|本系统|这个系统|这套系统|该系统|这个助手)"
_自述诉求 = (r"(?:有什么|有哪些|能做(?:什么|啥|些什么)|能干什么|会(?:什么|啥)|都会啥|"
              r"是(?:什么|谁)|叫什么|啥功能|介绍一下|自我介绍|怎么用|如何使用|"
              r"使用说明|帮助文档|支持(?:哪些|什么)|能帮(?:我)?(?:做|干)(?:什么|啥)|"
              # ⭐ 2026-10-20 真实流量补：**否定式/反问式**的能力询问同样是在问"你能干什么"。
              #   实测「你不能提供策略吗」被判「域外」拒答 —— 但它问的正是本系统能力边界，
              #   有确定答案（"我不给买卖建议，但能给数据"），必须走 D 自述作答。
              r"能(?:不能|否)?提供|可以提供|能提供(?:什么|哪些)|"
              r"有没有(?:能力|工具|策略|办法)|会不会(?:分析|看盘|选股)|"
              # ⭐ 2026-10-20 多角度评测：「你能查哪些数据？」被判「域外」拒答 ——
              #   它问的是本系统的**数据覆盖范围**，有确定答案（清单），是典型自述题。
              #   「查哪些/查什么/有哪些数据」是最自然的能力问法，之前一个都没有。
              r"查(?:哪些|什么|得到哪些)|有哪些数据|支持(?:哪些|什么)数据|提供(?:哪些|什么)数据)")
_自述 = re.compile(
    r"(?:" + _自指 + r".{0,12}" + _自述诉求 + r")"
    r"|"
    r"(?:" + _自述诉求 + r".{0,12}" + _自指 + r")"
    r"|"
    r"(?:使用说明|自我介绍|帮助文档)"
)

