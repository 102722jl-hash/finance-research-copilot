# ⭐ v5 第 10 讲：**行业 / 主题类**（趋势·前景·格局·竞争·动态·进展…）
#
#   实测（把 83 条真实问句按规则跑分诊）：**62 条全落进 B 通道**。
#   这是"体验差"的真正来源 —— B 通道的两条规矩对这类问题是**错配**：
#     · B 要求"每一句事实都必须来自工具并标出处" → 模型被迫去调 查快讯/查研报；
#     · B 只有 2 轮上限 → 调到第 2 轮还没命中就"认输"
#       → 用户看到的是「连续调用工具2轮仍未收敛」这种**内部术语**。
#   可这些问题（"医疗器械行业的发展趋势""半导体有哪些新动态"）本质是
#   **概念/资讯类** —— 问的是"这个领域大致什么样"，不是"某家公司的某个数"。
#   它们该和 D 通道同路：**用通用知识/公开资讯给结构性回答，并标明来源**。
#
#   判据：命中一个「主题对象」（行业/产业/技术/领域…）**且**命中一个
#   「主题诉求」（趋势/前景/竞争/动态/方向…），**且没有具体公司标的**
#   （有标的的问题优先交给 A/B，别被主题规则抢走）。
#   ⚠️ 要求"无标的"是关键：「东吴证券有哪些关键行业」有标的 → 不归主题类。
# ══════════════════════════════════════════════════════════════
#   ⚠️ 主题对象**不含裸"市场"** —— 实测「今天市场上有哪些涨停的股票」会被
#      "市场 + 有哪些" 误拉进 D（那是**数据查询**，该走 B/A）。宁可少收，不可错收。
_主题对象 = r"(行业|产业|产业链|赛道|领域|概念|板块|技术)"
_主题诉求 = (r"趋势|前景|格局|竞争|动态|进展|应用|挑战|机会|方向|发展方向|"
             r"变化|情况|怎么样|如何|有哪些|是什么|动向|风口|景气")
# ⚠️ 两边都要用 **(?:...)** 包住再拼 `|` —— 否则 `|` 会把整串在最外层劈成若干**独立分支**，
#    "如何" 这种诉求词就变成能**裸匹配**（实测踩到：「亨迪药业表现如何 明天趋势」里的"如何"
#    命中主题趋势 → 本该拒答的预测句被放行）。这是正则拼接最容易翻车的地方。
_主题趋势 = re.compile(
    r"(?:" + _主题对象 + r".{0,12}(?:" + _主题诉求 + r"))"
    r"|"
    r"(?:(?:" + _主题诉求 + r").{0,12}(?:" + _主题对象 + r"))"
)

