def _域内(问题: str) -> bool:
    """问题里是否沾到**任何**投研信号。全无 → 域外（交给 C 拒答）。"""
    return (_有标的(问题)
            or _有信息类型(问题)
            or bool(_主题趋势.search(问题))
            or bool(_知识解释.search(问题))
            or bool(_域内词.search(问题))
            or bool(_海外标的.search(问题))
            # ⭐ 2026-10-20 边界审计：**豁免表必须同时算作域内**，否则会出现逻辑悖论。
            #   实测「下个月的解禁名单」：`_日历事实` 认它、替它豁免了"越界预测"，
            #   回头 `_域内` 却不认它 → 判"与投研无关"拒答。
            #   既说它"不是预测"，又说它"跟投研无关" —— 两张表各管一段，漏一边就自相矛盾。
            #   结论：凡是系统愿意**豁免**的，就已经承认它是域内，必须放行。
            #   （代价：`什么时候`/`计划` 这类通用词会让极少数域外问题落到 B ——
            #     但按项目定下的"宁可多走一轮 B，也绝不误拒"原则，这是正确的一侧。）
            or bool(_日历事实.search(问题))
            or bool(_规划事实.search(问题))
            # ⭐ 2026-10-20：**名称表外的公司简称**（「新光制药」「云飞励天」）也算域内 ——
            #   它们是"一个具体标的"，该由 B 通道回"没找到，请给全称/代码"，而不是说"与投研无关"。
            or _疑似标的短句(问题)
            )


