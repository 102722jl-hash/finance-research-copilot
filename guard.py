# ③ 越界检测（作用在**答案**上，不是问题上）
# ══════════════════════════════════════════════════════════════
_答案越界 = re.compile(
    r"建议(买入|卖出|加仓|减仓|持有|建仓)|"
    r"推荐(买入|卖出|持有|这只|该股)|"
    r"(可以|值得|适合|应当|应该)(买入|卖出|买入并持有|持有|投资)|"
    r"预计(会|将|有望)?(涨|跌|上行|下行)|预计股价|"
    r"我个人认为|个人观点|我的判断是|综上建议"
)

# 「引用型」表述：**只有在原文不是机构观点时**才算越界。
# ⚠️ 2026-10-20 实测事故（「宝钢股份最近有哪些研报？」）：
#    工具原文表头是「【券商研报】…」→ 豁免生效、`_抹引用片段` 也跑了，
#    但模型是用**普通段落**写的「多家券商给出目标价 8.5 元、评级买入」——
#    没有引号、不是表格行、不含【机构名】→ 抹不掉 → 照样命中「目标价」→ 整条被拒答。
#    根因不在"抹不干净"，而在**判据本身过宽**：
#      用户问「有哪些研报」，答案里出现「目标价/评级」是这个任务的**正常产出**；
#      真正的越界是**系统自己给建议/预测**，不是复述机构的观点。
#    ⇒ 拆成两组：
#      · 主张型（`_答案越界`）：任何场景都不许 —— "建议买入""我个人认为""预计将上涨"；
#      · 引用型（本组）：机构观点场景放行，其余场景照拦。
#    安全性：真越界问题（"该不该买宝钢"）的工具原文里**没有**研报标记，
#      走的是"引用型也扫"的分支 → 拦截能力一点没减弱。
_答案越界_引用型 = re.compile(r"目标价|上看|下看|评级|建议(关注|配置)|推荐(关注|配置)")
# ⚠️ `建议关注` / `建议配置` 为什么归引用型（2026-10-20 第二次实测）：
#    券商研报的评级话术里「建议关注」「建议配置」是**标准表述**，
#    用户问"有哪些研报"时出现它，属于转述机构观点 → 不该拦。
#    但它们在非机构观点场景（"建议关注这只股票"）依然是越界 → 引用型在那边照扫。
#    而 `建议买入/卖出/加仓/减仓/持有/建仓` 是**动作性主张**，任何场景都必须拦。


_引号片段 = re.compile(r"[《「『\"]([^》」』\"]{0,160})[》」』\"]")
_表格行 = re.compile(r"(?m)^\s*\|.*\|\s*$")
_机构条目行 = re.compile(r"(?m)^.*【[^】]{2,24}】.*$")

# 「机构观点」类工具原文的标志（`查研报` / `查快讯` 的固定表头）
_机构观点源 = ("券商研报", "机构观点", "机构评级")


def _抹引用片段(文本: str) -> str:
    """抹掉**引用来的**片段，只留下"系统自己说的话"。

    ⚠️ 2026-10-20 实测事故（「宝钢股份最近有哪些研报？」）：
       研报标题形如「…钢铁行业龙头，目标价 8.50 元」——模型**照抄标题**，
       `检测越界` 命中「目标价」→ 整条答案被判越界拒答。
       **引用别人的观点 ≠ 系统自己在给价格预测**，这两件事必须分开。

    抹三类：
      ① 引号/书名号里的内容（`《…》`「…」『…』"…"）—— 引用语气最明确；
      ② markdown 表格行 —— 研报/快讯列表天然是表格，且表格里的词序不构成主张；
      ③ 含 `【机构名】` 的行 —— `查研报` 返回的固定格式（`· 2026-09-09 【开源证券】…`）。
    """
    s = _引号片段.sub("〔引用〕", 文本 or "")
    s = _表格行.sub("〔表格〕", s)
    s = _机构条目行.sub("〔引用〕", s)
    return s


def 检测越界(回答: str, 原文: str = "") -> list[str]:
    """扫答案里有没有"建议/预测"类表述。返回命中的词（可能为空）。

    `原文` 传工具返回：**只有原文是「机构观点」类**（研报/快讯）时才做引用豁免 ——
    这样"该不该买宝钢"这种真越界问题不受任何影响（原文里没有研报标记）。

    豁免是**两级**的（2026-10-20 补第二级）：
      ① 抹掉引用片段（引号 / 表格行 / 【机构名】行）—— 抓"照抄标题"；
      ② **引用型词（目标价/上看/下看/评级）在机构观点场景直接不算越界** ——
         抓"用普通段落转述机构观点"这种抹不掉的写法。
         主张型词（建议买入 / 我个人认为 / 预计将上涨）任何场景都照拦。
    """
    扫 = 回答 or ""
    机构源 = bool(原文) and any(k in 原文 for k in _机构观点源)
    if 机构源:
        扫 = _抹引用片段(扫)
    命中 = {m.group(0) for m in _答案越界.finditer(扫)}
    if not 机构源:
        命中 |= {m.group(0) for m in _答案越界_引用型.finditer(扫)}
    return sorted(命中)


