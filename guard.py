# ⭐ 2026-10-20 多角度评测抓到的真 bug：**追问被判域外**
#
#   实测「宝钢股份2025年资产负债率是多少？」→ 正常 answered；
#   紧接着「那2024年呢？」→ **判「域外」拒答**。
#   原因：分诊是**纯函数**，只看当前这句 —— 而追问天然没有任何投研词。
#   真实流量集里追问的 C 率一直是首轮的 3~4 倍（2.9% vs 10.3%），根子就在这。
#
#   【为什么不能靠"记住上一轮"】
#     `分诊(问题)` 签名固定、且金标准集大量直接拿它做单测。改签名会连坐一大片。
#     ⇒ 这里只做**形状判据**：短句 + 反问尾巴 + 指代词 → 认为"它依赖上文"，
#       于是**只把「域外」升级成 B**（B 通道本来就能读会话历史），
#       **越界判定完全不动**（买卖建议该拒还是拒，它先于域外判定）。
#   ⚠️ 代价：「那天气呢」这种也会从域外变 B（多一轮 LLM，模型会说"这超出投研范围"）。
#      按项目"宽进严出"原则，这是安全的一侧。
# ══════════════════════════════════════════════════════════════
_追问指代 = re.compile(r"那|换成|改看|它|这个|这只|这家|上面|刚才|同样|还有|其中")
_追问尾 = re.compile(r"(?:呢|吗)\s*$")

# ⭐ 2026-10-20 长会话实测：上面那条「长度+呢/吗+指代」三条件**太窄**，漏掉一整类追问。
#    实测事故（同一 session 连问 8 轮）：
#      [4]「同比变化多少？」（上一轮刚问完净利润）→ 判**域外**拒答
#      [8]「把上面这些数据汇总成一张表」→ 判**域外**拒答
#    两者都只差一个条件：「同比」不在 `_追问指代` 里、结尾也不是呢/吗。
#    业务上这两条是**最典型的上下文承接**（用户不想重复说标的和指标），
#    判成"与投研无关"，等于把多轮对话最常见的用法拒之门外。
#    ⇒ 补一条**并列**的判据：短句里只要出现"强承接词"就够，不必凑齐三条件。
#    「强承接词」的选取标准：**脱离上文就说不通**的词 —— 比较级（同比/环比）、
#      指位（上面/上述/这些数据）、归纳动作（汇总/整理成表/加起来）。
#      不含"多少钱/怎么样"这种单轮也成立的泛问，避免把真域外问题放进来。
_追问承接 = re.compile(
    r"上面|上述|以上|前面|刚才|这些数据|那些数据|该股|该公司|"
    r"同比|环比|"
    r"汇总|整理成|合并成|做成表|列个表|加起来|总共|一共"
)


def _像追问(问题: str) -> bool:
    """这句是不是"依赖上文的追问"？（只用于把域外升级成 B，不用于别的判断）"""
    文 = (问题 or "").strip().rstrip("？?").strip()
    if not (2 <= len(文) <= 20):
        return False
    # ① 原判据：短句 + 呢/吗 结尾 + 指代词（「那2024年呢？」）
    if _追问尾.search(文) and _追问指代.search(文):
        return True
    # ② 新判据：短句 + 强承接词（「同比变化多少？」「把上面这些数据汇总成一张表」）
    return bool(_追问承接.search(文))


def _有信息类型(问题: str) -> bool:
    return bool(_指标词 and any(k in 问题 for k in _指标词)) \
        or bool(_行情词.search(问题)) or bool(_公告词.search(问题)) \
        or bool(_派生词.search(问题))       # v5-13 补：ROE / 净资产收益率 / 每股净资产


def _去名(问题: str) -> str:
    """把问题里的**公司名**抹掉，得到"只剩诉求"的版本。

    ⭐ v5 第 10 讲修一处误伤：`_越界预测` 里有裸的 `未来`，于是
      「**德尔未来**」（002631，公司名）被当成"价格预测" → 直接拒答。
      先把全市场公司名删掉再判预测词，"德尔未来"就变成空串，不再误伤；
      而「中安科**未来**的走势」删名后剩"未来的走势" → 仍是预测，该拒。
    ⚠️ 只在判"越界词"时用这个版本，别拿它去做别的判断。
    """
    出 = 问题
    for 名 in 名称表():
        if len(名) >= 3 and 名 in 出:      # ≥3 字，避免 2 字名过度删除
            出 = 出.replace(名, "")
    return 出


_分诊提示 = (
    "你是一个文本分类器。把用户问题分到下面四类之一，只输出一个 JSON，不要解释。\n"
    'A = 结构化查询：有明确标的（公司名/指数名/6位代码）且信息类型明确（财务指标/行情/公告/资金流等）。\n'
    'B = 需要组织语言的开放问题：比如原因分析、影响分析、概述、比较——但问题本身不要求预测或投资建议。\n'
    'C = 越界：要求投资建议（买不买、持不持有）、价格预测（会不会涨、目标价）、或无法验证的主观判断。\n'
    'D = 概念解释：问一个通用概念是什么/怎么算/什么区别（如「市盈率是什么」「RSI怎么算」），'
    '不指向某家公司的具体数据。\n'
    '输出格式：{"通道":"A"或"B"或"C"或"D","理由":"不超过20字"}'
)


def _LLM分诊(问题: str) -> dict | None:
    """让模型只吐一个 JSON。任何异常/解析失败都返回 None（调用方回退到 B）。"""
    try:
        回复 = _llm.invoke([SystemMessage(content=_分诊提示), HumanMessage(content=问题)])
        文本 = (回复.content or "").strip()
        m = re.search(r"\{.*\}", 文本, re.S)
        if not m:
            return None
        数据 = json.loads(m.group(0))
        通道 = str(数据.get("通道", "")).strip().upper()[:1]
        if 通道 not in ("A", "B", "C", "D"):
            return None
        出 = {"通道": 通道, "理由": str(数据.get("理由", ""))[:40], "判定": "LLM"}
        # ⭐ 2026-10-20 多角度评测抓到的真 bug：「宝钢股份的目标价是多少？」由 LLM 判进 C，
        #   但 `_LLM分诊` 不写 `子类` → 拒答文案退化成通用「C」、评测里也被记成"(无)"。
        #   LLM 的 C 定义**本来就只有"越界"一种**（买卖建议/价格预测/不可验证主观判断），
        #   域外根本不进 LLM（`not _域内()` 在 LLM 之前就 return 了）→ 这里补 `越界` 是对的。
        if 通道 == "C":
            出["子类"] = "越界"
        return 出
    except Exception:
        return None


def 分诊(问题: str, 允许LLM: bool = True) -> dict:
    """把用户问题分到 A / B / C / D 之一。**这是全流程唯一允许 LLM 做判断的地方。**

    顺序（规则优先，知识点 2）：
      1. 越界词命中        → C（不需要问模型，规则就够）
      2. 有标的 + 有信息类型 → A
      3. 行业/主题类（无标的）→ D（v5-10 新增：别再塞进 B 空转 2 轮后截断）
      4. 纯概念问法命中     → D（v5-8 新增：概念题不该被 B 的"必须查工具"卡死）
      5. 系统自述命中       → D（v5-17 补丁：问本系统能力/工具，**必须排在域外之前**）
      6. 无任何投研信号     → C（v5-16 新增：域外问题直接拒答，不进 LLM）
      7. 规则定不了         → 问模型（只让它回一个词）
      8. 模型也失败 / 关闭了 → B（**默认走受约束通道，这是安全的一侧**）
    """
    问题 = (问题 or "").strip()
    if not 问题:
        return {"通道": "C", "理由": "空问题", "判定": "规则"}
    if _越界建议.search(_去交易数据词(问题)):
        return {"通道": "C", "子类": "越界",
                "理由": "涉及买卖建议（无法验证，且越界）", "判定": "规则"}
    # ⚠️ v5-10 修两处过判：
    #   (a) 用 `_去名` 把公司名抹掉再判，"德尔未来"不再被裸 `未来` 误伤；
    #   (b) 命中「行业/主题类」的**产业趋势**（"5G产业未来的发展趋势"）不是价格预测，
    #       放行给下面的主题类 → D，别扣"预测"的帽子拒掉。
    # ⚠️ v5-18 再加一条豁免：命中「日历事实」（事件/会议/公告/披露…）时，
    #   "下周/明天"这类**弱时间词**不算预测 —— 问题问的是日程不是涨跌。
    if (_越界预测.search(_去名(问题))
            and not _主题趋势.search(问题)
            and not _日历事实.search(问题)
            and not _规划事实.search(问题)):
        return {"通道": "C", "子类": "越界",
                "理由": "涉及价格/走势预测（无法验证，且越界）", "判定": "规则"}
    if _有标的(问题) and _有信息类型(问题):
        return {"通道": "A", "理由": "有明确标的 + 明确信息类型", "判定": "规则"}
    # ⭐ 补丁（本地修复）：**会话自指**（"我前面问了什么问题""我们聊到哪了"）→ D 通道。
    #   ⚠️ 必须排在**知识解释之前**：像「我上一个问题**是什么**」会被 `_知识解释`
    #      的裸 `是什么` 先抢走 → 判成"概念解释"，答非所问（实测踩到）。
    #   也必须在**域外判定之前** —— 这类问题无投研信号，放后面会被误判域外拒答。
    if _会话自指.search(问题):
        return {"通道": "D", "子类": "会话",
                "理由": "会话自指（询问本会话/前文内容）", "判定": "规则"}
    # ⭐ v5-10：行业/主题类 → D。**必须在 A 之后、且要求"无标的"** ——
    #    有标的的问题优先走 A/B，不能被主题规则抢走。
    if _主题趋势.search(问题) and not _有标的(问题):
        return {"通道": "D", "理由": "行业/主题类（通用知识与公开资讯层面）", "判定": "规则"}
    # ⚠️ 放在 A 之后：像「宝钢股份的市盈率是多少」这类，标的清晰 → 仍走 A 去查数；
    #    只有**没有标的**的纯概念问法（「市盈率是什么」）才落到 D。
    if _知识解释.search(问题) and not _有标的(问题):
        return {"通道": "D", "理由": "概念解释类（通用知识，无需数据）", "判定": "规则"}
    # ⭐ v5-17 补丁：**系统自述**（"你有哪些能力""你有什么工具""你是谁"）→ D 通道。
    #    ⚠️ 必须在**域外判定之前** —— 这类问题没有任何投研信号，
    #       放后面会被域外规则误判成 C 拒答（v5-16 上线后在前端实测到的真回归）。
    if _自述.search(问题):
        return {"通道": "D", "子类": "自述",
                "理由": "系统自述（介绍本系统的能力与工具）", "判定": "规则"}
    # ⭐ v5-16：域外判定 —— 规则全不命中 + 无任何投研信号 → C 拒答。
    #    ⚠️ 放在 LLM **之前**：这是确定性的，不需要问模型；也让"天气/娱乐"这类
    #       问题**根本不进 call_model**（省一整轮 LLM + 无意义的工具调用）。
    #    放在**所有域内规则之后**：只要 A/B/D 任一条命中过，就走不到这里。
    # ⭐ 2026-10-20 多角度评测：**短追问**必须有兜底，否则「那2024年呢？」被判域外拒答。
    #   放在这里（域外之前、越界之后）是刻意的：
    #     · 在越界之后 → 「那明天会涨吗」仍被拦（越界优先）；
    #     · 在域外之前 → 只有"本来要判域外"的短追问受影响。
    if _像追问(问题):
        return {"通道": "B", "理由": "短追问（依赖上文，交由 B 通道结合会话作答）", "判定": "规则"}
    if not _域内(问题):
        return {"通道": "C", "子类": "域外",
                "理由": "与投研无关（域外，超出本系统能力范围）", "判定": "规则"}
    if 允许LLM:
        结果 = _LLM分诊(问题)
        if 结果:
            return 结果
    return {"通道": "B", "理由": "规则未命中，按受约束泛问处理", "判定": "兜底"}


