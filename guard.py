# ⭐ 2026-10-20 真实流量集补：**疑似标的短句**（名称表外的公司简称）
#
#   实测「新光制药」「云飞励天」「西变中特」「海南长兴」被判「域外」拒答，
#   但它们是**用户心里的一家具体公司**，只是名字不完全在名单里（笔误/改名/未收录）。
#   正确产品行为不是"与投研无关"，而是 **"没找到这个标的，请给全称或代码"** —— 那就该走 B。
#
#   判据（全部满足才放行，宁可漏放）：
#     · 长度 ≤ 8（超过就不是"一个名字"了）
#     · 纯中文（不含数字/英文/标点）
#     · 不以动作词开头（买/卖/查/看/写/讲/做/帮/给/算/教）
#     · 不含疑问词/语气词（什么/怎么/如何/为什么/哪/吗/呢/吧/多少/几/是否/能否）
#   ⚠️ 代价（诚实记）：像「红烧肉做法」这种 5 字纯中文名词也会落进 B，
#      多花一轮 LLM（模型会说"这超出了投研范围"）。换回 4 条真实公司简称，值。
# ══════════════════════════════════════════════════════════════
_短句动作头 = re.compile(r"^(?:买|卖|查|看|写|讲|做|帮|给|算|教|推荐|翻译|生成|介绍)")
_短句疑问 = re.compile(r"什么|怎么|如何|为什么|哪|吗|呢|吧|多少|几|是否|能否|可以|应该")


def _疑似标的短句(问题: str) -> bool:
    文 = (问题 or "").strip()
    if not (2 <= len(文) <= 8):
        return False
    if not re.fullmatch(r"[\u4e00-\u9fa5]+", 文):
        return False
    return not (_短句动作头.search(文) or _短句疑问.search(文))


