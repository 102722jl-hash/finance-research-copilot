# ④.5 部分降级：删掉"该拦的那几句"，保留其余
# ══════════════════════════════════════════════════════════════
def 剥离句(回答: str, 该删) -> tuple[str, list[str]]:
    """按句/行删：`该删(片) -> bool`。返回 (剩余文本, 被删内容)。

    粒度：**表格行整行判**（删半行会破坏表格），正文按句末标点切。
    """
    保留, 删 = [], []
    for 行 in (回答 or "").split("\n"):
        片们 = [行] if 行.strip().startswith("|") else \
            [p for p in re.split(r"(?<=[。；！？])", 行) if p]
        新 = []
        for 片 in 片们:
            if 该删(片):
                删.append(片.strip())
            else:
                新.append(片)
        if 新:
            保留.append("".join(新))
    return "\n".join(保留).strip(), 删


def 剥离含数句(回答: str, 数值们) -> tuple[str, list[str]]:
    """把答案里**含这些数值的句子/表格行**整句删掉，返回 (剩余文本, 被删内容)。

    为什么要它（2026-10-20 实测）：
      「分析一下宝钢股份2025年的经营情况」——模型写了一篇完整分析，
      **里面夹了一个自己算的比率**。`需硬拦数 > 0` → 整条被替换成
      「该比率并非工具返回（疑似模型自行计算），请先把该指标下沉到工具」
      → 用户问经营情况，拿到一句**给开发者看的内部话术**，没有任何数据。

    正确的降级是「**删掉那一句、保留其余**」：
      编造的比率一定不能给（那是财务结论，错了代价最大），
      但同一个答案里**有工具出处的营收/净利润/资产负债**应当照给。
      ⇒ 宁可少给一段，不要整篇作废。
    """
    目标 = set()
    for x in (数值们 or []):
        try:
            目标.add(round(float(x), 6))
        except (TypeError, ValueError):
            continue
    if not 目标:
        return 回答 or "", []

    def 该删(片: str) -> bool:
        for m in _数.finditer(片):
            try:
                if round(float(m.group(0).replace(",", "")), 6) in 目标:
                    return True
            except ValueError:
                continue
        return False

    return 剥离句(回答, 该删)


def 剥离含词句(回答: str, 词们) -> tuple[str, list[str]]:
    """把含**越界词**（建议买入/目标价…）的句子删掉，保留其余。

    2026-10-20：与 `剥离含数句` 同理 —— 「宝钢股份最近有哪些研报？」答案末尾
    模型自己加了一句「建议关注」，整条研报列表就被越界护栏废掉了。
    删掉那一句，研报清单照样是有用的。
    """
    词 = [w for w in (词们 or []) if w]
    if not 词:
        return 回答 or "", []
    return 剥离句(回答, lambda 片: any(w in 片 for w in 词))


