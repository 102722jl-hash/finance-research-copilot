# guard.py —— v5 第 5 讲：三通道分诊 + 断言溯源（把"不编造"从软约束变成硬规则）
#
# 【本讲要解决的根本问题】
#   v5-4 的评测暴露了两个数字：
#     · 真实流量里本系统只接得住 0.1% —— 剩下的不是"答错"，是"没有数据源"；
#     · 泛问（占 38.9%）这类问题**没有唯一正确答案**，所以"正确率"这个指标在它上面失效。
#   但"没有唯一正确答案"不等于"无法约束"。一个长答案不是一块石头，它是
#   **一堆原子断言拼起来的**——每一条都能单独判：
#       ① 事实型（数值/日期/事件）→ 必须有工具出处，没有就删
#       ② 推理型（比较/推导/因果）→ 前置事实必须都在上下文里
#       ③ 观点型（建议/预测/评价）→ 默认禁止输出
#   → 于是指标从"整体正确率"换成三个**可自动计算**的数：
#       可溯源率 / 无支撑断言率 / 越界率
#
# 【本讲的 6 个知识点】
#   1. **分诊层是唯一允许 LLM 做判断的地方**，而且它只做"分类"，不做"生成"。
#   2. **规则优先、LLM 兜底**：规则能定的事不要问模型——省一次调用，也多一分确定性。
#   3. **数值归一化**是溯源检查的技术核心：工具返回 346926（百万元），
#      答案写 3469.26 亿元，字符串比对必然失败 —— 必须按**量纲换算**比对。
#   4. **支撑池 = 工具原文 + 用户本轮问题**：用户自己说过的事实（比如"2023 年"）不算编造。
#   5. **拦截 ≠ 删除**：和 复核 节点一样，追加一条消息盖住原答案，保持 messages 可追溯。
#   6. **确定性检查也有盲区**（单字符数字、单位歧义），所以它是"护栏"不是"证明"——
#      诚实清单里要写清楚。

