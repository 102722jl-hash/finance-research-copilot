def _搜(query: str, 条数: int) -> list[dict]:
    """调 Tavily。所有第三方输出都重定向到 stderr，保住 stdout 这条协议通道。

    ⚠️ 加重试：实测国内直连 Tavily 偶发 `SSL: UNEXPECTED_EOF_WHILE_READING`
       （尤其连续调用时）。一次失败就返回"搜索失败"，模型会退化成"建议你自己去查"。
       这里退避重试 3 次，仍失败才抛。
    """
    import time

    from tavily import TavilyClient

    最后: Exception | None = None
    for i in range(3):
        try:
            with redirect_stdout(sys.stderr):
                客户端 = TavilyClient(api_key=_拿key())
                return 客户端.search(query=query, max_results=条数,
                                     search_depth="basic").get("results", [])
        except Exception as e:  # noqa: BLE001
            最后 = e
            time.sleep(0.8 * (i + 1))
    raise 最后 if 最后 else RuntimeError("Tavily 未知错误")


def _捞日期(文本: str) -> list[str]:
    """从正文里**捞**日期（Tavily 的 `published_date` 经常是空的，实测 6 条全是 None）。

    ⚠️ 为什么要在服务端做这件"脏活"：日期只藏在正文里（「发布日期：2026-08-25」
       或「截至8月21日」），让模型自己去 6 条摘要里找，它就会**挑错时点**（实测栽过）。
       这里用固定正则把候选日期抽出来，摆在结果里给模型看 —— 确定性的事别交给 LLM。

    只做"提示"不做"判定"：抽不出来就返回空列表，**绝不猜**。
    """
    import re
    模式 = [
        r"发布日期[：:\s]*(\d{4})[-/年](\d{1,2})[-/月](\d{1,2})",   # 发布日期：2026-08-25
        r"(\d{4})[-/年](\d{1,2})[-/月](\d{1,2})日?",              # 2026-08-21 / 2026年8月21日
        r"截至\s*(\d{1,2})月(\d{1,2})日",                          # 截至8月21日（无年份）
    ]
    出: list[str] = []
    for i, p in enumerate(模式):
        for 组 in re.findall(p, 文本):
            if i == 2:
                出.append(f"截至{组[0]}月{组[1]}日")
            else:
                y, m, d = 组
                出.append(f"{y}-{int(m):02d}-{int(d):02d}")
    # 去重保序
    见 = set()
    结果 = []
    for x in 出:
        if x not in 见:
            见.add(x)
            结果.append(x)
    return 结果[:6]


def _关键句(文本: str, 上限: int = 8, 实体: str = "") -> list[str]:
    """摘出含「数字 + 量词」的句子，**总量句 + 含实体词的句子优先** —— 数量类题目的答案几乎都在这些句子里。

    ⚠️ 为什么需要：实测那条官方页正文 1185 字，「境内外总数达 297 家，其中 A股 236 家」
       落在**第 722 字**；前 600 字全是市值、板块分布、境外 63 家。
       摘要截断 = 模型拿不到核心数字 → 于是去用了别处的 235。
    ⚠️ 为什么还要打分：简单取「前 N 句含数字的」会被市值/板块句占满（实测 6 句全被占），
       所以按「总数/累计/共有/境内外/达 X 家」加权，让总量句排到最前面。
    ⚠️ 为什么还要看实体词：一篇《江苏9月报告》里「江苏 A股总数 740 家」比「苏州 236 家」
       更像"总量句"，会被排到第一 → 模型把 740 当苏州家数。含实体词（如「苏州」）的句子加权。
    """
    import re

    句们 = re.split(r"[。！？；\n]", 文本 or "")
    打分: list[tuple[int, str]] = []
    见 = set()
    for s in 句们:
        s = s.strip(" 　·|")
        if not (8 <= len(s) <= 220) or s in 见:
            continue
        if not re.search(r"\d+\s*(家|只|亿元|万亿|万人)", s):
            continue
        分 = 0
        if 实体 and 实体 in s:
            分 += 3
        if re.search(r"(总数|累计|共有|合计|全市|境内外)", s):
            分 += 3
        if re.search(r"(达|为|共)\s*\d+\s*家", s):
            分 += 2
        if "截至" in s:
            分 += 1
        见.add(s)
        打分.append((分, s))
    # 稳定排序：同分保持原文顺序
    打分.sort(key=lambda x: -x[0])
    return [s for _, s in 打分[:上限]]


def _含总量(文: str) -> bool:
    """块里是否有「总量陈述」（总数/共有/合计…N 家）—— 数量类问题的答案判据。

    ⚠️ 只靠日期会把《苏州市IPO企业加速 年内已有16家企业上市》排到第一：
       它含「苏州」「上市」「公司」，日期又新，但讲的是 IPO 进程不是存量家数。
       「16 家」是**新增**不是**总数**，必须区分开。
    """
    import re

    return bool(re.search(r"(总数|共有|合计|累计|已达|达到|拥有)[^。；\n]{0,25}?\d+\s*家", 文 or ""))


def _时点去重(排好: list[dict], 实体: str) -> tuple[list[dict], str]:
    """同一实体 + 同一指标 + 多个时点 → **只留最新那一组**，其余整块拿走。

    ⚠️ 这是"答 284 而不是 297"的治本点（2026-10-19 实测）：
       两篇都含「苏州」+「总数/拥有 N 家」，排序键打平后只剩日期在比 ——
       但提示词"只取最新"实测**不稳**，模型仍会挑那篇标题更贴问法的旧文
       （《每10个新股就有1个来自苏州…2025年度新增A股数全国第一》，284/229，2026-01）。
       ⇒ 不要指望模型自觉。**在工具层把旧时点的总量块直接收走**，它就没得挑。
    保护：总量块不足 2 条时不动（宁可多给，不可误杀）。
    """
    def 文(r):
        return (r.get("title") or "") + (r.get("content") or "")

    总量块 = [r for r in 排好
              if r.get("_日期") and _严格总量句(文(r), 实体)]
    if len(总量块) < 2:
        return 排好, ""

    总量块.sort(key=lambda r: r["_日期"], reverse=True)
    最新日 = 总量块[0]["_日期"]
    # 🔴 折叠基准**不能只看"日期最新"** —— 媒体的新文会盖过官方旧文，这正是本次的坑：
    #   官方 297/236(2026-08-25) 被媒体 238(2026-09-30) 顶掉，用户直接指出"238 不是真实数据"。
    #   做法：在"最新日往前 120 天内"的总量块里挑**权威分最高**的当基准（同分再比日期）。
    #   超过 120 天的官方旧文不参与竞争 —— 否则 2023 年的官方页会把今年的媒体数全删掉，答成旧数。
    近 = [r for r in 总量块 if _天内(r["_日期"], 最新日) <= 120]
    基准 = max(近, key=lambda r: (_权威分(r.get("url") or "", r.get("title") or ""), r["_日期"]))
    基日 = 基准["_日期"]
    删id = {id(r) for r in 总量块 if r is not 基准}
    if not 删id:
        return 排好, ""

    最早 = min(r["_日期"] for r in 总量块)
    留 = [r for r in 排好 if id(r) not in 删id]
    _源 = "官方" if _权威分(基准.get("url") or "", 基准.get("title") or "") >= 3 else "媒体"
    return 留, (f"另有 {len(删id)} 条**同一指标但来源更弱 / 时点更早**的报道"
                f"（{最早} ~ {最新日}）已省略；该指标只采用 {基日} 的**{_源}口径**那一组数字。")


# ── 来源权威性：数量题的最终答案用谁的数据，由它决定 ──────────────────────
#   🔴 2026-10-19（用户当场指出「238 不是真实数据」）：
#     官方的 297/236（苏州市政府，2026-08-21）被媒体更新的 238（21经济网，9-30）挤掉。
#     238 本身不是编的（236 + 9月新增2家 = 238，与该文自述一致），但**口径是"境内A股"**，
#     而用户问的是"上市公司"（默认境内外合计 = 297）。
#   ⇒ 官方是统计口径的定义者，媒体转载常混口径 ⇒ **权威性排在时点之前**。
_官方域 = ("gov.cn", "sse.com.cn", "szse.cn", "bse.cn", "csrc.gov.cn",
          "stats.gov.cn", "pbc.gov.cn", "cninfo.com.cn")
_头部媒体域 = ("xinhuanet.com", "people.com.cn", "stcn.com", "cs.com.cn",
              "21jingji.com", "caixin.com", "yicai.com", "cls.cn", "jjckb.cn")
_官方标题词 = ("人民政府", "政府网", "政府门户", "交易所", "统计局", "证监局", "证监会")


def _权威分(url: str, title: str = "") -> int:
    """来源权威性：3 = 官方（政府/交易所/统计局/证监系统），2 = 头部财经媒体，1 = 其他。"""
    u = (url or "").lower()
    t = title or ""
    if any(d in u for d in _官方域) or any(k in t for k in _官方标题词):
        return 3
    if any(d in u for d in _头部媒体域):
        return 2
    return 1


def _天内(a: str, b: str) -> int:
    """两个 ISO 日期相差多少天；任一个解析不了就返回 9999（视为"不在近期"）。"""
    from datetime import date

    try:
        return abs((date.fromisoformat(a) - date.fromisoformat(b)).days)
    except Exception:
        return 9999


def _相关词(query: str) -> list[str]:
    """把 query 切成 2 字中文片段（去重保序），用于算块与问题的相关度。

    噪音片段（如「州多」「个上」）在正文里基本不出现，不会虚增得分；
    真正起作用的「苏州」「上市」「数量」会稳定命中。
    """
    import re

    q = re.sub(r"[^\u4e00-\u9fa5]", "", query or "")
    return list(dict.fromkeys(q[i:i + 2] for i in range(len(q) - 1)))


# 实体词排除表：这些片段在结果里几乎 100% 出现，选它当"实体"等于没选。
#   ⚠️ 实测事故：query「南京有多少家上市公司」，按"覆盖率最高"挑到了「上市」，
#      于是《江苏共有上市公司 741 家》被判定为"南京的总量句"，【建议采用】直接给了 741。
_实体停用 = frozenset({
    "上市", "市公", "公司", "数量", "家数", "多少", "几家", "总数", "一共",
    "总共", "市场", "行业", "企业", "情况", "最新", "目前", "现在", "今年",
    "去年", "我国", "全国", "数据", "统计", "如何", "怎么", "哪些", "什么",
    "多少家", "有多少", "是多少", "多少个",
})


def _实体词(query: str, 块们: list[dict]) -> str:
    """从 query 里挑出"实体词"（苏州 / 无锡 / 南京…），用于判断"总量句说的是谁"。

    ⚠️ 为什么需要：排序只看日期会被**别的对象的最新文章**劫持 ——
       实测 query「苏州 上市公司 数量 2026年」的最新块是《江苏A股公司总数达 740 家》
       （省级数据、9 月末），它日期最新就被排到第一，模型很容易把 740 当成苏州家数。
    ⚠️ 挑法（两版都踩过坑，最终用这个）：
       · 第一版按「30%~90% 覆盖率」筛 → 只返回 3 条时「苏州」覆盖 100% 被误排除；
       · 第二版按「覆盖率最高 + 同分取位置靠前」→ 「上市」「公司」覆盖 100% 直接胜出，
         南京那道题因此拿江苏 741 家当南京答案。
       ⇒ 现在：**按 query 中的先后顺序**扫，取第一个"覆盖率 ≥60% 且不在停用表"的片段。
         问句开头的词通常就是实体；停用表把「上市/公司/数量」这类拦掉。
       挑不出来就返回 ""，**不降权**（宁可不管，也不误杀）。
    """
    import re

    q = re.sub(r"[^\u4e00-\u9fa5]", "", query or "")
    片段们 = list(dict.fromkeys(q[i:i + 2] for i in range(len(q) - 1)))
    if not 片段们 or not 块们:
        return ""
    文本们 = [(r.get("title") or "") + (r.get("content") or "") for r in 块们]
    总 = len(文本们)

    for w in 片段们:
        if w in _实体停用:
            continue
        if sum(1 for t in 文本们 if w in t) / 总 >= 0.6:
            return w

    # 兜底：覆盖率最高的（不再按位置，因为没有达标项）
    得分 = []
    for i, w in enumerate(片段们):
        if w in _实体停用:
            continue
        比 = sum(1 for t in 文本们 if w in t) / 总
        if 比 >= 0.3:
            得分.append((比, -i, w))
    if not 得分:
        return ""
    得分.sort(reverse=True)
    return 得分[0][2]


def _URL日期(url: str) -> str:
    """从 URL 路径里兜底取日期（`/202601/`、`/2026/07/07/`）。

    ⚠️ 实测那条 284 的旧文（`.../szyw/202601/1f49b0fd...`）正文里**没有任何日期格式**，
       `published_date` 也是 None → `_日期` 为空 → 排序/去重全都漏掉它
       （它于是稳坐"无日期"组，被模型当成没时点的资料直接引用）。
       URL 里的 `YYYYMM` 是最后一道兜底。
    """
    import re

    u = url or ""
    m = re.search(r"/(20\d{2})/(0[1-9]|1[0-2])(?:/(0[1-9]|[12]\d|3[01]))?/", u)
    if m:
        return f"{m.group(1)}-{m.group(2)}-{m.group(3) or '01'}"
    m = re.search(r"/(20\d{2})(0[1-9]|1[0-2])/", u)
    if m:
        return f"{m.group(1)}-{m.group(2)}-01"
    return ""


def _块日期(摘要: str, 字段日期: str, url: str = "") -> str:
    """把一个结果块的日期归一成 `YYYY-MM-DD`（取该块里**最晚**的完整日期）。

    只认能确定的日期，取不到返回 `""`（排到最后、不参与时效判断）。
    「截至8月21日」没有年份 → 补当前年；补出来若在未来，说明是去年的（跨年常见）。
    """
    import re
    from datetime import date

    候选: list[str] = []
    for 源 in (字段日期, 摘要):
        for d in _捞日期(源 or ""):
            if re.match(r"^\d{4}-\d{2}-\d{2}$", d):
                候选.append(d)
                continue
            m = re.match(r"^截至(\d{1,2})月(\d{1,2})日$", d)
            if not m:
                continue
            y = date.today().year
            try:
                补 = date(y, int(m.group(1)), int(m.group(2))).isoformat()
                if 补 > date.today().isoformat():
                    补 = date(y - 1, int(m.group(1)), int(m.group(2))).isoformat()
            except ValueError:
                continue
            候选.append(补)
    if 候选:
        return max(候选)
    # 正文/字段都抽不到 → 用 URL 里的年月兜底（精度低但比"无日期"强得多）
    return _URL日期(url)


# ── 「N 家做了某事」≠「共有 N 家」 ────────────────────────────────────────
#   🔴 2026-10-19 前端实测（同一个问题答两次、一次成功一次失败）的**确定性根因**：
#     首轮 Tavily 只搜到《苏州上市公司回购潮》，句中
#     「已有28家苏州A股上市公司实施股份回购」被旧版 `_含总量句` 判成"苏州有 28 家"，
#     → `_需要补搜` 返回 False → **跳过时间锚定补搜** → 模型手里没有任何家数
#     → 只能按规则 18(d) 答"查不到"，还把"28家"当噪音写进答案。
#     第二次因 Tavily 结果不同、恰好首轮就有 238 家那篇，于是答对了。
#   ⇒ 判据必须区分**存量陈述**（有多少家）与**行为陈述**（多少家做了什么）。
_行为词 = ("回购|增持|减持|分红|派现|派息|调研|中标|签约|解禁|质押|停牌|复牌|"
          "涨停|跌停|成交|持股|募资|融资|实施|完成|披露|申报|过会|获评|获批|"
          "参与|受让|收购|并购|重组")
# ⚠️ 存量标志词：N 家**前面**出现它们时，即使后面跟行为词也仍算存量（防误杀）
#   例「上市公司数量达到238家，其中…」—— "数量"已明示是存量。
_存量词 = "数量|总数|家数|规模"


def _全是行为数量(s: str) -> bool:
    """单句里的每个「N 家」是不是**都属于行为陈述**（多少家做了某事）。

    逐个 `N家` 判：`N家` 之后 16 字内出现行为词、且 `N家` 之前 8 字内没有存量标志词
    → 这个 N 不是存量；**只要有一个 N 是存量，整句就仍算总量句**（返回 False）。

    ⚠️ 为什么逐个判而不是整句一刀切：
       「苏州有238家上市公司，其中28家实施回购」这种句子里两个 N 混在一起，
       整句判会因为"实施"把 238 也误杀。
    ⚠️ 为什么不把「上市」放进行为词：`238家上市公司` 的尾巴就是"上市公司"，
       放进去会把所有正常存量句全误杀。
    """
    import re

    位置 = list(re.finditer(r"\d+\s*家", s))
    if not 位置:
        return False
    for m in 位置:
        # ⚠️ 后段**必须在同一分句内**截断：踩过的坑是
        #   「苏州有238家上市公司，其中28家实施回购」—— 238 的后段如果跨过逗号
        #   就会看到后半句的"实施"，把存量 238 也误判成行为数量。
        后段 = re.split(r"[，,。；！？]", s[m.end():])[0][:16]
        前段 = s[max(0, m.start() - 8): m.start()]
        if (re.search(r"(?:" + _行为词 + ")", 后段)
                and not re.search(r"(?:" + _存量词 + ")", 前段)):
            continue
        return False
    return True


def _严格总量句(文: str, 实体: str = "") -> bool:
    """**只认显式存量表述**：「总数/数量/家数/合计/累计/达/共有/拥有/规模 … N 家」。

    两个调用方都要求「宁可漏判、不可错判」：
      · `_需要补搜`：错判 True → 跳过补搜 → 手里没数，只能答"查不到"（本次 bug A）；
      · `[建议采用]` 锚：错判 True → **把错数字直接摆在模型面前**（本次 bug B，危害更大）。

    漏判的代价只是多花一次检索；错判的代价是给出错答案。
    """
    import re

    for s in re.split(r"[。！？；\n]", 文 or ""):
        if 实体 and 实体 not in s:
            continue
        if _全是行为数量(s):
            continue
        if re.search(r"(总数|数量|家数|合计|累计|已达|达到|达|共有|拥有|规模)"
                     r"[^。；\n]{0,25}?\d+\s*家", s):
            return True
    return False


def _含总量句(文: str, 实体: str = "") -> bool:
    """块里有没有**一句话同时**含（实体）与「总数/共有/合计…N 家」。

    ⚠️ 比 `_含总量` 严：`_含总量` 允许"实体在摘要、总量在另一段"（排序用，宽松）；
       但判断"这轮是否已经拿到该实体的当前存量"必须同句 ——
       否则《IPO火爆！江苏全国第二》这种（正文有「截至9月末，江苏A股总数达740家」，
       另有一句提到苏州 11 家）会被误认为"已有苏州总量" → 不补搜 → 答成 740。
    """
    import re

    # ⚠️ 先用严格版过一遍：命中就是铁证，不必再走宽松分支的猜测。
    if _严格总量句(文, 实体):
        return True

    for s in re.split(r"[。！？；\n]", 文 or ""):
        if 实体 and 实体 not in s:
            continue
        # ④【行为陈述】「28家…实施回购」「43家…接受调研」= 多少家做了某事，不是存量总数。
        #   必须放在最前面：否则会先在下面的严格分支里被「已有/共有…N家」命中。
        if _全是行为数量(s):
            continue
        # 宽松分支：中文写法太活（「南京上市公司 125 家」没有"总数"二字）→ 同句「实体 + N家」也算。
        #   两条护栏：
        #   ① 变动量不算存量（新增/减少/退出/退市…）；
        #   ② 列举句不算（「北京59家，上海25家…南京4家」里 3 个以上"家" → 是分项不是总量）。
        if len(re.findall(r"\d+\s*家", s)) >= 3:
            continue
        # ③ 样本/评级/榜单里的"家"不是总量（「从本次苏州194家样本看」实测被误判成总量）
        if re.search(r"(样本|评级|榜单|名单|参评)", s):
            continue
        # ⑤「N 家…上市/挂牌」同样是行为句 ——「前9月，苏州有11家A股公司上市」。
        #   🔴 这个句式 2026-10-19 真实把「11 家」送进了 `[建议采用]`，等于直接喂错答案。
        #   用 `(?!上市公司)` 避开名词：`238家上市公司` 里的"上市公司"是定语，不能误杀。
        if re.search(r"\d+\s*家(?!上市公司)[^，。；\n]{0,14}?(?:上市|挂牌|过会|注册)", s):
            continue
        # ⑥「苏州的 11 家覆盖生物医药…」= **指代前文的分项**，不是存量总数。
        #   🔴 2026-10-19：正是这句让 10-13 的《IPO火爆》被认成"苏州有 11 家"，
        #   进而被 `_时点去重` 当成"最新一组"，把真正的 238(9-30) / 297(8-25) 全删了。
        #   `(的|这|那)` 后**必须紧跟数字**才判："苏州的上市公司总数达238家" 里"的"后是"上市" → 不误杀。
        if re.search(r"(?:的|这|那)\s*\d+\s*家", s):
            continue
        if re.search(r"\d+\s*家", s) and not re.search(
                r"(新增|新上市|减少|退出|摘牌|退市|净增|同比)", s):
            return True
    return False


def _是历史查询(query: str) -> bool:
    """query 里出现**今年以外**的年份 → 历史查询（不做时效干预、不补搜）。"""
    import re
    from datetime import date

    今年 = str(date.today().year)
    return any(y != 今年 for y in re.findall(r"(?:19|20)\d{2}", query or ""))


def _像数量题(query: str) -> bool:
    import re

    return bool(re.search(r"(多少|几家|数量|家数|总数|一共|总共)", query or ""))


def _补搜query(query: str) -> str:
    """把口语问法改写成「带时间锚的总量问法」—— 实测命中率明显高于原问法。

    「苏州多少个上市公司」→「苏州 上市公司 家数 截至 2026年9月」

    🔴 2026-10-19 实测定论：**「总数」这个词会把整个查询打废**。
      旧模板用的「…总数 截至 2026年9月」，实测 8 条结果依次是：
      中国探月与深空探测网 / 安理会主席 / Visa Bulletin / 百达翡丽月相设置 /
      台湾赋税统计 / 外交史上的今天 / 维基词典「月」/ 月兔漫游 —— **全是垃圾，
      一条苏州上市公司的都没有**（等于补搜这一轮白花钱，还往结果里灌噪音）。
      只把「总数」换成「家数」，同一天、同一接口、同样 8 条：
      第 1 条 = 21经济网《2026年9月江苏上市公司发展报告》「截至 2026-09-30，苏州 A股 238 家」；
      第 3 条 = 苏州市政府官网「境内外 297 家 / A股 236 家」。
      **一个词之差，从全废到最优** ⇒ 这个字不要再改回去。
    """
    import re
    from datetime import date

    干净 = re.sub(r"(多少个|多少家|一共有多少|一共|总共|多少)", " ", query or "")
    干净 = re.sub(r"\s+", " ", 干净).strip()
    d = date.today()
    上 = d.month - 1 or 12
    年 = d.year if d.month > 1 else d.year - 1
    return f"{干净} 家数 截至 {年}年{上}月"


def _需要补搜(块们: list[dict], query: str) -> bool:
    """要不要再搜一轮。两个条件**任一**成立就补：

    (1) 首轮里没有近 95 天、含实体的**存量陈述** → 这轮压根没搜到"当前有多少"；
    (2) 有，但**最新那条已经超过 45 天** → 搜到的是旧版，找一版更新的。

    🔴 (2) 是 2026-10-19 补的：用户第二次问时才答出 238 家（2026-09-30），
      而首轮稳定给的是 297/236（2026-08-25，已 55 天）。首轮既然"有存量"就不补搜，
      系统于是**永远停留在 8 月那一版**，和别处看到的 238 对不上。
      量的更新节奏是月报级，45 天能覆盖"本月报还没出"的空窗。
    """
    from datetime import date, timedelta

    实体 = _实体词(query, 块们)
    线 = (date.today() - timedelta(days=95)).isoformat()
    最新 = ""
    for r in 块们:
        文 = (r.get("title") or "") + (r.get("content") or "")
        字段 = (r.get("published_date") or r.get("published_at") or r.get("date") or "").strip()
        d = r.get("_日期") or _块日期(文, 字段, r.get("url") or "")
        if d and d >= 线 and _严格总量句(文, 实体) and d > 最新:
            最新 = d
    if not 最新:
        return True          # (1) 完全没有存量 → 补
    陈旧线 = (date.today() - timedelta(days=45)).isoformat()
    return 最新 < 陈旧线     # (2) 有但太旧 → 也补


def _时效整理(结果: list[dict], query: str) -> tuple[list[dict], str, str, bool]:
    """按发布日期**从新到旧**重排，并把过旧的块折叠掉。

    返回 (排好的块, 最新日期, 折叠说明, 是否历史查询)。

    ⚠️ 为什么必须在服务端做：实测问「苏州多少个上市公司」，Tavily 的**前 5 条全是
       2022~2024 的旧文**（261/217、263、219、267），而真正的官方新页
       「截至 8月21日 297/236」（2026-08-25）排在第 6 条 —— 旧版 `max_results=5`
       **连拿都拿不到**；即便拿到，模型也常被前面那堆旧数字带偏。
       按时点排序 + 折叠过时块，是确定性手段，不依赖模型自觉。

    折叠规则（保守）：
      · query 里写了具体年份（问历史数据）→ **不折叠、不排序干预**，原样返回；
      · 否则丢掉 365 天以前的块，但**剩下的不足 2 条就整体保留**（宁可多给，不可误杀）。
    """
    import re
    from datetime import date, timedelta

    原始 = list(结果)
    for r in 结果:
        字段 = (r.get("published_date") or r.get("published_at")
                or r.get("date") or "").strip()
        摘要 = (r.get("content") or "").replace("\n", " ")
        r["_日期"] = _块日期(摘要, 字段, r.get("url") or "")

    有日期 = [r for r in 原始 if r["_日期"]]
    无日期 = [r for r in 原始 if not r["_日期"]]
    实体 = _实体词(query, 原始)
    词表 = _相关词(query)
    今年 = str(date.today().year)
    年份们 = re.findall(r"(?:19|20)\d{2}", query)
    目标年 = [y for y in 年份们 if y != 今年]

    def _键(r):
        """排序键：实体 > 该实体的总量陈述 > 命中 query 片段数 > 有日期 > 日期，全部降序。

        ⚠️ 三处都踩过坑：
           ① 只用日期排序：《江苏A股总数 740 家》《苏州上市公司密集回购增持》
              《苏州IPO加速 年内已有16家上市》都会被推到第一（省级/无关/新增≠存量）；
           ② 总量陈述用**宽松版**（`_含总量`）时，讲江苏 740 家的文章也算"有总量"，
              于是给「无锡」排到了第一 → **必须用同句实体版** `_含总量句`；
           ③ 不区分"有无日期"时，一篇无日期的 500 强榜单文会凭相关度压过有日期的块
              → 数量题宁可用有日期的。
        """
        文 = (r.get("title") or "") + (r.get("content") or "")
        # 排序维度（降序）：实体 > 严格总量句 > **来源权威性** > 宽松总量句 > 词表 > 有日期 > 日期
        #   ⭐ `_权威分` 插在日期**之前**是本次的核心改动：
        #     官方 297/236（8-25）必须压过媒体 238（9-30），否则又是"媒体覆盖官方"。
        权 = _权威分(r.get("url") or "", r.get("title") or "")
        return (1 if (实体 and 实体 in 文) else 0,
                1 if _严格总量句(文, 实体) else 0,
                权,
                1 if _含总量句(文, 实体) else 0,
                sum(1 for w in 词表 if w in 文),
                1 if r["_日期"] else 0,
                r["_日期"] or "")

    def _键历史(r):
        """历史查询：讲的是**目标年份** > 有总量陈述 > 含实体 > **离目标年份最近**。

        ⚠️ 最后一层不能再用"日期越新越好"：问 2023 年，2026 年的回顾文章只因
           「正文顺带提了一句 2023」就会排到最前（实测就是这么答错的）。
        """
        文 = (r.get("title") or "") + (r.get("content") or "")
        try:
            年 = int((r.get("_日期") or "")[:4])
        except ValueError:
            年 = 9999
        差 = min((abs(年 - int(t)) for t in 目标年), default=9999)
        return (1 if (目标年 and any(y in 文 for y in 目标年)) else 0,
                1 if _含总量句(文, 实体) else 0,
                1 if (实体 and 实体 in 文) else 0,
                -差)

    排好 = sorted(有日期 + 无日期, key=(_键历史 if 目标年 else _键), reverse=True)
    最新 = max((r["_日期"] for r in 原始 if r["_日期"]), default="")

    # 问的是历史（query 里有**今年以外**的年份）→ **按目标年份排序**，不做时效折叠
    #   ⚠️ 两个踩过的点：
    #   ① 历史查询也曾被按日期倒序 → "2023年苏州多少家" 第一条变成 2026 年的，历史题答成当期数；
    #   ② 不能"只要出现年份就当历史" —— "2026年8月苏州多少家" 是**当期**查询，
    #      单纯按 `\d{4}` 判定会把当期题误降到历史分支（不给"用最新"提示）。
    if 目标年:
        return 排好, 最新, "", True

    # ① 同指标多时点 → 只留最新那一组（治本：别让旧时点总量块留在候选里）
    排好, 去重说明 = _时点去重(排好, 实体)
    # ⚠️ 「采用日期」= 排序第 1 块（最该用的那块）的日期，不是全组最大日期。
    #    否则会出现：第 1 块是 297（2026-08-25），但另一篇「苏州新增一家上市公司」
    #    日期更新（2026-10）→ 头部说"最新是 2026-10"，模型转头去用了那篇无关的。
    最新 = next((r["_日期"] for r in 排好 if r["_日期"]), 最新)

    # ② 再折叠一年以前的旧报道
    线 = (date.today() - timedelta(days=365)).isoformat()
    新 = [r for r in 排好 if r["_日期"] and r["_日期"] >= 线]
    旧 = [r for r in 排好 if not (r["_日期"] and r["_日期"] >= 线)]
    说明 = 去重说明
    if len(新) >= 2 and 旧:
        说明 = "；".join(x for x in (说明, (
            f"另有 {len(旧)} 条一年以前的旧报道已省略（问历史数据请在 query 里写明年份）")) if x)
        return 新, 最新, 说明, False
    return 排好, 最新, 说明, False


@mcp.tool(name="web_search")
def 网页搜索(query: str, max_results: int = 8) -> str:
    """搜索互联网上的**最新**信息（新闻、政策、突发事件、行业动态）。

    什么时候该用：
      - 问"最近/今天/最新"的新闻、政策、突发事件；
      - 问行业动态、公司舆情、市场消息 —— 这些**本地数据库里没有**；
      - 问"XX 行业有什么新闻""某项政策说了什么"。

    什么时候不该用：
      - 问公司财务数字（该用 query_financials）；
      - 问公告原文（该用 query_announcements）；
      - 问实时股价（该用 query_realtime_quote）。

    ⚠️ 搜索结果是**媒体报道/观点，不是事实数据**：引用时必须写明**来源站点与日期**，
    并说明它是"消息/观点"；不要把媒体说法当成核实过的财务数据。

    参数：
      - query：搜索关键词（中文即可）。**问「最新/当前/今年」的数据时，query 里带上时间词**
        （如「2026年 苏州 上市公司 数量」），能显著提高命中新版官方页的概率。
      - max_results：返回条数，默认 8（不再是 5 —— 实测最新的官方页常排在第 6 条之后，
        给 5 条会直接漏掉）。结果**已按发布日期从新到旧排好，第 1 条最新**。
    """
    if not _拿key():
        return ("【网页搜索不可用】未配置 TAVILY_API_KEY。"
                "请去 https://tavily.com 注册（每月 1000 次免费），"
                "把 key 写进项目根目录的 .env：`TAVILY_API_KEY=tvly-xxxx`。"
                "这是**配置缺失**，不是「搜不到」 —— 请如实告诉用户。")

    try:
        结果 = _搜(query, max(1, min(int(max_results), 10)))
    except Exception as e:
        return f"【网页搜索失败】{type(e).__name__}: {e}（调用 Tavily 出错，请稍后重试）"

    if not 结果:
        return f"【网页搜索】没有搜到与「{query}」相关的结果。"

    # ⚠️ 补搜兜底：数量题首轮没拿到"近期存量"时，追加一轮带时间锚的检索
    #   实测「苏州多少个上市公司」有 1/6 的概率 Tavily 不返回官方最新页（前 8 条里没有），
    #   那一次无论怎么排序都救不回来 → 只能再搜一次。
    补搜说明 = ""
    if _像数量题(query) and not _是历史查询(query) and _需要补搜(结果, query):
        try:
            额外 = _搜(_补搜query(query), 8)
        except Exception:
            额外 = []
        已有 = {r.get("url") for r in 结果}
        新块 = [r for r in 额外 if r.get("url") and r.get("url") not in 已有]
        if 新块:
            结果 = 结果 + 新块
            补搜说明 = f"｜为拿准当前存量，已追加一轮时间锚定检索（+{len(新块)} 条）"

    # ⚠️ 先把时点摆正：按发布日期倒序 + 折叠一年前的旧块（问历史时不干预）
    结果, 最新日期, 折叠说明, 是历史 = _时效整理(结果, query)
    # 最多给 5 条：剩下的大多是"无日期的名单/百科/监管局表格"，只会干扰判断
    结果 = 结果[:5]

    # ⚠️ 首轮 + 补搜之后**仍然**没有「该对象的存量总数」→ 必须显式告诉模型。
    #   实测（2026-10-19）：首轮只拿到《苏州上市公司回购潮》，模型把
    #   「已有28家苏州A股上市公司实施股份回购」写进答案当成"苏州有28家"的开场，
    #   用户看到的是「关于苏州有多少上市公司，仅找到 28 家实施回购的报道」这种噪音。
    #   ⇒ 缺口要在**工具返回体**里说清，不能指望模型自己判断。
    # ⚠️ 「缺口」= **一条存量句都没有**（不是"存量有点旧"）。
    #   早前这里误用了 `_需要补搜`，而它现在还包含"存量超 45 天也补搜"——
    #   结果 297/236 明明在返回体里，却又同时报「没有检索到存量总数」，自相矛盾。
    缺存量 = (not 是历史) and _像数量题(query) and not any(
        _严格总量句((r.get("title") or "") + (r.get("content") or ""), _实体词(query, 结果))
        for r in 结果)

    # ⚠️ 数量题的时点锚必须落在**真正含存量总数**的那一条上，而不是"发布日期最新"那一条。
    #   🔴 2026-10-19 实测：补搜带进来一篇 2026-10-13 的《IPO火爆！江苏全国第二》，
    #   它日期最新，但通篇只有「苏州 11 家上市」「江苏 740 家」「苏州一市就有 60 家」，
    #   一个「苏州有多少家」的总数都没有。按"最新日期"锚定 → 文案会要求模型
    #   「采用第 1 条那几个数字」→ 直接把 11 家当答案。锚错位置比没锚更危险。
    采用日期 = 最新日期
    if (not 是历史) and _像数量题(query):
        _实体0 = _实体词(query, 结果)
        # ⚠️ 取**排序后第一块**有严格存量句的日期，不是日期最大值。
        #   之前用 max()：官方 297（8-25）排第一、锚说的是它，日期却取到媒体 238（9-30）那条，
        #   → 返回体自相矛盾（文案说"采用 9-30 那组数"，但给出的句子是 8 月的）。
        采用日期 = next((r["_日期"] for r in 结果
                         if r.get("_日期")
                         and _严格总量句((r.get("title") or "") + (r.get("content") or ""), _实体0)), "")

    行 = [f"【网页搜索】「{query}」共 {len(结果)} 条（来源：Tavily）"
          + ("｜按相关性排列（历史查询，未做时效干预）" if 是历史
             else "｜**已按「相关度 + 时点」重排，第 1 条最该采用**")
          + 补搜说明]
    if 采用日期 and not 是历史:
        行.append(
            f"【时点】请采用标注 [时点=采用] 的那一条（发布于 {采用日期}）那一组数字，"
            f"并在答案里写明「截至{采用日期}」；"
            f"其余块（标注 [时点=其他]）的同类数字**不许**与之并排或混用。"
            + ("" if 采用日期 == 最新日期 else
               f"⚠️ 注意：日期最新的那条是 {最新日期}，但它**没有该对象的存量总数**，不要采用它的数字。"))
    elif 最新日期 and 是历史:
        行.append("【时点】query 指定了年份 → 本轮是**历史查询**，"
                  "请取与 query 年份相符的那条，不要用最新日期的数字。")
    if 折叠说明:
        行.append(f"【时效过滤】{折叠说明}")

    实体词 = _实体词(query, 结果)
    锚 = ""
    for i, r in enumerate(结果, 1):
        # ⚠️ 【本地修复 · 时效】必须把**发布日期**带出来 —— 否则模型无法判断哪条更新，
        #    实测就栽在这：问「苏州有多少家上市公司」，检索结果里既有「2025 年末 284 家」
        #    的旧文，也有「截至 2026-08-21 共 297 家」的官方新页，而旧版输出只有标题+链接+摘要，
        #    模型挑了旧文 → 给出 284/229（旧口径），和官方 297/236 对不上。
        日期 = r.get("_日期") or (r.get("published_date") or r.get("published_at")
                                  or r.get("date") or "").strip()
        摘要 = (r.get("content") or "").replace("\n", " ").strip()
        文中日期 = [d for d in _捞日期(摘要) if d != 日期]
        关键 = _关键句(摘要, 实体=实体词)
        # 记下第 1 块里的总量句，稍后提到头部当"建议采用"——
        #   ⚠️ 只从**原文原样摘**，且必须是「实体 + 总量」**同一句**（`_含总量句`）。
        #   踩过：用宽松版 `_含总量` 判断，结果给「无锡」推荐了
        #   「截至9月末，江苏A股公司总数达到740家」—— 把错误答案摆在最显眼的位置。
        # ⚠️ 锚必须用**严格版**，而且要在全部关键句里找第一个命中的 ——
        #   原来取 `关键[0]` 且用宽松判据，实测把「前9月，苏州有11家A股公司上市」
        #   当成了"苏州有 11 家"，并以「建议采用」的名义摆在返回体最显眼处。
        if i == 1 and 关键:
            for _k in 关键:
                if _严格总量句(_k, 实体词):
                    锚 = _k
                    break
        标记 = ""
        if 是历史:
            标记 = f"  [日期={日期}]" if 日期 else ""
        elif 采用日期 and 日期:
            标记 = "  [时点=采用]" if 日期 == 采用日期 else "  [时点=其他]"
        # 来源级别直接摆在标题后面：官方 > 媒体。数量题的最终取数由它决定（见 `_权威分`）。
        _权 = _权威分(r.get("url") or "", r.get("title") or "")
        权标 = "  [权威=官方]" if _权 >= 3 else ("  [权威=媒体]" if _权 == 2 else "")
        行.append(f"\n{i}. {r.get('title', '(无标题)')}{标记}{权标}")
        行.append(f"   发布日期：{日期 or '未标注（正文里若有「发布日期/截至…」以正文为准）'}")
        if 文中日期:
            行.append(f"   正文中的日期（按出现顺序，**越靠后通常越旧**）：{'、'.join(文中日期)}")
        行.append(f"   来源：{r.get('url', '(无链接)')}")
        行.append(f"   摘要：{摘要[:600]}{'…' if len(摘要) > 600 else ''}")
        if 关键:
            行.append("   关键句（含数字的句子，**数量类答案优先从这里取**）：")
            for k in 关键:
                行.append(f"     · {k}")
    if 锚:
        for _i, _ln in enumerate(行):
            if _ln.startswith("\n1."):
                行.insert(_i, f"【建议采用】{锚}"
                               f"（时点 {采用日期}，出自原文，请原样引用并注明来源）")
                break

    if 缺存量:
        行.append("\n🔴【本轮缺口 · 必读】没有检索到该对象的**当前存量总数**。"
                  "上面出现的任何「N 家」都是回购/增持/调研/新增等**行为类数量**，"
                  "**严禁**把它们当成「一共有多少家」回答，也**严禁**在答案里把它们"
                  "当成与问题相关的信息来铺垫（那是检索噪音，不是你找到的答案）；"
                  "按规则 18(d) 如实回答「已检索但未取得权威总量数据」，"
                  "并说明这是**数据缺口**，不是本系统不支持该类问题。")

    行.append("\n⚠️ 以上是**媒体报道/观点**，引用时请标注来源站点；不是核实过的财务数据。"
              "\n⚠️ 若问的是**数量/总量/最新时点数据**：**先比来源权威（官方 > 媒体）、再比发布日期**，"
              "只取一条来源的那一组数，写明「截至 YYYY-MM-DD」；"
              "**官方口径即使早一两个月，也优先于媒体的新数字**。"
              "\n⚠️ 数字必须**整组照抄同一条来源的同一个时点**，不许把不同来源/不同时点的数拼在一起。")
    return "\n".join(行)


