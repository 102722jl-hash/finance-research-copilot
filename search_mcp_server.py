# search_mcp_server.py —— v5 第 13 讲任务 2：把 **网页搜索** 包成一个独立 MCP server
#
# 【为什么独立成一个 server（而不是塞进 `投研工具集`）】
#   ① **依赖隔离**：Tavily 需要 API Key + 要走外网。它挂了不该拖垮本地那三个工具；
#   ② **可插拔**：不想用 Tavily 了，把 `mcp_client.配置` 里这一条删掉即可，
#      `graph.py` / `tools.py` 一行都不用改（这是 v5 第 3 讲"可插拔"的兑现）；
#   ③ **零项目依赖**：本文件不 import 项目里任何模块 —— 干净、可单独复用。
#
# ⚠️⚠️ 【stdio 传输的第一天坑】⚠️⚠️
#   stdio 模式下 **stdout 是 JSON-RPC 的协议通道**，本文件里**绝对不能 print()**
#   （任何一行 print 都会冲乱协议，且报错会飘到客户端极难定位）。
#   日志一律走 stderr。第三方库（tavily 及其依赖）若往 stdout 写东西，
#   这里用 `redirect_stdout(sys.stderr)` 挡住 —— **同样的坑不能踩第三次**。
#
# 【API Key】
#   走环境变量 `TAVILY_API_KEY`，由 `config._load_env()` 从项目根目录的 `.env` 读入。
#   没配就明确报"未配置"，**绝不假装搜到了**（假装有结果 = 编造，这是本项目一直防的事）。

