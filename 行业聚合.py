# 行业聚合.py —— v5 第 15 讲：行业级（跨公司）聚合工具
#
# 【它补的是哪个洞】
#   v5-10 起，分诊会把"家电行业平均毛利率""钢铁行业营收合计"这类问题放进 D 通道（概念/主题），
#   但 D 通道拿不到数据，只能给通用知识 —— 因为**现有工具全是单公司口径**：
#   `查财务指标` 一次只查一家，`市场工具` 是行情不是财务。
#   于是"行业级聚合"一直挂在遗留清单里。本文件把它补上。
#
# 【两个数据来源，各管一半】
#   ① **"行业里有谁"** = `fr<行业>_history` 表（申万一级行业，28 个）。
#      ⚠️ 之前以为库里没有"股票→行业"的归属表（`fr_industry_raw_cells` 是空表），
#         实际上 `fr<行业>_history` 的头两列就是 `股票代码 / 股票简称` —— 归属关系一直在，
#         只是藏在一堆"行业打分表"里，需要专门去找。
#   ② **"每家的数是多少"** = 三大报表（`ashareincome_*` / `asharebalancesheet_*` / `asharecashflow_*`），
#      指标翻译**复用 `tools.py::翻译指标()`** —— 绝不自己再抄一份，
#      否则"单公司查走白名单、行业查走字典"，两处口径迟早漂移。
#
# 【财务逻辑上的三个坚持（这不是技术问题，是建模问题）】
#   1. **比率类不能"把比率加起来"**：行业毛利率 ≠ 各家毛利率的算术平均
#      （会被小公司拉偏，且忽略了规模）。所以：
#        · 绝对量（营收/资产/净利润…）→ 给 **合计 / 均值 / 中位数**；
#        · 比率类（带 %）→ 只给 **均值 / 中位数**，并且**明确标注"成员简单平均，非行业加权"**。
#      宁可少给一个数，也不给一个"看着像但对不上口径"的数。
#   2. **默认给中位数**：行业里常有极端值（一家巨亏把均值拉穿），中位数更稳。
#   3. **口径必须写在返回体里**：本库是**母公司（个别）报表**，行业合计与公开合并数不可比。
#
# 【诚实边界】
#   · 成员表最大 521 行 → `机械设备`/`电子` 这类大行业**可能被截断**（知道就写出来）；
#   · 只覆盖 28 个**申万一级**行业，不认"板块"（概念板块没有财务归属）；
#   · 一次只算**一个指标、一个报告期**。
#
