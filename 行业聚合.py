def 可用行业(cur) -> list[str]:
    """列出库里真实存在的行业（从 `fr<行业>_history` 表名反推）。"""
    cur.execute(
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema=%s AND table_name LIKE %s ORDER BY table_name",
        # ⚠️ 别在 LIKE 里用 `\_` 转义下划线 —— 本机 sql_mode 下它会一路转义成
        #    `\\_`（字面反斜杠 + 任意字符），**一条都匹配不到**（踩过）。
        #    改用最朴素的 `fr%history`，再在 Python 里精确判后缀。
        (DB_NAME, 行业前缀 + "%" + 行业后缀),
    )
    出 = []
    for (t,) in cur.fetchall():
        if not t.endswith(行业后缀):
            continue
        名 = t[len(行业前缀):-len(行业后缀)]
        if 名 and not 名.startswith("_"):     # 排除 fr_industry_raw_cells 这类
            出.append(名)
    return 出


def _归一行业(行业: str, 可选: list[str]) -> str | None:
    """把用户说的行业名归一成库里真实的行业名。

    ⚠️ 这一步是**省一次失败往返**用的，不是"猜"：只有**明确唯一**时才归一，
    否则返回 None 让调用方列出可用行业。
      ① 精确命中 → 直接返回；
      ② 常见口语别名（"家电"→"家用电器"、"军工"→"国防军工"）；
      ③ 唯一的前后缀包含（"医药"→"医药生物"）。
    """
    名 = (行业 or "").strip()
    if 名 in 可选:
        return 名
    # 去掉"行业/板块"这类后缀（用户会说"钢铁行业""电子板块"）
    for 尾 in ("行业", "板块"):
        if 名.endswith(尾):
            短 = 名[:-len(尾)]
            if 短 in 可选:
                return 短
            名 = 短
            break
    if 名 in 可选:
        return 名
    别名 = {
        "家电": "家用电器", "医药": "医药生物", "食品": "食品饮料", "饮料": "食品饮料",
        "有色": "有色金属", "化工": "基础化工", "建材": "建筑材料", "建筑": "建筑装饰",
        "军工": "国防军工", "石化": "石油石化", "农业": "农林牧渔", "农牧": "农林牧渔",
        "轻工": "轻工制造", "纺服": "纺织服饰", "纺织": "纺织服饰",
        "新能源": "电力设备", "半导体": "电子", "软件": "计算机", "互联网": "传媒",
        "通讯": "通信", "交运": "交通运输", "商贸": "商贸零售", "零售": "商贸零售",
        "地产": "房地产",
    }
    if 名 in 别名 and 别名[名] in 可选:
        return 别名[名]
    命中 = [t for t in 可选 if t.startswith(名) or t.endswith(名) or 名 in t]
    return 命中[0] if len(命中) == 1 else None


def _取成员(cur, 行业: str) -> tuple[str, list[tuple[str, str]]]:
    """返回 (成员表真名, [(wind_code, 股票简称)])。表的头两列就是 股票代码 / 股票简称。"""
    cur.execute(
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema=%s AND table_name=%s LIMIT 1",
        (DB_NAME, f"{行业前缀}{行业}{行业后缀}"),
    )
    r = cur.fetchone()
    if not r:
        raise KeyError(行业)
    表 = r[0]
    # ⚠️ 成员表是"Excel 导出形"：后面有大量空行（股票代码 = '0'），
    #    所以必须过滤掉 —— 不过滤就会把空行当成"0 家公司"混进样本。
    cur.execute(f"SELECT 股票代码, 股票简称 FROM `{表}` "
                f"WHERE 股票代码 LIKE %s", ("%.%",))
    return 表, [(a, b) for a, b in cur.fetchall() if a]


def _报告期(cur, 表: str, 年份: int) -> int | None:
    期 = int(f"{年份}1231") if 年份 else None
    if 期:
        return 期
    cur.execute(f"SELECT MAX(report_period) FROM `{表}` WHERE report_period LIKE %s", ("%1231",))
    r = cur.fetchone()
    return int(r[0]) if r and r[0] else None


def _中位数(xs: list[float]) -> float:
    s = sorted(xs)
    n = len(s)
    if n == 0:
        return 0.0
    m = n // 2
    return s[m] if n % 2 else (s[m - 1] + s[m]) / 2


def _亿(v: float) -> str:
    """元 → 亿元（展示层换算；库里存的始终是元）。"""
    return f"{v / 1e8:,.2f} 亿元"


@tool
def 行业聚合(行业: str, 指标: str, 年份: int = 0, 口径: str = "中位数") -> str:
    """把**同一行业的多家公司**的某个财务指标聚合成行业级数字（合计 / 均值 / 中位数）。

    何时该用：问**整个行业**的财务情况 —— "钢铁行业营业收入合计多少""医药生物行业的
      平均毛利率""家电行业的总资产规模""煤炭行业净利润中位数"。
    何时不该用：问**单家公司**（用 `查财务指标`）；问**行情/涨跌幅**（用 `查板块`）；
      问"哪个行业涨得好"（那是行情，不是财务）。

    参数：
      - 行业：**申万一级行业名**，如 "钢铁" / "医药生物" / "电子" / "食品饮料"。
        （库里共 28 个行业，具体名单见"可用行业"报错提示。）
      - 指标：中文指标名，支持三大报表 400+ 科目与派生指标，与 `查财务指标` **同一套翻译**。
      - 年份：报告期年份（如 2025）；不填取最新一期**年报**。
      - 口径：想看哪个（合计 / 均值 / 中位数 / 加权，默认中位数）。**能算的都会列出来**，
        这个参数只标"采用"。

    ⚠️ 返回体里的**口径说明必须一起转述**：
      · 比率的"均值/中位数"是**成员简单平均**（每家一票，小公司会拉偏）；
      · "加权" = **Σ分子 ÷ Σ分母**（按规模加权，等于行业真实水平，如 毛利率的加权 =
        Σ(收入−成本) ÷ Σ收入）。**两者不是一个东西**，回答时必须说清用的是哪个；
      · 只有定义了分子/分母的比值（毛利率 / 净利率 / 资产负债率）才有加权口径；
      · 本库是**母公司（个别）报表**，行业合计与公开（合并报表）口径**不可直接对照**。
    """
    行业 = (行业 or "").strip()
    指标 = (指标 or "").strip()
    口径 = (口径 or "中位数").strip() or "中位数"
    if not 行业 or not 指标:
        return "请同时给出**行业**与**指标**（例：行业=钢铁，指标=营业总收入）。"

    # ── ① 翻译指标（复用 tools.py 的唯一入口）──
    tr = 翻译指标(指标)
    if not tr["ok"]:
        return tr["错误"]
    表前缀, 取数式, is_expr = tr["表前缀"], tr["取数式"], tr["is_expr"]
    语义注 = tr["语义注"]

    # ⭐ v5-16：这条指标能不能算**加权口径**？（= 有 分子/分母 定义）
    #   用 expr 反查，所以"销售毛利率"这类别名也能自动享受到加权，不必维护别名表。
    比值名 = 由算式找比值(取数式, is_expr)
    规格 = 可加权比值.get(比值名) if 比值名 else None

    try:
        conn = _连()
    except Exception as e:
        return (f"数据库连接失败（{type(e).__name__}），暂时算不了行业聚合。"
                f"请稍后重试，或确认本机 MySQL 服务已启动。")
    try:
        with conn.cursor() as cur:
            # ── ② 行业成员（先归一行业名，省一次失败往返）──
            可选 = 可用行业(cur)
            真行业 = _归一行业(行业, 可选)
            if 真行业 is None:
                return (f"认不出行业「{行业}」。可用行业（共 {len(可选)} 个，申万一级）："
                        + "、".join(可选))
            try:
                成员表, 成员们 = _取成员(cur, 真行业)
            except KeyError:
                return (f"库里没有行业「{真行业}」的成员表。可用行业："
                        + "、".join(可选))
            行业 = 真行业

            真表 = _找真表名(cur, 表前缀)
            if 真表 is None:
                return f"库里找不到「{表前缀}」系列的表"

            期 = _报告期(cur, 真表, 年份)
            if not 期:
                return f"取不到「{指标}」的报告期"

            # ⭐ 2026-10-20：**行业级也要先比覆盖区间** —— 用户截图的正是这条路径。
            #   0/45 有两种完全不同的原因，必须分开说：**库不覆盖这一年** vs **公司真没披露**。
            if 年份:
                区 = 覆盖区间(cur, 真表)
                if 区 and 期 and (期 < 区[0] or 期 > 区[1]):
                    # 🔴 2026-10-20 二改：**这句原来只让人"逐家自己查"，等于发放弃许可**。
                    #   实测后果：模型读到就停下，只查一两家龙头、或反问"需要我逐家查吗"。
                    #   现在必须**指向真正能换的那把工具**（行业级公开财报聚合）。
                    return (f"【超出本库覆盖范围】{行业}行业 · {年份}年报 —— "
                            f"本库只有 {_期名(区[0])} ~ {_期名(区[1])} 的数据，"
                            f"**不含 {年份} 年**。\n"
                            f"⚠️ 这不是「成员公司都没披露」—— 是**本库没有收这一年**"
                            f"（实测：整张表 report_period 只到 {区[0]} ~ {区[1]}）。\n"
                            f"👉 **换工具**：调用 `query_industry_public_financials"
                            f"(行业=\"{行业}\", 指标=\"{指标}\", 年份={年份})` —— "
                            f"它取**行业成员 + 逐家公开合并报表**后汇总，能给出该行业的"
                            f"合计/均值/中位数（比率类还含加权），实测可回溯到 1997 年。\n"
                            f"⚠️ 必须转述它返回的两条限制：① **合并报表口径**（≠本库母公司个别报表）；"
                            f"② 成员是**当前快照** → 历史年份有**幸存者偏差**（已退市的当年成员不在内）。"
                            f"**不要**只查一两家龙头当作行业情况，**也不要**反问用户要不要逐家查 —— "
                            f"该工具会自己做完。")

            # ── ③ 一条 SQL 取全行业（不逐家公司查 40 次）──
            select_col = 取数式 if is_expr else f"`{取数式}`"
            码们 = [c for c, _ in 成员们]
            占位 = ",".join(["%s"] * len(码们))
            sql = (f"SELECT wind_code, {select_col} FROM `{真表}` "
                   f"WHERE wind_code IN ({占位}) AND report_period=%s")
            cur.execute(sql, (*码们, 期))
            行 = cur.fetchall()

            # ── ③-b 【v5-16】加权口径：取**分子/分母的原始字段**，跨公司各自求和后再相除 ──
            #   ⚠️ 绝不能拿"格式化后的比率"去加权 —— 那样只能得到简单平均。
            #   ⚠️ 只保留"分子分母**都**有值"的公司：否则 Σ分子 与 Σ分母 覆盖的样本不同，
            #      相除出来的口径是混的（这是加权最容易悄悄错的地方）。
            加权样本: list[dict] = []
            加权分子 = 加权分母 = 0.0
            if 规格:
                字段们 = list(dict.fromkeys([f for f, _ in 规格["分子"] + 规格["分母"]]))
                cols = ", ".join(f"`{f}`" for f in 字段们)
                cur.execute(f"SELECT wind_code, {cols} FROM `{真表}` "
                            f"WHERE wind_code IN ({占位}) AND report_period=%s", (*码们, 期))
                for r2 in cur.fetchall():
                    d = dict(zip(字段们, r2[1:]))
                    if any(d.get(f) is None for f in 字段们):
                        continue
                    加权样本.append(d)
                for d in 加权样本:
                    加权分子 += sum(s * float(d[f]) for f, s in 规格["分子"])
                    加权分母 += sum(s * float(d[f]) for f, s in 规格["分母"])
    except Exception as e:
        return (f"聚合「{行业}·{指标}」时出错（{type(e).__name__}: {e}）。"
                f"这多半是本机数据库的问题，不是数据本身没有 —— 请如实告知用户查询失败。")
    finally:
        conn.close()

    样本: list[tuple[str, float, str]] = []
    for 码, 值 in 行:
        if 值 is None:
            continue
        if isinstance(值, str):
            try:
                数 = float(值.rstrip("%"))
            except ValueError:
                continue
            是比率 = 值.strip().endswith("%")
        else:
            数 = float(值)
            是比率 = False
        样本.append((码, 数, "比率" if 是比率 else "数额"))

    有值 = len(样本)
    是比率 = bool(样本) and all(s[2] == "比率" for s in 样本)
    数们 = [s[1] for s in 样本]

    行 = [f"【行业聚合】{行业}行业 · {str(期)[:4]} 年报 · 「{指标}」{语义注}",
          f"成员来源：`{成员表}`（申万一级行业）｜ 表内有效成员 {len(成员们)} 只 "
          f"｜ 本期有值样本 {有值}/{len(成员们)}"]

    if 有值 == 0:
        # ⚠️ 2026-10-20 改：原话「可能是该指标在这些公司里普遍为空，或报告期不对」是**假二分**。
        #   能走到这里说明**报告期确实在库覆盖区间内**（越界已在上面拦掉），
        #   所以"报告期不对"不成立；而"普遍为空"也应给出可执行的下一步，而不是让用户干猜。
        行.append(f"⚠️ 本期（{_期名(期)}，在本库覆盖区间内）没有任何成员取到「{指标}」的数值。"
                  "可能是该科目在报表里普遍为空（如小公司不披露细项），或本库这一期该字段未采集。")
        行.append("👉 建议：① 换一个更常见的科目（如「营业总收入」「资产总计」）再试；"
                  "② 若要**公开合并报表口径**，用 `query_public_financials` 对个别成员公司核对。")
        行.append(f"数据源：本机 MySQL workspace（{真表} + {成员表}）")
        return "\n".join(行)

    行.append("口径：")
    if not 是比率:
        合计 = sum(数们)
        行.append(f"  · 合计   = {_亿(合计)}"
                  + ("   ← 采用" if 口径 == "合计" else ""))
    else:
        行.append("  · 合计   = （**比率类不给合计** —— 把各家的比率加起来没有意义）")
    均值 = sum(数们) / 有值
    中位 = _中位数(数们)
    if 是比率:
        行.append(f"  · 均值   = {均值:.2f}%   （成员**简单平均**）"
                  + ("   ← 采用" if 口径 in ("均值", "简单平均") else ""))
        行.append(f"  · 中位数 = {中位:.2f}%" + ("   ← 采用" if 口径 == "中位数" else ""))
        # ⭐ v5-16：加权口径（Σ分子 ÷ Σ分母）—— 只有定义了分子/分母的比值才给
        if 加权样本 and 加权分母:
            加权值 = 加权分子 / 加权分母 * 100
            行.append(f"  · 加权   = {加权值:.2f}%   （**Σ分子 ÷ Σ分母**：先把各家的分子、分母"
                      f"分别求和再相除；口径 = {比值名}）"
                      + ("   ← 采用" if 口径 == "加权" else ""))
            行.append(f"      ↳ 简单平均 {均值:.2f}% 与加权 {加权值:.2f}% "
                      f"{'一致' if abs(均值 - 加权值) < 0.01 else f'相差 {加权值 - 均值:+.2f} 个百分点'}"
                      f"（简单平均会被小公司拉偏，**加权才等于行业真实水平**）")
            行.append(f"      ↳ 加权口径的有效公司 {len(加权样本)}/{len(成员们)}"
                      f"（要求分子分母**同时**有值，故可能少于简单平均的 {有值} 家）")
        elif 规格:
            行.append("  · 加权   = （本期算不出：没有任何成员**分子分母同时有值**）")
    else:
        行.append(f"  · 均值   = {_亿(均值)}" + ("   ← 采用" if 口径 == "均值" else ""))
        行.append(f"  · 中位数 = {_亿(中位)}" + ("   ← 采用" if 口径 == "中位数" else ""))

    if len(成员们) >= 成员表容量:
        行.append(f"⚠️ 成员表已满 {成员表容量} 行（行业过大，**可能被截断**）—— "
                  f"该行业的成员数很可能不止 {len(成员们)} 只，结论只能当**下界**看。")
    行.append("⚠️ 口径说明：本库为**母公司（个别）报表**，行业合计/均值与公开（合并报表）"
              "口径**不可直接对照**。")
    if 是比率:
        行.append("  · 「均值/中位数」= **成员简单平均**（每家一票，小公司会拉偏）；"
                  "「加权」= **Σ分子 ÷ Σ分母**（按规模加权，等于行业真实水平）。"
                  "两者**不是一个东西**，转述时必须说清用的是哪个。")
        if 规格:
            行.append(f"  · 本指标有加权定义（口径 = {比值名}）；"
                      "加权口径**跨的是同一张表**，与简单平均用的是同一条指标定义。")
    else:
        行.append("  · 绝对量的「合计」才是「行业总规模」；「均值/中位数」是**成员简单平均**，"
                  "大公司一家就能把均值抬高，看行业规模请用「合计」。")
    行.append(f"数据源：本机 MySQL workspace（{真表} + {成员表}，报告期 {期}）")
    # ⭐ v5-22：**成分股快照偏差**（体检第 3 条）
    #   成员表 `fr<行业>_history` 存的是**当前**成分股名单，没有时点维度。
    #   查 2020 年的行业数据时，用的是今天这个名单：
    #     · 当年在、后来退市的公司 → 不在名单里（漏）
    #     · 当年没上市、后来上市的 → 在名单里（多）
    #   这就是财务研究里的**幸存者偏差**，会让历史行业均值/合计系统性偏离。
    #   数据层面无法补救（库内没有历史成分表），所以**必须在返回体里明说**，
    #   至少让模型转述时把这条限制带出去，而不是把一个带偏差的数当成事实。
    if 期 and str(期)[:4] != str(__import__("datetime").date.today().year):
        行.append("⚠️ 成分股说明：行业成员取自成员表的**当前快照**（无历史时点版本）。"
                  f"查 {str(期)[:4]} 年的数据时，已退市的公司不在内、后来上市的公司在內 —— "
                  "存在**幸存者偏差**，与当年真实行业口径会有出入，转述时请一并说明。")
    return "\n".join(行)


