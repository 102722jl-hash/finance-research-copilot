    "请遵守："
    "(a) 开头标注【通用知识】或【公开资讯】，并说明**不含本系统的实时数据**、不构成投资建议；"
    "(b) 概念题直接用通用知识简明解释；行业主题题给出**结构性/概念性描述**（如产业链环节、"
    "竞争要素、技术路线），**不要编造具体的市场规模、增速、份额等数值** —— 这些必须有数据源，"
