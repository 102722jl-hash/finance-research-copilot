# v5 第 5 讲：四个新节点
#   1. 分诊      —— 图的最开头，定通道（全流程唯一让 LLM 做判断的地方）
#   2. 拒答      —— C 通道的终点：不是"不回答"，是"回答我为什么答不了"
#   3. 认输      —— 轮数护栏触发时的终点
#   4. 溯源      —— 图的最末尾，逐条核对答案里的数字有没有出处
# ══════════════════════════════════════════════════════════════
def _最后用户问题(state: AgentState) -> str:
    """本轮的用户问题。分诊要用它，溯源也要用它（用户说过的数字不算编造）。"""
    for m in reversed(state["messages"]):
        if isinstance(m, HumanMessage):
            return m.content or ""
    return ""


def 分诊节点(state: AgentState) -> dict:
    """定通道。**只分类，不生成答案** —— 这是全流程唯一允许 LLM 做判断的地方。

    ⚠️ 为什么不在 call_model 里顺带做？因为"决定怎么答"和"答"是两件事：
      混在一起之后，模型会在"要不要拒答"上犹豫，于是既不拒也不约束地乱答。
      拆开之后，通道一旦定了，后面每一步都是确定性的。
    """
    结果 = 分诊(_最后用户问题(state))
    # ⚠️ 2026-10-20：「短追问 → 域外」的兜底已经下沉到 `guard.分诊()` 里
    #   （`_像追问`）。放那里的理由：`真实流量评测.py` 是**纯规则**跑批、不起服务，
    #   规则若只写在图节点里，那套 1410 条的真实流量评测就量不到它的效果。
    # v5-16：C 通道里还要再分「越界」与「域外」—— 两者的拒答话术不同
    #   （越界=不给建议/预测；域外=这问题不属于本系统）。用 `子类` 透传，缺省回退 "C"。
    # v5-17：`子类` 也用于 D 通道的「自述」分支（提示词不同），所以一并透传。
    return {"通道": 结果["通道"],
            "通道理由": f"[{结果['判定']}] {结果['理由']}",
            "拒答类别": 结果.get("子类") or "C",
            "子类": 结果.get("子类") or ""}


def 分诊后(state: AgentState) -> Literal["答", "拒"]:
    """条件边：C 通道直接去拒答，不去 call_model（省掉一整轮 LLM + 无意义的工具调用）。"""
    return "拒" if state.get("通道") == "C" else "答"


def 拒答节点(state: AgentState) -> dict:
    """C 通道终点：产出**结构化拒答**。拒答也是一种回答，所以响应率仍是 100%。

    v5-16：C 通道内部再分「越界」与「域外」两种话术（由 `拒答类别` 决定）。
    """
    类别 = state.get("拒答类别") or "C"
    return {"messages": [AIMessage(content=拒绝文案(
        类别, 详情=f"分诊依据：{state.get('通道理由') or '越界'}"))]}


def 认输节点(state: AgentState) -> dict:
    """轮数护栏终点：承认"我查不出来"，而不是继续空转。"""
    # ⚠️ v5-8 修：这里原来数的是 **ToolMessage 条数**，和 v5-7 在 should_continue 里
    #    修过的是同一个口径 bug —— 模型**一轮会并发发多个工具调用**，
    #    数 ToolMessage 会把"1 轮"数成"3 轮"，护栏提前生效。必须数"带 tool_calls 的 AIMessage"。
    # ⚠️ v5-19：口径再统一为 `_本轮轮数`（多轮会话不能跨轮累计）。
    已用 = _本轮轮数(state)
    上限 = 最大工具轮数.get(state.get("通道") or "", 默认最大轮数)
    # ⚠️ v5-10：`详情` 会原样出现在用户看到的文案里（`拒绝文案` 会拼一行「细节：…」），
    #    所以这里也**不能写"未收敛"这种内部术语** —— 它和主文案一样是产品面。
    return {"messages": [AIMessage(content=拒绝文案(
        "轮数上限", 详情=f"已连续查了 {已用} 轮（本通道上限 {上限} 轮），仍没拿到能回答你的数据。"))]}


def 收尾节点(state: AgentState) -> dict:
    """轮数到顶、但**手里已经有工具数据**时的收尾：用已有结果**尽力作答**。

    【为什么需要它（v5-18 修的真 bug）】
      实测「请分析当前 LPR、CPI 数据，结合 A 股近期震荡，判断对权益市场的影响，
      并举例说明 1 家上市公司…」——模型第 1 轮就查到了 LPR、CPI、大盘行情、快讯，
      但整题还含它覆盖不到的部分（任意公司公告 + 主观判断），2 轮上限一到就「认输」，
      文案却说"仍没拿到能回答你的数据" —— **数据被扔了，还对用户说了假话**。
      收尾节点把已拿到的数据用起来：**能答的部分作答 + 明说边界**。

    【和「认输」的分工】
      · 认输  = 查了但**啥也没查到** → 结构化拒答（诚实）。
      · 收尾  = 查到了东西、只是整题没拼完 → 尽力作答（也是诚实）。

    ⚠️ 这里用**不带工具的 `llm`**（不是 `llm_with_tools`）—— 断了它继续查的路，
       逼它基于现有数据收口。产出的答案照常走「复核 → 溯源」两道硬护栏。
    """
    历史 = list(state["messages"])
    # ⚠️ 丢掉"想调工具、但被轮数护栏拦下"的那条 AIMessage(tool_calls)：
    #    它没有配对的 ToolMessage，直接喂给 API 会报"tool_calls must be followed by tool messages"。
    if 历史 and getattr(历史[-1], "tool_calls", None):
        历史 = 历史[:-1]
    指令 = (
        "【收尾作答】你已到达工具调用上限，**禁止再调用任何工具**。"
        "请只依据**上面工具已经返回的数据**尽力回答用户。硬性要求："
        "(1) 能答的部分正常给出，并照常标注数据出处/时点，遵守全部既有的硬性规则；"
        "(2) 若问题里还有你手上数据**覆盖不到**的部分，**明确说明哪一部分回答不了**，"
        "不要假装答了、更不要编造；"
        "(3) 若工具返回里其实没有任何可用数据，就如实说查不到。")
    # ⚠️ 两条踩过的坑，都记在这里，别改回去：
    #   ① 指令必须是**末尾的 HumanMessage**，不能并进 SystemMessage。
    #      实测：并进 SystemMessage → 最后一条是 ToolMessage 时模型判定"工具循环继续"，
    #      直接返回**空内容**（整题变空答案）。作末尾 Human 才正常触发作答。
    #   ② 系统提示只能有**一条**且在开头。拼成 [系统提示, 指令] 两条 SystemMessage →
    #      网关报 "System message must be at the beginning." 400。
    提示 = 系统提示(读偏好(), state.get("通道"), state.get("子类") or "")
    reply = llm.invoke([提示] + 历史 + [HumanMessage(content=指令)])
    return {"messages": [reply]}


# ── 节点：确认（v2 第 2 讲 · 人工介入）──────────────────────
def 确认公司(state: AgentState) -> dict:
    """模型想查一家我们"拿不准"的公司 → 停下整张图，问用户要 wind_code。

    三个要点：
    - `interrupt(问题)` 会**暂停整张图**，把问题交回给调用方；调用方用
      `Command(resume=用户答复)` 再 invoke，图就从**这一行**接着往下跑。
    - 暂停要靠 checkpointer 把现场存下来 —— 所以带 interrupt 的图**必须**挂 checkpointer。
    - 这里**不真去查库**：把用户答复包成一条 ToolMessage **回答掉这次 tool_call**，
      再回到 call_model，让模型拿着新代码重新发起查询（不要在节点里替模型做决定）。
    """
    调用 = state["messages"][-1].tool_calls[0]
    公司 = str((调用.get("args") or {}).get("公司", "")).strip()

    答复 = interrupt(
        f"我不确定「{公司}」是哪家公司（不在 A 股名单里）。\n"
        f"请给它的 wind_code（例如 600019.SH）；直接回车＝放弃这次查询。"
    )
    代码 = str(答复 or "").strip()

    if not 代码:
        内容 = f"用户未能提供「{公司}」的 wind_code，本次查询放弃。请如实告知查不到，不要编数字。"
    else:
        内容 = f"用户确认「{公司}」的 wind_code = {代码}。请用它重新调用 查财务指标。"

    # 用真实的工具名，避免有些接口校验 ToolMessage.name 对不上
    return {"messages": [ToolMessage(content=内容, tool_call_id=调用["id"], name="查财务指标")]}


# ── 护栏第 2 层：硬校验节点（护栏即节点）────────────────────
_百分比 = re.compile(r"\d+(?:\.\d+)?\s*%")
# v3 第 2 讲新增：公告"出处"引用（如"第 12 页"）——用来抓"编造页码"。
_页码引用 = re.compile(r"第\s*\d+\s*页")
# v5 第 1 讲新增：时效性措辞 —— 用来抓"把上一交易日收盘价说成实时价"。
_实时措辞 = re.compile(r"实时|当前价|现价|此时此刻|刚刚|现在股价")
_已声明快照 = re.compile(r"收盘|快照|上一交易日|非交易时段|昨收|未开盘")

def 复核(state: AgentState) -> dict:
    """硬护栏：在回答交给用户之前，检查"数字/出处/时效"的来源。

    三条启发式规则（讲解见讲义）：
      - 规则1（v1）：**回答里有百分比，但工具从没返回过百分比** → 判为模型自算，拦截。
      - 规则2（v3）：**回答里引用了页码，但工具从没返回过任何公告片段** → 判为编造出处，拦截。
        （RAG 接进来之后新增：模型可能"假装"读过年报、顺手编一个"第 12 页"。）
      - 规则3（v5）：**行情工具说"非交易时段"，而回答用了"实时/当前价"却没提"收盘/快照"**
        → 判为把**昨天的收盘价**说成**现在的价格**，拦截。
        （外部证据的护栏：不只查"有没有出处"，还要查"时点说没说对"。）

    - 为什么放在"节点"里：图结构里它就是必经的一站，不靠模型自觉 —— 这是"硬"的意思。
    - 拦截方式：不删原回答，而是**再追加一条 AI 消息**把它盖住（保持 messages 历史可追溯）。
    """
    回答 = state["messages"][-1].content or ""
    工具原文 = "\n".join(m.content for m in state["messages"] if isinstance(m, ToolMessage))
    通道 = state.get("通道") or ""

    # ⭐ v5-17 续：D 通道（概念 / 行业主题 / 系统自述）豁免规则 1。
    #    规则 1 的前提是"回答里的百分比该来自工具"——只对 A/B（数据问答）成立。
    #    D 的回答本就是**通用知识 / 自我介绍**：概念解释里写「一般 15% 以上算优秀」、
    #    自述里写「共 24 个工具」，都不是"模型自算数据"，套规则 1 只会**误拦**。
    if 通道 != "D" and _百分比.search(回答) and not _百分比.search(工具原文):
        return {"messages": [AIMessage(content=(
            "⚠️【护栏拦截】该比率并非工具返回（疑似模型自行计算），按规则不予提供。"
            "请先把该指标下沉到工具（如在 SQL 里算），再来查询。"
        ))]}
    if _页码引用.search(回答) and not _页码引用.search(工具原文):
        return {"messages": [AIMessage(content=(
            "⚠️【护栏拦截】回答引用了公告页码，但工具并未返回过任何公告片段（疑似编造出处）。"
            "请先调用 查公告 检索后再引用，或如实说明未找到。"
        ))]}
    if ("非交易时段" in 工具原文 and _实时措辞.search(回答)
            and not _已声明快照.search(回答)):
        return {"messages": [AIMessage(content=(
            "⚠️【护栏拦截】行情工具已标明当前为**非交易时段**（数据是上一交易日收盘快照），"
            "但回答把它说成了实时/当前价。请改为明确说明数据时点后重答。"
        ))]}
    return {}          # 合规：不改任何东西，图接着去 END


# ── 护栏第 3 层：断言溯源（v5 第 5 讲 · 硬规则）────────────────
def 溯源(state: AgentState) -> dict:
    """图的最后一站：把答案拆成"数值断言"，逐条核对有没有出处。

    和 复核 的分工（这一层是**升级版**，不是重复）：
      - 复核 用的是"回答里有 X、但工具从没返回过 X"的**特征启发式**（百分比 / 页码 / 时效措辞），
        它只能抓这三种**已知**的编造形态；
      - 溯源 是**逐条断言**核对 —— 不管是哪种编造形态，只要这个数字在支撑池里找不到，
        就会被揪出来。覆盖面广得多。

    支撑池 = 工具原文 + 用户本轮问题（用户自己说过的数字不算编造）。

    拦截策略（**分级，避免误伤**）：
      - 存在 |值| >= 硬拦截阈值 的无支撑数字 → 拦截整条回答（金额/市值级别的编造，代价最大）；
      - 只有小数字无支撑                        → 不拦截，但指标照记（多半是序号/条数，误报率高）。

    —— 为什么这一层能叫"硬"？因为它**不含模型**：同样的输入必得同样的判定。
    """
    回答 = state["messages"][-1].content or ""
    if "【护栏拦截】" in 回答 or "【无法回答】" in 回答:
        return {}          # 上游已经拦过 / 这本来就是一条拒答，不重复处理

    # ⭐ v5-17 续：D 通道整体豁免「数值溯源 + 越界关键词」。
    #    这一层的前提是"答案里的每个数字都该来自工具"——只对 A/B（数据问答）成立。
    #    D 是通用知识 / 行业主题 / 系统自述：
    #      · 概念解释的数字（"15% 算优秀"）没有工具出处；
    #      · 自述里「不提供目标价 / 不给建议买入」会被越界关键词**反向命中**
    #        （它说的是**能力边界**，不是**投资建议**）。
    #    对 D 套这一层，净效果只有误拦，所以直接跳过（D 的事实纪律靠提示词 + 【通用知识】标注）。
    if (state.get("通道") or "") == "D":
        return {}

    工具原文 = "\n".join(m.content or "" for m in state["messages"] if isinstance(m, ToolMessage))
    指标 = 评估回答(回答, 工具原文, _最后用户问题(state))

    if 指标["越界命中"]:
        命中 = "、".join(指标["越界命中"])
        # ⭐ 2026-10-20：同「部分降级」—— 「宝钢股份最近有哪些研报？」答案末尾
        #   模型自己加了一句「建议关注」，整条研报清单就被废掉（用户啥也没拿到）。
        #   删掉含越界词的那一句，其余照给；删完没剩多少才走整条拒答。
        剩余, 删句 = 剥离含词句(回答, 指标["越界命中"])
        原长 = len(回答 or "")
        if 剩余 and len(剩余) >= 150 and len(剩余) >= 原长 * 0.5 and len(删句) <= 4:
            return {"messages": [AIMessage(content=(
                剩余
                + f"\n\n> ⚠️ 已移除 {len(删句)} 处**投资建议/价格预测**类表述"
                  f"（{命中}）—— 这类结论没有可验证的正确答案，本系统不提供。"
                  f"其余内容为可核对的数据/事实。"))]}
        return {"messages": [AIMessage(content=拒绝文案("C", 详情=f"回答中检出越界表述：{命中}"))]}

    if 指标["需硬拦数"]:
        样 = "、".join(str(x) for x in 指标["需硬拦样例"])
        率 = 指标["无支撑断言率"]
        详情 = (f"共 {指标['无支撑数']} 个数字找不到出处，其中 {指标['需硬拦数']} 个达到拦截阈值"
                f"（样例：{样}）；无支撑断言率 {率:.0%}")
        # ── 第 3.5 层（2026-10-20）：**部分降级优于整体作废** ─────────────
        #   实测：「分析一下宝钢股份2025年的经营情况」→ 模型写了一整篇分析，
        #   里面夹了 1~2 个自算比率 → 整条被换成「该比率并非工具返回（疑似模型自行计算）」。
        #   用户问经营情况，却只拿到一句**给开发者看的内部话术**，一个数都没有。
        #   ⇒ 能删句就别整篇扔：把含被拦数值的句子删掉，其它有出处的数据照给。
        #   门槛（宁严勿滥）：剩余 ≥150 字、≥原文一半、被删 ≤8 处。
        #     达不到就还是走整条拒答 —— 说明这篇答案的可信部分太少，给了也是误导。
        剩余, 删句 = 剥离含数句(回答, 指标.get("需硬拦") or 指标["需硬拦样例"])
        原长 = len(回答 or "")
        if 剩余 and len(剩余) >= 150 and len(剩余) >= 原长 * 0.5 and len(删句) <= 8:
            return {"messages": [AIMessage(content=(
                剩余
                + f"\n\n> ⚠️ 已移除 {len(删句)} 处**无法对应到任何工具返回**的数值"
                  f"（样例：{样}）—— 它们疑似模型自行计算或编造，本系统不予提供。"
                  f"其余内容均有工具出处。"))]}
        return {"messages": [AIMessage(content=拒绝文案("无出处", 详情=详情))]}

    # ── 第 4 层（v5-21）：同源同组 —— 抓「有出处、但选错了那一个」 ──────────
    #   【为什么前三层抓不到它】
    #     `检查断言` 校验的是**存在性**：297/295/284/236/235 全都在工具原文里
    #     （不同时点、不同来源），所以无支撑断言率 = 0，一层都拦不住。
    #     2026-10-16 的真实事故就是这么漏出去的（答 295/235，官方是 297/236）。
    #   【这一层校验什么】
    #     答案里的**数字** 与 **它自己标注的时点** 必须出自**同一块来源**。
    #     跨块配对 = 把 A 文章的数和 B 文章的日期拼在一起 = 必错。
    #   【为什么敢放在这里硬拦】
    #     判据是纯函数（`关系判据.同源同组`），不含模型；且**拿不准就跳过**
    #     （原文没分块 / 答案没时点 / 引用性旧值 → 不判），只在"能确认"时才拦。
    #     D 通道在函数开头就 return 了，不受影响。
    #   ⚠️ 只判**主口径**（合计/A股家数）：实测过一条假阳性 —— 主答案 297/236 完全正确，
    #      但同段列了「创业板 69 家 / 科创板 59 家」来自另一篇报道，整条被拦。
    #      用户问"有多少家上市公司"，主答案对却因分项连坐，代价大于收益。
    关系意见 = 关系判据.判("同源同组", 答案=回答, 原文=工具原文, 只判主口径=True)
    if 关系意见.startswith("❌"):
        return {"messages": [AIMessage(content=拒绝文案(
            "口径混搭", 详情=关系意见[1:].strip()))]}

    return {}


