tool_node = ToolNode(tools)


# ── 接线（框架结构，已搭好，你不用改）──────────────────────
def build_graph(checkpointer=None, store=None):
    """把图拼起来并 compile。

    参数 checkpointer（v2 第 1 讲新增）：
      - 不传 → None → 图**无记忆**：每次 invoke 都从 START 重来（v1 就是这状态）。
      - 传一个 checkpointer（如 InMemorySaver()）→ 图会把每个超步后的 state 存进
        指定 thread；下次用**同一个 thread_id** 调用时，自动加载上次的 state 接着跑。
      这就是"多轮对话"的底座：会话 = 一个 thread_id。
      ⚠️ v2 第 2 讲起，"确认"节点用了 interrupt —— **没有 checkpointer 就跑不了**
         （暂停时无处存现场）。所以凡是要走人工介入的入口，都要传 checkpointer。

    参数 store（v2 第 3 讲新增）：
      - 跨会话的**长期记忆**（如"用户偏好"）。checkpointer 记的是"一个会话之内"，
        store 记的是"跨会话/跨 thread"。
      - 不传 → 节点里 `get_store()` 返回 None（读偏好自然为空）；传了就在节点里能读写。
    """
    g = StateGraph(AgentState)
    g.add_node("分诊", 分诊节点)      # v5：定通道（图的最开头）
    g.add_node("call_model", call_model)
    g.add_node("tools", tool_node)
    g.add_node("确认", 确认公司)      # v2：人工介入（拿不准的公司 → 问用户）
    g.add_node("复核", 复核)          # 硬护栏第 2 层：特征启发式（三条已知编造形态）
    g.add_node("溯源", 溯源)          # v5：硬护栏第 3 层：逐条断言核对出处
    g.add_node("拒答", 拒答节点)      # v5：C 通道终点（结构化拒答）
    g.add_node("认输", 认输节点)      # v5：轮数护栏终点（治"卡死"）
    g.add_node("收尾", 收尾节点)      # v5-18：超轮但已有数据 → 用已有数据尽力作答

    g.add_edge(START, "分诊")
    # v5：分诊完分流 —— C 通道直接去拒答，不浪费一轮 LLM 和工具调用
    g.add_conditional_edges("分诊", 分诊后, {"答": "call_model", "拒": "拒答"})
    g.add_edge("拒答", END)
    g.add_edge("认输", END)
    # v5-18：收尾产出的答案也要过两道硬护栏（数字照样要溯源）
    g.add_edge("收尾", "复核")

    # 条件边：有 tool_calls 且公司拿不准 → 去"确认"；认得 → 去 tools；
    #        工具轮数超上限 → 已有数据走"收尾"尽力作答、没数据走"认输"；想收尾 → 先去"复核"过护栏
    g.add_conditional_edges(
        "call_model",
        should_continue,
        {"tools": "tools", "确认": "确认", "check": "复核", "认输": "认输", "收尾": "收尾"},
    )
    # 工具跑完 → 回到 call_model，形成"查完再判断、不够再查"的循环（第 3/4 课）
    g.add_edge("tools", "call_model")
    # 问完用户 → 回到 call_model，让它拿着用户给的代码重新发起查询
    g.add_edge("确认", "call_model")
    # 复核 → 溯源 → END（v5：两道硬护栏串联，都过了才把答案交给用户）
    g.add_edge("复核", "溯源")
    g.add_edge("溯源", END)

    return g.compile(checkpointer=checkpointer, store=store)
