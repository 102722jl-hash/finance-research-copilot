# rag_search.py —— 向量检索的"公共底座"：库/嵌入器的进程内缓存 + 证据拼接。
#
# 【本文件现在的定位（v3 第 3 讲整理后）】
#   ⚠️ 本文件**不再提供检索入口**。
#   检索统一走 hybrid_search.检索(查询, 条数, 方式)，四种方式：
#        "向量" | "BM25" | "融合" | "融合重排"
#   这里只留两样**所有检索路都要用**的东西：
#     ① _取库() / _取嵌入器() —— 懒加载 + 进程内缓存（只读、无状态 → 复用安全）
#     ② 拼证据()              —— 把检索结果拼成"给模型看的证据块"（带出处标注）
#
#   为什么单拆出来：hybrid_search（编排）、评测脚本、调试脚本都要用它们；
#   放在最底层、不 import 任何上层模块，谁都能用，也不会绕成环。
#
# 【历史沿革】
#   v3 第 1 讲：本文件曾是"纯向量检索"的主人，有 检索() 和 拼证据()。
#   v3 第 3 讲：检索统一到 hybrid_search 后，检索() 已删除
#              （纯向量那条路现在走 hybrid_search.检索(方式="向量")，功能一样，只是换了门）。

from rag_ingest import 建embedding, 库存目录
from vector_store import 向量库


# ── 进程内缓存 ────────────────────────────────────────────
# Agent 一次问答里可能调好几次"查公告"。每次都重开库(读 5.6MB 文件)+重建嵌入器，纯属浪费。
# ⚠️ 缓存成立的前提：**被缓存的东西不变量**。库只读、嵌入器无状态 → 安全。
#    哪天要往库里写（增量入库在线化），这个缓存就是隐患，得改成"写时失效"或加锁。
_库缓存 = None
_嵌入器缓存 = None


def _取库():
    global _库缓存
    if _库缓存 is None:
        _库缓存 = 向量库(库存目录).打开()
    return _库缓存


def _取嵌入器():
    global _嵌入器缓存
    if _嵌入器缓存 is None:
        _嵌入器缓存 = 建embedding()
    return _嵌入器缓存


# ── 证据格式化（给模型看的样子）──────────────────────────
def 拼证据(命中列表: list[dict]) -> str:
    """把检索结果拼成"给模型看的证据块"（带出处标注）。

    这一步是 RAG 的"G"能被信任的关键：
      模型看到的不是"我搜到的东西"，而是"编号 + 出处 + 原文"，可以逐条引用/核对。
    """
    行 = []
    for i, h in enumerate(命中列表, start=1):
        行.append(
            f"【片段{i}】来源：{h['股票']} {h['文件']} 第{h['页码']}页"
            f"（相似度 {h['相似度']}）\n{h['文本']}"
        )
    return "\n\n".join(行)


if __name__ == "__main__":
    # 自检：库能打开、条数对、嵌入器能出向量
    库 = _取库()
    print(f"向量库：{库.条数()} 条")
    向量 = _取嵌入器().embed_query("宝钢2023年营业总收入")
    print(f"嵌入器：输出 {len(向量)} 维")
    print("检索入口请用：hybrid_search.检索(查询, 条数, 方式)")
