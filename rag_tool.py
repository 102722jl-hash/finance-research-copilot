# rag_tool.py —— v3 第 2 讲：把"检索公告"包成一个 @tool，让 Agent 能自己查公告原文。
#
# 【为什么单独一个文件】
#   Agent 的"能力"= 它手上的工具列表。本项目从此有两类工具，性质完全不同：
#     - tools.py    → 查财务指标：**结构化**数字，走 MySQL，回答"是多少"
#     - rag_tool.py → 查公告    ：**非结构化**原文，走向量库，回答"怎么说的/原文依据"
#   分成两个文件，谁坏换谁，互不牵连。
#
# 【@tool 的三个要点（和 查财务指标 一样）】
#   1. 函数名 = 工具名（模型看到的就是它）；
#   2. docstring = 给模型看的"说明书"，模型**靠它决定什么时候该调用** —— 要写清适用场景；
#   3. 参数带类型注解，模型才知道怎么填。
#
# 【和 查财务指标 的关键差别】
#   查财务指标 有个"公司→代码"的翻译 + 人工确认；查公告的入参就是**一句自然语言问题**，
#   直接丢给检索即可，不需要人工介入。

from langchain_core.tools import tool

# v3 第 3 讲：检索从"纯向量"（rag_search）换成"混合检索+重排"（hybrid_search）。
# 换这一行即可 —— 因为两边的 检索() **返回同一形状**（带 股票/文件/页码/文本/相似度）。
# 这就是"接口不变、实现可换"的好处：工具和图的代码一行都不用动。
from hybrid_search import 检索

# v3 第 3 讲整理：证据拼接统一用 rag_search.拼证据()，不再在本文件里重复写一遍循环。
from rag_search import 拼证据


@tool
def 查公告(问题: str) -> str:
    """在上市公司公告 / 年报原文里做**语义检索**，找回最相关的段落。

    ⚠️ 什么时候该用它（写进 docstring 就是为了让模型判断得准）：
      - 问"公告里怎么说""年报原文""管理层讨论与分析""风险提示""分红方案""这段细节"；
      - 需要**原文依据 / 出处**才能回答的问题。
    ⚠️ 什么时候不该用它：
      - 只要一个标准财务数字（如营业总收入、归母净利润）→ 该用 查财务指标（更快更准）。

    参数：
      - 问题：一句自然语言问题或关键词。如 "宝钢2023年度业绩快报归母净利润"。

    返回若干带出处的片段，每条格式为：
      【片段N】来源：<股票代码> <文件名> 第<页码>页（相似度 x）
      <原文>
    回答引用这些内容时，**必须标出对应的"文件名 第X页"**，方便用户回原文核对。
    """
    命中 = 检索(问题, 条数=5)          # 默认方式 = "融合重排"（向量+BM25 融合 → 交叉编码器精排）
    if not 命中:
        return "公告库里没有检索到相关内容（可能尚未建库，或该公司的公告还没收录）。请如实说明未找到。"
    return 拼证据(命中)


