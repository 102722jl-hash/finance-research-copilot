    参数: dict = field(default_factory=dict)
    断言: list = field(default_factory=list)   # 见 一键回归.py 的 _查断言()
    来源: str = ""               # 期望值来源：[SQL] / [复算] / [标注] / [外部]
    级别: str = "P0"             # P0 / KNOWN
    说明: str = ""               # 为什么是这个期望（给人看的）


