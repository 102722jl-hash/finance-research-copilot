# 金标准集.py —— v5 第 14 讲：这个项目的**回归基线**
#
# 【为什么需要它】
#   到 v5-13 为止，项目里有 20 个测试脚本，但**每个只覆盖自己那一讲**，彼此孤立：
#   `v5_7_回归` / `v5_12_冒烟` / `v5_13_回归` / `v5_guard_test` / `v5_8_自测` …
#   → 改一处（比如 v5-13 重构 `tools.py` 抽出 `查财务数值`）根本不知道该跑哪些。
#   本文件把所有"应有行为"收成**一张表**，由 `一键回归.py` 统一跑。
#
# 【最重要的一条纪律：期望值必须来自**独立路径**】
#   如果期望值是从被测函数自己跑一遍抄回来的，那这个测试**什么都没测** ——
#   它只能证明"代码没变"，不能证明"代码是对的"。
#   所以每条用例的 `来源` 字段必须写清期望值从哪来，只有四类：
#     [SQL]  直接查库（绕过 tools.py 的翻译/匹配层，手写 SQL 拿真值）
#     [复算] 用 Python **另写一遍**公式算（不复用 派生指标.py 的计算路径）
#     [标注] 人工判定（通道归类、该不该拒答、该不该反问 —— 这类没有"自动真值"）
#     [外部] 依赖外部接口（行情/宏观/搜索），**不断言具体数值**，只断言"结构齐不齐"
#           （否则别人跑、别的日子跑，数值必然不同 → 假失败）
#
# 【另一个纪律：题目里**固定年份**，不用"最新"】
#   "最新年报"会随时间漂移（明年就换一期），断言就会假失败。
#   → 能固定就固定（如 2025 年报）。确实只能取"最新"的，就断言结构不锚死数字。
#
# 【级别】
#   P0    必过。红了就是真回归。
#   KNOWN 已知偏差 / 已知边界。红了是"提醒"，不是"新问题"—— 值要人工复核后再动。

from dataclasses import dataclass, field


