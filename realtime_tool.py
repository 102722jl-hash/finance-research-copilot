@tool
def 查实时行情(标的: str) -> str:
    """查 A 股实时行情（价格、涨跌幅、成交量、总市值等），数据来自公开行情接口。

    何时该用：用户问"现在多少钱""今天涨了吗""今天大盘怎么样"这类**时效性问题**。
    何时不该用：问历史某年的财务数字（用 查财务指标）、问公告原文（用 查公告）。

    参数：
      - 标的：公司名（如 "宝钢股份"）、wind_code（如 "600019.SH"）或指数名（如 "上证指数"）。

    返回带数据源与数据时点的文字。⚠️ 非交易时段拿到的是**最近一次快照**（收盘价），
    回答时必须照搬返回里的"数据时点"，不得说成"现在的即时价格"。
    """
    解析 = _解析标的(标的)
    if 解析 is None:
        return (f"认不出标的「{标的}」。请用**公司名**（如 宝钢股份、贵州茅台）、"
                f"**指数名**（{'、'.join(指数映射)}）或 **wind_code**（如 600019.SH）。"
                f"（v5-8 起公司名已支持全市场 A 股。）")
    代码, 显示名 = 解析
    信息 = _取行情(代码)
    if 信息 is None:
        return (f"三个数据源（{'、'.join(名 for 名, _ in 数据源链)}）都没取到 "
                f"{显示名}（{代码}）的行情。可能是网络问题或接口临时抽风，"
                f"请稍后再试 —— 不要凭记忆作答。")
    return _格式化(信息, 显示名 in 指数映射)


