# ③ 三个数据源各自的解析器
#    每个都返回**同一种形状**的 dict（这就是"适配器"模式），
#    上层完全不用关心数据是从哪来的。
# ══════════════════════════════════════════════════════════════
def _从东财(代码: str):
    字段 = ("f43,f44,f45,f46,f47,f48,f57,f58,f59,f60,f86,f116,f117,f168,f169,f170")
    url = (f"https://push2.eastmoney.com/api/qt/stock/get?"
           f"secid={_东财secid(代码)}&fields={字段}")
    原文 = _取文本(url, 来源页="https://quote.eastmoney.com/")
    if not 原文:
        return None
    try:
        数据 = json.loads(原文).get("data")
    except Exception:
        return None
    if not 数据:
        return None
    小数 = 数据.get("f59") or 2
    定 = lambda v: None if v in (None, "-", "") else round(v / (10 ** 小数), 小数)

    return {
        "来源": "东方财富",
        "名称": 数据.get("f58"),
        "代码": 数据.get("f57"),
        "最新价": 定(数据.get("f43")),
        "昨收": 定(数据.get("f60")),
        "今开": 定(数据.get("f46")),
        "最高": 定(数据.get("f44")),
        "最低": 定(数据.get("f45")),
        "涨跌额": 定(数据.get("f169")),
        "涨跌幅": None if 数据.get("f170") in (None, "-") else 数据["f170"] / 100,
        "成交量手": 数据.get("f47"),
        "成交额元": 数据.get("f48"),
        "换手率": None if 数据.get("f168") in (None, "-") else 数据["f168"] / 100,
        "总市值亿": None if 数据.get("f116") in (None, "-") else 数据["f116"] / 1e8,
        "时点": (datetime.fromtimestamp(数据["f86"]).strftime("%Y-%m-%d %H:%M:%S")
                 if 数据.get("f86") else None),
    }


def _从腾讯(代码: str):
    原文 = _取文本(f"https://qt.gtimg.cn/q={_腾讯新浪代码(代码)}", 编码="gbk",
                  来源页="https://gu.qq.com/")
    if not 原文 or "=" not in 原文:
        return None
    正文 = 原文.split("=", 1)[1].strip().strip(';').strip('"')
    段 = 正文.split("~")
    if len(段) < 46 or not 段[1]:
        return None
    数 = lambda i: (None if 段[i] in ("", "-") else float(段[i]))

    return {
        "来源": "腾讯财经",
        "名称": 段[1],
        "代码": 段[2],
        "最新价": 数(3),
        "昨收": 数(4),
        "今开": 数(5),
        "最高": 数(33),
        "最低": 数(34),
        "涨跌额": 数(31),
        "涨跌幅": 数(32),
        "成交量手": 数(6),
        "成交额元": (数(37) or 0) * 10000 if 数(37) is not None else None,   # 腾讯给的是「万元」
        "换手率": 数(38),
        "总市值亿": 数(45),
        "时点": (datetime.strptime(段[30], "%Y%m%d%H%M%S").strftime("%Y-%m-%d %H:%M:%S")
                 if len(段[30]) == 14 and 段[30].isdigit() else None),
    }


def _从新浪(代码: str):
    原文 = _取文本(f"https://hq.sinajs.cn/list={_腾讯新浪代码(代码)}",
                 编码="gbk",
                 来源页="https://finance.sina.com.cn")   # ⚠️ 不加这个 Referer 直接 403
    if not 原文 or "=" not in 原文 or len(原文) < 40:
        return None
    正文 = 原文.split('"')[1] if '"' in 原文 else ""
    段 = 正文.split(",")
    if len(段) < 32 or not 段[0]:
        return None
    数 = lambda i: (None if 段[i] in ("", "-") else float(段[i]))
    最新, 昨收 = 数(3), 数(2)
    涨跌额 = round(最新 - 昨收, 3) if (最新 is not None and 昨收) else None
    涨跌幅 = round((涨跌额 / 昨收) * 100, 2) if (涨跌额 is not None and 昨收) else None

    return {
        "来源": "新浪财经",
        "名称": 段[0],
        "代码": 代码,
        "最新价": 最新,
        "昨收": 昨收,
        "今开": 数(1),
        "最高": 数(4),
        "最低": 数(5),
        "涨跌额": 涨跌额,
        "涨跌幅": 涨跌幅,
        "成交量手": (数(8) or 0) / 100 if 数(8) is not None else None,   # 新浪给的是「股」
        "成交额元": 数(9),
        "换手率": None,          # 新浪这个接口不提供
        "总市值亿": None,
        "时点": f"{段[30]} {段[31]}" if len(段) > 31 else None,
    }


# ⚠️ 顺序是**实测排出来的，不是按名气排的**（知识点 1 的延伸）：
#    东财单次成功率实测只有 ~40%（打 5 次通 2 次），腾讯/新浪接近 100%。
#    所以把**最可靠且字段够全**的腾讯放第一，东财（JSON 最规整、字段最全）放第二，
#    新浪（字段最少，无换手率/市值）兜底。
#    → 工程结论：**选数据源靠实测成功率 × 字段完整度，不靠"谁更官方"。**
数据源链 = [("腾讯财经", _从腾讯), ("东方财富", _从东财), ("新浪财经", _从新浪)]


def _取行情(代码: str) -> dict | None:
    """按顺序问各个源，谁先给出**够用**的数据就用谁。

    ⚠️ 「够用」的标准是实测出来的：**非交易时段东财会把盘中字段全清零**
       （f43/f44/f45/f46 = 0，只剩昨收），而腾讯/新浪仍保留上一交易日的完整 OHLC。
       所以不能"第一个响应成功的源就用"，而要"第一个给出有效最新价的源才用" ——
       否则开盘前你会拿到一条全是 0 的行情，比拿不到还危险（模型会照抄 0）。
    """
    备选 = []
    for 源名, 取数 in 数据源链:
        try:
            信息 = 取数(代码)
        except Exception:
            信息 = None
        if not (信息 and 信息.get("名称")):
            continue
        备选.append(信息)
        if 信息.get("最新价"):        # 有有效最新价 → 够用，不再问下一个（省时间）
            return 信息
    return 备选[0] if 备选 else None


# ══════════════════════════════════════════════════════════════
# ④ 交易时段判断（知识点 2）
#    "实时"这个词在不交易的时候是假的。工具必须自己说清楚现在是什么状态。
# ══════════════════════════════════════════════════════════════
def _行情状态(现在: datetime | None = None) -> str:
    现在 = 现在 or datetime.now()
    if 现在.weekday() >= 5:
        return "休市（周末）"
    hm = 现在.hour * 60 + 现在.minute
    if hm < 9 * 60 + 15:
        return "未开盘（数据为上一交易日快照）"
    if hm < 9 * 60 + 30:
        return "集合竞价中"
    if hm < 11 * 60 + 30:
        return "交易中（早盘）"
    if hm < 13 * 60:
        return "午间休市"
    if hm < 15 * 60:
        return "交易中（午盘）"
    return "已收盘（数据为最近一次收盘快照）"


def _有无(v) -> bool:
    """0 和 None 都算"没有有效值"——行情里的 0 几乎总是"未产生/该源没给"，不是真的 0 元。"""
    return v is not None and v != 0


def _显示(v) -> str:
    return "—" if not _有无(v) else str(v)


def _格式化(信息: dict, 是指数: bool) -> str:
    """把 dict 变成"人话 + 出处 + 时点 + 风险提示"——四样缺一不可。"""
    状态 = _行情状态()
    单位 = "点" if 是指数 else "元"
    行 = [f"【实时行情】{信息['名称']}（{信息['代码']}）",
          f"数据源：{信息['来源']} ｜ 快照时点：{信息['时点'] or '未知'} ｜ 当前：{状态}"]

    非交易 = ("未开盘" in 状态 or "收盘" in 状态 or "休市" in 状态)
    if 非交易:
        行.append(f"⚠️ 非交易时段：以下为最近一次收盘快照（{信息['时点'] or '时间未知'}），"
                  f"**不是当前价格**，回答时必须照搬这个时点。")

    最新, 昨收 = 信息["最新价"], 信息["昨收"]
    if not _有无(最新):
        最新 = 昨收
        行.append("⚠️ 该源在非交易时段不返回盘中字段，最新价一栏用昨收代替。")

    涨跌额, 涨跌幅 = 信息["涨跌额"], 信息["涨跌幅"]
    箭头 = "—"
    if _有无(涨跌额):
        箭头 = "涨" if 涨跌额 > 0 else ("跌" if 涨跌额 < 0 else "平")

    行.append(f"最新价 {_显示(最新)} {单位} ｜ {箭头} {_显示(涨跌额)}"
              f"（{_显示(涨跌幅) if 涨跌幅 is not None else '—'}%）")
    行.append(f"今开 {_显示(信息['今开'])} ｜ 最高 {_显示(信息['最高'])} ｜ "
              f"最低 {_显示(信息['最低'])} ｜ 昨收 {_显示(昨收)}")

    段 = []
    if _有无(信息["成交量手"]):
        段.append(f"成交量 {信息['成交量手']:.0f} 手")
    if _有无(信息["成交额元"]):
        段.append(f"成交额 {信息['成交额元'] / 1e8:.2f} 亿元")
    if _有无(信息["换手率"]):
        段.append(f"换手率 {信息['换手率']}%")
    if _有无(信息["总市值亿"]) and not 是指数:      # 指数的"总市值"没有意义
        段.append(f"总市值 {信息['总市值亿']:.2f} 亿元")
    if 段:
        行.append(" ｜ ".join(段))
    return "\n".join(行)


