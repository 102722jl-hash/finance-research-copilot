# realtime_tool.py —— v5 第 1 讲：给 Copilot 装上"看实时"的眼睛。
#
# 【本讲要解决的根本问题】
#   Agent 的知识 = ① 模型参数知识（冻结）∪ ② 你喂的语料（静态）∪ ③ 工具能取到的。
#   前两层在"编译期"就定死了，**运行时唯一能长的只有第 ③ 层**。
#   所以"想答时效性内容"这个问题，技术上只有一个答案：**给它能取实时数据的工具**。
#
# 【为什么不用 akshare（虽然它更省事）】
#   见讲义对比表。一句话：akshare 是"几百个接口的大礼包"，包厚、出问题难定位；
#   本讲只需要"一个股票现在多少钱"这一件事，用**公开接口 + 零依赖**更快更透明，
#   而且能逼着你亲手处理"外部接口会挂"这个真问题 —— 这才是生产环境的日常。
#
# 【本讲要教的四个真问题（讲义里的知识点）】
#   1. **外部接口不稳定，且"换个 HTTP 客户端"就能天差地别**（本讲最反直觉的实测）：
#      同一个东财 URL，`urllib` 连打 5 次 **0/5 全挂**（RemoteDisconnected），
#      换成 `requests` 打 5 次 **5/5 全通**。风控在按「客户端指纹」过滤。
#      但换成 requests 也**不是万能**：东财单次成功率实测仍只有 **~40%**。
#      → 教训：工具必须「选对 HTTP 客户端 + 重试 + 指数退避 + 多源兜底」，四件事都要。
#      → 更狠的一条：**源要靠实测排序**（见下方 `数据源链`），别按"谁更官方"排。
#   2. **"实时"是个陷阱**：09:30 前、15:00 后拿到的不是实时价，是**上一交易日的收盘快照**。
#      → 工具必须自己判断交易时段，并在返回值里**明确写清数据时点**，否则模型会把
#        "昨天的收盘价"当"现在的价格"说出去。（这就是护栏延伸到外部证据）
#   3. **定标（scaling）**：东财返回的 f43=588 不是 588 元，是 5.88 元（要除以 10^f59）。
#      → 外部数据的"单位"从来不会自己告诉你，必须自己定标，否则差 100 倍。
#   4. **多源兜底要有统一的返回形状**：三个源字段名、单位、编码全不一样
#      （东财 JSON/定标、腾讯 GBK/万元、新浪 GBK/股），但对外必须吐**同一种形状**
#      → 这就是"适配器模式"，上层（格式化 + 工具）完全不用知道数据从哪来。

