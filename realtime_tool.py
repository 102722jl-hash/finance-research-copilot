# ══════════════════════════════════════════════════════════════
# ① 标的 → 各数据源的代码格式（又一次"翻译"，和 tools.py 里那两次动机一样）
#    同一个 600019，三家写法不同：
#      东财 push2 → secid = "1.600019"（1=沪 0=深）
#      腾讯/新浪  → "sh600019"
#    ⭐ v5-8 起：中文名解析交给 stock_names（全市场名单），这里只管"代码→各家格式"。
# ══════════════════════════════════════════════════════════════
指数映射 = {
    "上证指数": "000001.SH", "深证成指": "399001.SZ", "创业板指": "399006.SZ",
    "沪深300": "000300.SH", "科创50": "000688.SH",
}


def _解析标的(标的: str) -> tuple[str, str] | None:
    """把用户给的『标的』统一成一个 wind_code。返回 (代码, 显示名)。

    接受：内置指数名（上证指数）/ 全市场中文公司名（宝钢股份…）/ wind_code（600019.SH）。
    认不出来返回 None —— 让工具走"如实说"兜底，而不是瞎猜一个代码去查。
    """
    标的 = (标的 or "").strip()
    if not 标的:
        return None
    if 标的 in 指数映射:
        return 指数映射[标的], 标的
    代码 = 解析公司(标的)
    if 代码:
        return 代码, 标的
    return None


def _东财secid(代码: str) -> str:
    """600019.SH → 1.600019；000063.SZ → 0.000063。"""
    号, 交易所 = 代码.split(".")
    return f"{'1' if 交易所 == 'SH' else '0'}.{号}"


def _腾讯新浪代码(代码: str) -> str:
    """600019.SH → sh600019；000063.SZ → sz000063。"""
    号, 交易所 = 代码.split(".")
    前缀 = {"SH": "sh", "SZ": "sz", "BJ": "bj"}[交易所]
    return f"{前缀}{号}"


# ══════════════════════════════════════════════════════════════
# ② 取数：requests + 重试 + 指数退避（知识点 1）
#
#    ⚠️ 这里**必须用 requests，不能用 urllib**。实测（见讲义对比表）：
#       同一个 URL：urllib 0/5 全挂、requests 5/5 全通。
#       补 Accept-Encoding / Connection 头都救不了 urllib —— 风控看的是客户端指纹。
#
#    重试 + 退避也不是可选项：外部源会抽风、会限流。退避（0.6s→1.2s→2.4s）
#    既是给对方喘气，也是防止把对方彻底打急之后**直接封你 IP**。
#
#    ⚠️ 另一个实测细节：**每个源的 Referer 要求不一样**。
#       新浪 hq.sinajs.cn 不带 Referer 直接 **403 Forbidden**（实测：无 Referer 403、
#       带 https://finance.sina.com.cn 200）。所以 Referer 不能全局写死一个，
#       必须**跟着源走**。这类"隐性门槛"不看文档、只能靠实打实撞出来。
# ══════════════════════════════════════════════════════════════
_UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
       "(KHTML, like Gecko) Chrome/120.0 Safari/537.36")


def _取文本(url: str, 编码: str = "utf-8", 来源页: str | None = None,
            次数: int = 3) -> str | None:
    """取回原始文本。失败重试，指数退避；全败返回 None（由上层走"如实说"兜底）。"""
    头 = {"User-Agent": _UA, "Accept": "*/*", "Accept-Language": "zh-CN,zh;q=0.9"}
    if 来源页:
        头["Referer"] = 来源页
    for i in range(次数):
        try:
            r = requests.get(url, headers=头, timeout=8)
            if r.status_code == 200:
                r.encoding = 编码          # 新浪/腾讯是 GBK，必须显式指定
                return r.text
        except Exception:
            pass
        if i < 次数 - 1:
            time.sleep(0.6 * (2 ** i))     # 0.6 → 1.2 秒
    return None


